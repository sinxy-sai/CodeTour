# 字符串哈希 + 双哈希值
import sys

BASE = 300
MOD1 = 100000007
MOD2 = 100000009

def get_hash(s):
    h1 = 0
    h2 = 0
    for ch in s:
        x = ord(ch)
        h1 = (h1 * BASE + x) % MOD1
        h2 = (h2 * BASE + x) % MOD2
    return h1, h2


def main():
    N = int(sys.stdin.readline())
    hashes = []
    for _ in range(N):
        hashes.append(get_hash(sys.stdin.readline().strip()))

    hashes.sort()

    ans = 0
    for i in range(N):
        if i == 0 or hashes[i-1] != hashes[i]:
            ans += 1
    sys.stdout.write(str(ans))


if __name__ == '__main__':
    main()


# 思路说明：
#
# 题目要求统计 N 个字符串中有多少个不同的字符串。
# 如果直接比较字符串，思路是把相同字符串合并；如果要练习字符串哈希，
# 就把每个字符串先转换成一个哈希值，再统计不同哈希值的数量。
#
# 为什么可以用哈希：
# 这题的核心需求是“去重”，也就是判断两个字符串是否相同。
# 字符串哈希的做法是给每个字符串计算一个数字签名：
# 相同字符串一定会得到相同哈希值，不同字符串大概率得到不同哈希值。
# 所以可以先把字符串变成哈希值，再对哈希值排序去重。
#
# 哈希函数的核心规则：
#
#     h = (h * BASE + ord(ch)) % MOD
#
# 可以把字符串看成一个 BASE 进制的数字。
# 例如 "abc" 的哈希过程类似于十进制读入数字 123：
#
#     初始 h = 0
#     读入 'a'：h = 0 * BASE + ord('a')
#     读入 'b'：h = ord('a') * BASE + ord('b')
#     读入 'c'：h = (ord('a') * BASE + ord('b')) * BASE + ord('c')
#
# 展开后相当于：
#
#     ord('a') * BASE^2 + ord('b') * BASE + ord('c')
#
# 这样每个字符的值和位置都会影响结果。
# 如果只把字符编码简单相加，"abc"、"bca"、"cab" 可能得到相同结果；
# 但使用 h * BASE + 当前字符，就能把字符顺序也记录进去。
#
# BASE 和 MOD 的作用：
#
# BASE 可以理解成“进制”。常见取值有 131、13331 等。
# MOD 用来限制哈希值大小，避免数字随着字符串长度增长得过大。
# 取模之后可能会出现哈希冲突，也就是不同字符串得到相同哈希值。
#
# 为什么这里用双哈希：
#
# 单个哈希值有冲突风险，所以同时计算两个不同模数下的哈希值：
#
#     (h1, h2)
#
# 只有两个哈希值都相同，才认为两个字符串相同。
# 这样冲突概率会比单哈希低很多。
#
# 排序去重的过程：
#
# 1. 对每个字符串计算哈希值，存入 hashes。
# 2. 对 hashes 排序。
# 3. 排序后，相同哈希值会挨在一起。
# 4. 从前往后扫描，只要当前哈希值和前一个不同，就说明出现了一个新的字符串。
#
# 时间复杂度：
# 设所有字符串总长度为 S，字符串个数为 N。
# 计算哈希 O(S)，排序 O(N log N)，总复杂度 O(S + N log N)。
#
# 注意：
# Python 做双哈希时，每个字符都要做两次取模，常数比较大，可能 TLE。
# 同样思路用 C++ 通常更容易通过。
