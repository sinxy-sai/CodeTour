# 高斯消元法
import sys

def gaussian_elimination(matrix,n):
    EPS = 1e-8

    for col in range(n):
        # 选主元：在当前列找绝对值最大的元素
        pivot_row = col

        for row in range(col+1,n):
            if abs(matrix[row][col]) > abs(matrix[pivot_row][col]):
                pivot_row = row

        # 当前列没有非零主元，说明解不唯一或无解 
        if abs(matrix[pivot_row][col]) < EPS:
            return None

        # 把主元行换到当前行
        matrix[col],matrix[pivot_row] = matrix[pivot_row],matrix[col]

        # 把主元化为1
        pivot = matrix[col][col]

        for j in range(col,n+1):
            matrix[col][j] /= pivot

        #  消去其他行当前列的元素
        for row in range(n):
            if row == col:
                continue

            factor = matrix[row][col]

            if abs(factor) < EPS:
                continue

            for j in range(col,n+1):
                matrix[row][j] -= factor*matrix[col][j]

    # 此时左侧已经化为单位矩阵，最后一列就是解
    ans = []
    for i in range(n):
        value = matrix[i][n]

        if abs(value) < 0.0005:
            value = 0.0
        ans.append(f'{value:.2f}')

    return ans
        


def main():
    input = sys.stdin.buffer.readline

    n = int(input())
    matrix = []
    for _ in range(n):
        row = list(map(int,input().split()))
        matrix.append(row)

    ans = gaussian_elimination(matrix,n)

    if ans is None:
        sys.stdout.write('No Solution')
    else:
        sys.stdout.write('\n'.join(ans))

if __name__ == '__main__':
    main()


# ============================================================
# 高斯消元法：数学理论、算法思路与实现细节
# ============================================================
#
# 一、线性方程组
#
# 本题要求解 n 个未知数、n 个方程组成的线性方程组：
#
#     a11*x1 + a12*x2 + ... + a1n*xn = b1
#     a21*x1 + a22*x2 + ... + a2n*xn = b2
#     ...
#     an1*x1 + an2*x2 + ... + ann*xn = bn
#
# 可以把它写成矩阵形式：
#
#     A * X = B
#
# 其中：
#
#     A：系数矩阵；
#     X：未知数列向量；
#     B：常数列向量。
#
# 例如：
#
#     x + 2y = 5
#     3x + 4y = 11
#
# 对应的增广矩阵是：
#
#     [ 1  2 |  5 ]
#     [ 3  4 | 11 ]
#
# 竖线右边的最后一列保存方程右侧的常数。
#
#
# 二、什么是高斯消元
#
# 高斯消元的目标是通过不断进行行变换，
# 把增广矩阵化为容易直接读出答案的形式。
#
# 本程序采用的是高斯-约旦消元，
# 最终希望得到：
#
#     [ 1  0  0 | x1 ]
#     [ 0  1  0 | x2 ]
#     [ 0  0  1 | x3 ]
#
# 左侧是单位矩阵，
# 最后一列就是未知数 x1、x2、x3 的值。
#
# 如果只把主元下面的元素消成 0，
# 得到的是上三角矩阵，
# 还需要通过回代求出未知数。
#
# 本程序把主元所在列的其他元素也全部消成 0，
# 所以不需要单独进行回代。
#
#
# 三、三种初等行变换
#
# 高斯消元使用下面三种变换：
#
#     1. 交换两行；
#     2. 某一行乘以一个非零常数；
#     3. 某一行加上另一行的若干倍。
#
# 这些变换不会改变方程组的解集。
#
# 例如：
#
#     2x + 4y = 6
#
# 两边同时除以 2，变成：
#
#     x + 2y = 3
#
# 原方程和新方程完全等价。
#
# 又例如：
#
#     equation_2 <- equation_2 - 3 * equation_1
#
# 只是用两个原方程构造了一个等价的新方程，
# 不会改变所有方程的公共解。
#
#
# 四、主元是什么
#
# 在处理第 col 列时，
# 当前行 matrix[col][col] 被称为主元。
#
# 例如：
#
#     [ 2  4 | 6 ]
#     [ 1  3 | 5 ]
#
# 处理第 0 列时，左上角的 2 就是主元。
#
# 把主元所在行除以主元，
# 就可以把主元化为 1：
#
#     [ 1  2 | 3 ]
#     [ 1  3 | 5 ]
#
# 然后用第一行消掉第二行第一列的 1：
#
#     [ 1  2 | 3 ]
#     [ 0  1 | 2 ]
#
#
# 五、为什么要选绝对值最大的主元
#
# 浮点数消元过程中会产生误差。
# 如果直接使用一个非常接近 0 的数作为除数，
# 就可能把误差放大。
#
# 因此程序会在当前列的可用行中寻找绝对值最大的元素：
#
#     if abs(matrix[row][col]) > abs(matrix[pivot_row][col]):
#         pivot_row = row
#
# 这叫做部分选主元。
#
# 选出主元后交换到当前行：
#
#     matrix[col], matrix[pivot_row] = (
#         matrix[pivot_row], matrix[col]
#     )
#
# 这样可以提高浮点计算的稳定性。
#
#
# 六、EPS 的作用
#
# 理论上，0 与非 0 可以直接判断。
# 但是浮点数计算可能得到：
#
#     0.000000000001
#
# 这个数在数学上可能应该是 0，
# 只是由于计算误差没有得到精确的 0。
#
# 所以程序使用一个很小的阈值：
#
#     EPS = 1e-8
#
# 当：
#
#     abs(value) < EPS
#
# 时，就把 value 当作 0。
#
# 这是一种浮点数误差控制方法。
#
#
# 七、程序的消元流程
#
# 外层循环：
#
#     for col in range(n):
#
# 表示依次处理第 0、1、...、n-1 列。
#
# 每一列主要执行以下步骤：
#
#     1. 在当前列寻找主元；
#     2. 如果主元接近 0，判断为没有唯一解；
#     3. 将主元行交换到当前行；
#     4. 将主元化为 1；
#     5. 用当前行消去其他所有行的当前列。
#
# 处理完第 col 列后，
# 第 col 列除了主元位置以外都应该接近 0。
#
#
# 八、把主元化为 1
#
# 代码：
#
#     pivot = matrix[col][col]
#
#     for j in range(col, n + 1):
#         matrix[col][j] /= pivot
#
# 假设当前行是：
#
#     [ 2  6 | 10 ]
#
# 主元为 2，整行除以 2 后得到：
#
#     [ 1  3 | 5 ]
#
# 右侧常数也必须同时除以 2，
# 否则方程就不再等价。
#
#
# 九、消去其他行
#
# 代码：
#
#     factor = matrix[row][col]
#
#     for j in range(col, n + 1):
#         matrix[row][j] -= factor * matrix[col][j]
#
# 当前主元行已经满足：
#
#     matrix[col][col] = 1
#
# 如果其他行当前列的元素是 factor，
# 就执行：
#
#     当前行 <- 当前行 - factor * 主元行
#
# 当前列会变成：
#
#     factor - factor * 1 = 0
#
# 例如：
#
#     主元行：[1, 2 | 3]
#     目标行：[4, 7 | 9]
#
# 消元：
#
#     目标行 <- 目标行 - 4 * 主元行
#
# 得到：
#
#     [0, -1 | -3]
#
#
# 十、为什么当前列没有主元就输出 No Solution
#
# 本题有 n 个方程和 n 个未知数。
# 如果每一列都能找到非零主元，
# 就可以得到 n 个相互独立的方程，
# 从而得到唯一解。
#
# 如果某一列找不到非零主元，
# 说明矩阵的秩小于 n，
# 方程之间存在依赖关系。
#
# 此时可能出现两种情况：
#
#     1. 无穷多解；
#     2. 无解。
#
# 题目要求这两种情况都输出：
#
#     No Solution
#
# 因此代码中：
#
#     if abs(matrix[pivot_row][col]) < EPS:
#         return None
#
# 就表示不再具有唯一解。
#
# 更一般地说：
#
#     rank(A) < rank(A|B)  -> 无解
#     rank(A) = rank(A|B) < n -> 无穷多解
#     rank(A) = rank(A|B) = n -> 唯一解
#
# 本题只需要区分“唯一解”和“非唯一解/无解”，
# 所以前两种情况统一输出 `No Solution`。
#
#
# 十一、为什么最后一列就是答案
#
# 经过高斯-约旦消元后，矩阵变成：
#
#     [1 0 ... 0 | x1]
#     [0 1 ... 0 | x2]
#     [...       ...]
#     [0 0 ... 1 | xn]
#
# 第 i 行对应的方程就是：
#
#     xi = 右侧常数
#
# 因此代码可以直接读取：
#
#     value = matrix[i][n]
#
# 注意：
# 矩阵有 n+1 列，
# 前 n 列是系数，
# 第 n 列是常数和最终答案。
#
#
# 十二、为什么输入要转为浮点数
#
# 输入的系数虽然是整数，
# 但消元时经常需要除法。
#
# 例如：
#
#     1 / 3 = 0.333333...
#
# 如果继续使用整数类型，
# 就会发生整数除法，丢失小数部分。
#
# 所以实际存储时应使用：
#
#     row = list(map(float, input().split()))
#
# 这样矩阵中的除法结果才能保留小数。
#
#
# 十三、为什么要避免输出 `-0.00`
#
# 浮点运算可能得到：
#
#     -0.0000000001
#
# 格式化为两位小数时可能显示成：
#
#     -0.00
#
# 但从数学上它应该视为 0。
#
# 因此代码使用：
#
#     if abs(value) < 0.0005:
#         value = 0.0
#
# 这样格式化后会输出：
#
#     0.00
#
# `0.0005` 是因为保留两位小数时，
# 绝对值小于这个范围的数会四舍五入为 `0.00`。
#
#
# 十四、算法复杂度
#
# 共有 n 个主元。
#
# 对每个主元：
#
#     1. 寻找主元最多检查 O(n) 行；
#     2. 归一化一行需要 O(n)；
#     3. 消去 n 行，每行最多处理 O(n) 个元素。
#
# 因此总时间复杂度为：
#
#     O(n^3)
#
# 增广矩阵需要保存 n * (n + 1) 个数，
# 空间复杂度为：
#
#     O(n^2)
#
# 本题 n <= 100，O(n^3) 可以通过。
