# 线性筛素数
import sys
from array import array

def linear_sieve(n):
    # bytearray 比 Python 的 bool 列表更节省空间
    is_composite = bytearray(n+1)

    # 无符号整数数组保存素数
    primes = array('I')

    for i in range(2,n+1):

        # i 没有被标记，说明i是质数
        if not is_composite[i]:
            primes.append(i)

        # 用当前找到的质数筛选i的倍数
        for p in primes:
            value = i * p

            if value > n:
                break

            is_composite[value] = 1

            # 保证每个合数只被最小质因数筛选一次，否则会导致重复筛选
            if i % p == 0:
                break

    return primes

def main():

    input = sys.stdin.buffer.readline

    n,q = map(int,input().split())

    primes = linear_sieve(n)

    out = bytearray()
    for _ in range(q):
        k = int(input())
        out.extend(str(primes[k-1]).encode()) #例如str(7).encode() = b'7'
        out.append(10) #换行的ASCII码 等价于 b'\n'

    sys.stdout.buffer.write(out)

if __name__ == '__main__':
    main()


# ============================================================
# P3383 线性筛素数：数学理论、算法思路与细节
# ============================================================
#
# 一、质数和合数
#
# 质数是大于 1，并且只有 1 和它本身两个正因数的整数。
#
# 例如：
#
#     2、3、5、7、11
#
# 都是质数。
#
# 合数是大于 1，并且正因数超过两个的整数。
#
# 例如：
#
#     4、6、8、9、10
#
# 都是合数。
#
# 1 既不是质数，也不是合数。
#
#
# 二、题目要求
#
# 给定 n，需要找出 1 到 n 中的所有质数。
# 每次询问第 k 小的质数。
#
# 例如：
#
#     n = 20
#
# 质数序列为：
#
#     2、3、5、7、11、13、17、19
#
# 因此：
#
#     第 1 小的质数是 2；
#     第 4 小的质数是 7；
#     第 8 小的质数是 19。
#
# 程序使用数组下标保存质数：
#
#     primes[0] 表示第 1 小的质数；
#     primes[1] 表示第 2 小的质数；
#     primes[k - 1] 表示第 k 小的质数。
#
#
# 三、为什么不能逐个判断每个数是否为质数
#
# 如果对每个数字 i 单独判断质数，
# 每次都需要尝试除数，整体会重复进行很多计算。
#
# 筛法的思想是：
#
#     不直接判断每个数；
#     而是从已知质数出发，
#     把它们的倍数标记为合数。
#
# 例如找到质数 2 后：
#
#     4、6、8、10、12、...
#
# 都是合数。
#
# 找到质数 3 后：
#
#     6、9、12、15、...
#
# 都是合数。
#
#
# 四、线性筛的核心思想
#
# 线性筛保证：
#
#     每个合数只被它的最小质因数标记一次。
#
# 例如：
#
#     18 = 2 * 9
#
# 18 的最小质因数是 2，
# 因此 18 应该由质数 2 标记，而不是由质数 3 标记。
#
#     30 = 2 * 15
#
# 30 也应该由它的最小质因数 2 标记。
#
# 每个合数都按照自己的最小质因数确定唯一标记路径，
# 因此不会像普通埃氏筛那样重复标记。
#
#
# 五、is_composite 数组
#
#     is_composite[i]
#
# 表示 i 是否已经确定为合数。
#
#     0：目前没有被标记为合数；
#     1：已经被标记为合数。
#
# 如果：
#
#     not is_composite[i]
#
# 说明 i 没有被任何更小的质数标记。
# 因此 i 一定是质数：
#
#     primes.append(i)
#
#
# 六、为什么使用 bytearray
#
#     is_composite = bytearray(n + 1)
#
# bytearray 的每个元素只占一个字节，
# 比 Python 列表保存大量布尔对象更加节省空间。
#
# 它可以像数组一样使用：
#
#     is_composite[x] = 1
#
# 查询和修改都很方便。
#
#
# 七、线性筛的循环过程
#
# 外层循环：
#
#     for i in range(2, n + 1):
#
# 依次处理每个整数 i。
#
# 如果 i 没有被标记：
#
#     if not is_composite[i]:
#         primes.append(i)
#
# 说明 i 是质数，把它加入质数表。
#
# 然后使用已经找到的质数 p 构造：
#
#     value = i * p
#
# 并将 value 标记为合数。
#
#
# 八、为什么 `if i % p == 0` 时必须 break
#
# 质数数组 primes 按从小到大排列。
#
# 当第一次出现：
#
#     i % p == 0
#
# 时，p 就是 i 的最小质因数。
#
# 当前生成的：
#
#     i * p
#
# 已经由它的最小质因数 p 负责标记。
#
# 如果继续使用更大的质数 q，
# 那么 i * q 中仍然含有 i 的最小质因数 p，
# 这会导致同一个合数拥有其他重复的筛选路径。
#
# 例如 i = 6：
#
#     p = 2：
#         标记 6 * 2 = 12
#         6 % 2 == 0，停止
#
# 如果不停止，还会标记：
#
#     6 * 3 = 18
#     6 * 5 = 30
#
# 但：
#
#     18 应该由 9 * 2 标记；
#     30 应该由 15 * 2 标记。
#
# 因此：
#
#     if i % p == 0:
#         break
#
# 是线性筛最关键的语句。
#
#
# 九、为什么线性筛是 O(n)
#
# 在埃氏筛中，一个合数可能被多个质因数重复标记。
#
# 在线性筛中，每个合数只被自己的最小质因数标记一次。
#
# 因此所有内层循环的有效标记次数总共是 O(n)，
# 外层循环也是 O(n)。
#
# 所以线性筛的时间复杂度为：
#
#     O(n)
#
# 质数数组和合数标记数组需要保存到 n，
# 空间复杂度为：
#
#     O(n)
#
#
# 十、为什么使用 array('I') 保存质数
#
# 如果使用普通 Python 列表：
#
#     primes = []
#
# 列表中的整数对象会带来较大的额外空间开销。
#
# 程序使用：
#
#     primes = array('I')
#
# 其中 'I' 表示无符号整数，
# 用连续的底层内存保存质数。
#
# 这样比 Python 整数列表更加节省内存。
#
#
# 十一、查询第 k 小的质数
#
# 数学上的“第 k 小”从 1 开始计数，
# 但 Python 数组下标从 0 开始。
#
# 因此：
#
#     第 k 小的质数
#     = primes[k - 1]
#
# 代码中的：
#
#     primes[k - 1]
#
# 就是在完成这个下标转换。
#
#
# 十二、为什么使用 bytearray 输出
#
# q 最大时会有大量输出。
# 如果每次都调用 print，函数调用次数很多。
#
# 程序先创建：
#
#     out = bytearray()
#
# 然后把每个答案转成字节追加进去：
#
#     out.extend(str(primes[k - 1]).encode())
#     out.append(10)
#
# 其中：
#
#     10 是换行符 '\n' 的 ASCII 编码。
#
# 最后统一输出：
#
#     sys.stdout.buffer.write(out)
#
# 这样可以减少输出调用次数，提高输入输出效率。
#
#
# 十三、线性筛与埃氏筛的区别
#
# 埃氏筛：
#
#     从质数出发，标记它的所有倍数；
#     一个合数可能被多个质数重复标记；
#     时间复杂度约为 O(n log log n)。
#
# 线性筛：
#
#     每个合数只由最小质因数标记一次；
#     时间复杂度为 O(n)；
#     需要维护质数列表和更严格的循环逻辑。
#
# 本程序学习的是线性筛。
#
#
# 十四、Python 性能说明
#
# 虽然线性筛的理论时间复杂度是 O(n)，
# 但 n = 10^8 时，Python 仍然可能 TLE 或 MLE。
#
# 原因包括：
#
#     1. Python 的 for 循环开销较大；
#     2. 线性筛需要大量 Python 层循环；
#     3. n = 10^8 时数组本身就很大；
#     4. q = 10^6 时输入输出也会占用较多时间。
#
# 因此：
#
#     这份 Python 代码适合学习线性筛；
#     大数据提交可以使用 C++ 版本。
#
#
# 十五、这道题考查的知识点
#
#     1. 质数和合数；
#     2. 埃氏筛；
#     3. 线性筛；
#     4. 最小质因数；
#     5. 时间复杂度 O(n)；
#     6. 字节数组；
#     7. 第 k 小元素的下标转换；
#     8. 大规模输入输出优化。

#
# 十六、带余除法公式与 `%`
#
# 整数除法满足：
#
#     a = (a // b) * b + (a % b)
#
# 因此：
#
#     a % b = a - (a // b) * b
#
# 例如：
#
#     17 // 5 = 3
#     17 % 5  = 2
#
# 因为：
#
#     17 = 3 * 5 + 2
#
# `%` 得到的就是除法后的余数。
#
#
# 十七、带余除法与质因数分解
#
# 线性筛会使用：
#
#     i % p == 0
#
# 来判断 p 是否整除 i。
#
# 如果 `i % p == 0`，根据带余除法公式：
#
#     i = (i // p) * p + 0
#
# 说明 i 可以被 p 整除。
#
# 在线性筛中，如果 p 整除 i，
# 那么 p 已经是 i 的最小质因数，
# 继续使用更大的质数筛选会产生重复标记，
# 所以需要：
#
#     if i % p == 0:
#         break
#
#
# 十八、`%` 与数组下标、循环状态
#
# `%` 不只用于判断整除，
# 还经常用于把一个数限制在固定范围内。
#
# 例如：
#
#     x % p
#
# 的结果通常位于 0 到 p - 1 之间，
# 因此可以用来：
#
#     1. 计算循环数组下标；
#     2. 处理周期性状态；
#     3. 进行模意义下的数学运算；
#     4. 判断一个数是否是另一个数的倍数。
#
# 本题的核心是筛选质数，
# 其中最直接的用途就是判断：
#
#     p 是否整除 i
#
# 即：
#
#     i % p == 0
#
#
# 十九、为什么线性筛中的 `p` 一定是质数
#
# `primes` 数组只保存已经确认的质数。
# 对每个整数 i，程序只用 primes 中的 p 去生成：
#
#     i * p
#
# 因此：
#
#     i % p == 0
#
# 表示 p 是 i 的一个质因数；
# 如果此时停止，就能保证当前合数由最小质因数路径处理。
#
# 这同时联系了三个概念：
#
#     余数为 0  ->  可以整除
#     可以整除   ->  p 是 i 的因数
#     p 本身为质数 -> p 是 i 的质因数
#
#
# 二十、补充：Python 中负数 `%` 的说明
#
# 本题只处理正整数，所以不会遇到负数取模的问题。
# 在 Python 中，若 b > 0，则：
#
#     a % b
#
# 的结果总在 0 到 b - 1 之间。
#
# 例如：
#
#     -3 % 10 = 7
#
# 因为：
#
#     -3 = (-1) * 10 + 7
#
# 这与 C++ 中负数取模的表现可能不同。
# 但在线性筛中 i 和 p 都是正整数，
# 所以只需要按照普通的“余数是否为 0”来理解即可。
