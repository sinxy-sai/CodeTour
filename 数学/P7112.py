# 行列式求值
import sys

def determinant(matrix,n,mod):
    sign = 1

    for col in range(n):
        for row in range(col+1,n):
            # 类似辗转相除法
            while matrix[col][col] != 0:
                pivot = matrix[col][col]
                value = matrix[row][col]

                # 带余除法的商
                quotient = value // pivot

                pivot_row = matrix[col]
                current_row = matrix[row]

                for k in range(col,n):
                    current_row[k] = (current_row[k] - quotient * pivot_row[k]) % mod

                # 交换行
                matrix[col],matrix[row] = matrix[row],matrix[col]

                # 交换两行会使行列式乘以 -1
                sign *= -1

            # 当前主元变成 0 后，再交换回来
            matrix[col],matrix[row] = matrix[row],matrix[col]
            sign *= -1

    ans = sign
    # 消元后，行列式等于主对角线元素的乘积
    for i in range(n):
        ans = (ans * matrix[i][i]) % mod

    return ans % mod


def main():
    input = sys.stdin.buffer.readline
    n,p = map(int,input().split())

    matrix = []
    for _ in range(n):
        row = list(map(int,input().split()))
        matrix.append([value % p for value in row])

    det = determinant(matrix,n,p)
    sys.stdout.write(str(det))

if __name__ == '__main__':
    main()


# ============================================================
# 行列式求值：数学理论、算法思路与实现细节
# ============================================================
#
# 一、什么是行列式
#
# 对一个 n 阶方阵 A：
#
#     A = [a[i][j]]
#
# 它对应一个数，记作：
#
#     det(A) 或 |A|
#
# 行列式不是把矩阵中的所有元素简单相乘，
# 而是按照不同的行列选择方式，
# 将若干乘积按照正负号相加。
#
# 例如二阶行列式：
#
#     | a  b |
#     | c  d |
#
# 的值为：
#
#     ad - bc
#
# 对三阶及更高阶矩阵，
# 直接按照定义展开会非常慢。
# 高斯消元可以在 O(n^3) 级别完成求值。
#
#
# 二、上三角矩阵的行列式
#
# 如果矩阵已经是上三角矩阵：
#
#     [a11  *    *  ]
#     [ 0  a22   *  ]
#     [ 0   0   a33]
#
# 那么：
#
#     det(A) = a11 * a22 * a33
#
# 一般情况下：
#
#     det(A) = a11 * a22 * ... * ann
#
# 因此，求行列式的常见思路是：
#
#     1. 通过行变换把矩阵化成上三角矩阵；
#     2. 记录行变换对行列式的影响；
#     3. 计算主对角线元素的乘积。
#
#
# 三、初等行变换对行列式的影响
#
# 1. 某一行加上另一行的若干倍：
#
#        Ri <- Ri + k * Rj
#
#    行列式不变。
#
# 2. 交换两行：
#
#        Ri <-> Rj
#
#    行列式变号。
#
# 3. 某一行乘以 k：
#
#        Ri <- k * Ri
#
#    行列式也乘以 k。
#
# 本程序只使用第一种变换和交换行，
# 所以只需要维护交换行产生的符号：
#
#     sign = 1
#
# 每交换一次：
#
#     sign *= -1
#
# 最后：
#
#     det(A) = sign * 主对角线乘积
#
#
# 四、为什么不能像普通高斯消元一样直接除法
#
# 如果只在实数范围内求行列式，
# 可以把某一行除以主元。
#
# 但是本题要求结果对任意 p 取模，
# 而 p 不一定是质数。
#
# 在模 p 意义下，只有与 p 互质的数才一定有乘法逆元。
#
# 例如模 6 时：
#
#     2
#
# 没有乘法逆元，因为不存在整数 x 满足：
#
#     2x ≡ 1 (mod 6)
#
# 所以不能随意进行：
#
#     除以 2
#
# 也不能直接写成：
#
#     a / b ≡ a * inverse(b) (mod p)
#
# 因此本题不能依赖“模意义下的除法”，
# 而是使用类似欧几里得算法的行变换。
#
#
# 五、带余除法
#
# 对于正整数 a 和 b：
#
#     a = (a // b) * b + (a % b)
#
# 其中：
#
#     a // b：商；
#     a % b ：余数。
#
# 例如：
#
#     17 // 5 = 3
#     17 % 5  = 2
#
# 因为：
#
#     17 = 3 * 5 + 2
#
# 所以：
#
#     a % b = a - (a // b) * b
#
#
# 六、如何用带余除法消去一列
#
# 假设当前主元所在行的当前列元素为 a，
# 另一行当前列元素为 b：
#
#     主元行：a
#     目标行：b
#
# 令：
#
#     q = b // a
#
# 对目标行执行：
#
#     R目标 <- R目标 - q * R主元
#
# 当前列的新元素为：
#
#     b - q * a
#     = b % a
#
# 因此，目标元素从 b 变成了 b % a。
#
# 由于余数严格小于除数，
# 反复执行后，当前列最终会出现 0。
#
# 例如当前列为：
#
#     2
#     5
#
# 第一次：
#
#     5 // 2 = 2
#     5 - 2 * 2 = 1
#
# 然后交换两行，当前列变为：
#
#     1
#     2
#
# 第二次：
#
#     2 // 1 = 2
#     2 - 2 * 1 = 0
#
# 最终当前列变为：
#
#     1
#     0
#
# 这就是把欧几里得算法应用到矩阵行变换中。
#
#
# 七、代码中的核心循环
#
#     while matrix[col][col] != 0:
#
# `matrix[col][col]` 是当前主元。
#
# 只要主元不为 0，就可以计算：
#
#     quotient = value // pivot
#
# 然后对整行执行：
#
#     current_row[k] -= quotient * pivot_row[k]
#
# 这里不只修改当前列，
# 而是修改从当前列到最后一列的所有元素。
#
# 原因是行变换必须作用于整行，
# 否则只修改一个元素就不再是合法的行变换，
# 也不能保证行列式关系正确。
#
# 更新后交换两行：
#
#     matrix[col], matrix[row] = (
#         matrix[row],
#         matrix[col]
#     )
#
# 交换之后，余数会成为新的主元，
# 继续进行下一轮类似欧几里得算法的消元。
#
#
# 八、为什么循环结束后还要交换一次
#
# 当：
#
#     matrix[col][col] == 0
#
# 时，说明当前主元已经变成 0，
# 另一行保存着当前列的最终非零值。
#
# 在前面的每一轮循环中，程序都交换过两行。
# 循环结束时，最后一次交换后的两行顺序是：
#
#     当前行：0
#     另一行：g
#
# 其中 g 通常是当前列相关元素的最大公约数。
#
# 因此需要再交换回来：
#
#     matrix[col], matrix[row] = (
#         matrix[row],
#         matrix[col]
#     )
#
# 让矩阵恢复为：
#
#     当前行：g
#     另一行：0
#
# 这样才能继续处理下一列。
#
# 这次交换同样会使行列式变号，
# 所以也要执行：
#
#     sign *= -1
#
#
# 九、为什么 `sign` 要记录交换次数
#
# 行变换：
#
#     Ri <- Ri - q * Rj
#
# 不改变行列式。
#
# 交换两行会使行列式乘以 -1。
#
# 所以如果总共发生了 t 次行交换，
# 最终行列式会多一个因子：
#
#     (-1)^t
#
# 程序使用：
#
#     sign = 1
#
# 每次交换：
#
#     sign *= -1
#
# 最终就等价于计算：
#
#     sign = (-1)^t
#
#
# 十、一个数学演算例子
#
# 考虑矩阵：
#
#     [1  2  3]
#     [2  5  8]
#     [1  0  1]
#
# 第一列处理：
#
#     R2 <- R2 - 2R1
#
# 得到：
#
#     [1  2  3]
#     [0  1  2]
#     [1  0  1]
#
# 再执行：
#
#     R3 <- R3 - R1
#
# 得到：
#
#     [1  2  3]
#     [0  1  2]
#     [0 -2 -2]
#
# 第二列处理：
#
#     R3 <- R3 + 2R2
#
# 得到上三角矩阵：
#
#     [1 2 3]
#     [0 1 2]
#     [0 0 2]
#
# 没有交换行，因此 sign = 1。
#
# 所以：
#
#     det(A) = 1 * 1 * 2 = 2
#
# P7112 的代码做的是相同的事情，
# 只是把普通的“直接消成 0”
# 换成了“通过余数逐步消成 0”，
# 从而避免模意义下的除法。
#
#
# 十一、模运算的处理
#
# 因为题目只要求：
#
#     det(A) mod p
#
# 所以每次更新后都可以取模：
#
#     current_row[k] = (
#         current_row[k]
#         - quotient * pivot_row[k]
#     ) % mod
#
# 这样做不会影响最终答案，因为：
#
#     (x mod p) mod p = x mod p
#
# 且：
#
#     (x + y) mod p
#     = ((x mod p) + (y mod p)) mod p
#
#     (x * y) mod p
#     = ((x mod p) * (y mod p)) mod p
#
# 这些性质保证了可以在每一步控制数字大小。
#
#
# 十二、为什么输入时先取模
#
# 代码中：
#
#     matrix.append([value % p for value in row])
#
# 因为：
#
#     value ≡ value % p (mod p)
#
# 原矩阵和取模后的矩阵在模 p 意义下等价，
# 它们的行列式对 p 取模后的结果也相同。
#
# 这样可以让矩阵中的元素始终处于较小范围，
# 降低后续计算的数字规模。
#
#
# 十三、和线性方程组高斯消元的区别
#
# P3389 求解线性方程组时，
# 通常会把主元化为 1，
# 再消除该列其他元素。
#
# 那里可以使用实数除法，
# 因为目标是求未知数的近似值。
#
# P7112 求行列式时：
#
#     1. 不需要把主元化为 1；
#     2. 不能随意做模意义下的除法；
#     3. 只使用行减法和交换行；
#     4. 需要记录交换行带来的符号变化；
#     5. 最后乘主对角线。
#
# 两道题的共同基础都是：
#
#     初等行变换 + 消元
#
# 但保持的数学量不同：
#
#     线性方程组：保持解集不变；
#     行列式：跟踪行列式值的变化。
#
#
# 十四、算法复杂度
#
# 一共有 O(n^2) 对元素需要通过类似欧几里得算法处理。
#
# 每一对元素的余数过程最多进行 O(log p) 次，
# 每次需要更新 O(n) 个列元素。
#
# 因此较严格地估计时间复杂度为：
#
#     O(n^3 log p)
#
# 在实际分析中，常把这类模板记作：
#
#     O(n^3)
#
# 空间复杂度为：
#
#     O(n^2)
#
# 因为需要保存 n * n 的矩阵。
