# 最大公约数和最小公倍数问题
import sys
import math
def main():
    x0,y0 = map(int,sys.stdin.buffer.readline().split())

    # 最大公约数一定是最小公倍数的因数
    if y0 % x0 != 0:
        sys.stdout.buffer.write(b'0')
        return

    '''
    假设P,Q满足题目条件，则有：
    P = x0 * a
    Q = x0 * b

    因为x0 = gcd(P,Q)

    所以gcd(a,b) = 1,a,b一定互质

    定理1:gcd(P,Q)*lcm(P,Q) = P*Q

    结论1: gcd(a,b) = 1

    结论2: lcm(a,b) = a * b

    定理2:gcd(P,Q)*a*b = lcm(P,Q) ，其中a,b互质,且a,b是P,Q的因数，说明最大公约数一定是最小公倍数的因数
        
    '''

    product = y0 // x0
    ans = 0

    for a in range(1,math.isqrt(product)+1):
        if product % a != 0:
            continue

        b = product // a

        # 约束1: a,b互质
        if math.gcd(a,b) != 1:
            continue

        if a == b:
            ans += 1
        else:
            ans += 2

    sys.stdout.buffer.write(str(ans).encode())

if __name__ == '__main__':
    main()


# ============================================================
# gcd 与 lcm 的数学概念
# ============================================================
#
# 一、gcd：最大公约数
#
# gcd 是 greatest common divisor 的缩写，
# 中文是“最大公约数”。
#
# 如果一个数能够同时整除 a 和 b，
# 那么它就是 a、b 的公约数。
#
# 例如：
#
#     12 的因数：1、2、3、4、6、12
#     18 的因数：1、2、3、6、9、18
#
# 它们的公共因数是：
#
#     1、2、3、6
#
# 最大的公共因数是 6，所以：
#
#     gcd(12, 18) = 6
#
# Python 中可以使用：
#
#     math.gcd(12, 18)
#
# 结果为：
#
#     6
#
#
# 二、lcm：最小公倍数
#
# lcm 是 least common multiple 的缩写，
# 中文是“最小公倍数”。
#
# 如果一个数同时是 a 和 b 的倍数，
# 那么它就是 a、b 的公倍数。
#
# 例如：
#
#     12 的倍数：12、24、36、48、...
#     18 的倍数：18、36、54、...
#
# 最小的公共倍数是 36，所以：
#
#     lcm(12, 18) = 36
#
# Python 3.9 及以上可以使用：
#
#     math.lcm(12, 18)
#
# 结果为：
#
#     36
#
#
# 三、gcd 与 lcm 的重要关系
#
# 对任意两个正整数 a、b，都有：
#
#     gcd(a, b) * lcm(a, b) = a * b
#
# 因此：
#
#     lcm(a, b) = a * b // gcd(a, b)
#
# 例如：
#
#     gcd(12, 18) = 6
#     lcm(12, 18) = 12 * 18 // 6 = 36
#
#
# 四、为什么最大公约数一定是最小公倍数的因数
#
# 设：
#
#     g = gcd(a, b)
#
# 那么可以写成：
#
#     a = g * x
#     b = g * y
#
# 并且：
#
#     gcd(x, y) = 1
#
# 因为 x、y 互质，所以：
#
#     lcm(x, y) = x * y
#
# 因此：
#
#     lcm(a, b)
#     = g * lcm(x, y)
#     = g * x * y
#
# 所以 lcm(a, b) 一定包含因子 g，
# 即：
#
#     gcd(a, b) | lcm(a, b)
#
#
# 五、gcd 和 lcm 在本题中的含义
#
# 题目要求：
#
#     gcd(P, Q) = x0
#     lcm(P, Q) = y0
#
# 因为最大公约数一定是最小公倍数的因数，
# 所以必须满足：
#
#     y0 % x0 == 0
#
# 如果不能整除，则不存在合法的 P、Q。
#
# 这就是代码中：
#
#     if y0 % x0 != 0:
#         输出 0
#
# 的数学依据。
#
#
# 六、P1029 中的变量关系
#
# 设：
#
#     P = x0 * a
#     Q = x0 * b
#
# 因为 x0 已经是 P、Q 的最大公约数，
# 所以去掉共同的 x0 后，a、b 不能再有公共因数：
#
#     gcd(a, b) = 1
#
# 又因为：
#
#     gcd(P, Q) * lcm(P, Q) = P * Q
#
# 所以：
#
#     x0 * y0 = P * Q
#               = (x0 * a) * (x0 * b)
#
# 化简得到：
#
#     a * b = y0 // x0
#
# 因此，本题被转化为：
#
#     寻找 product = y0 // x0 的互质因数对 (a, b)
#
# 代码中的：
#
#     math.gcd(a, b) != 1
#
# 就是在排除不合法的因数对。

# ============================================================
# P1029 最大公约数和最小公倍数问题
# 数学理论、算法思路与细节
# ============================================================
#
# 一、题目条件
#
# 题目要求：
#
#     gcd(P, Q) = x0
#     lcm(P, Q) = y0
#
# 求满足条件的有序数对 (P, Q) 的数量。
#
# 注意：
#
#     (P, Q) 和 (Q, P)
#
# 被认为是两种不同的方案。
#
#
# 二、最大公约数一定是最小公倍数的因数
#
# 对任意两个正整数 a、b，都有：
#
#     gcd(a, b) | lcm(a, b)
#
# 也就是说，最大公约数一定是最小公倍数的因数。
#
# 因此本题必须满足：
#
#     x0 | y0
#
# 代码中的：
#
#     if y0 % x0 != 0:
#         输出 0
#
# 就是在判断 x0 是否为 y0 的因数。
#
# 如果 x0 不能整除 y0，
# 那么不可能存在满足题目条件的 P、Q。
#
#
# 三、把最大公约数提出来
#
# 因为：
#
#     gcd(P, Q) = x0
#
# 所以 P、Q 都是 x0 的倍数。
#
# 设：
#
#     P = x0 * a
#     Q = x0 * b
#
# 其中 a、b 是正整数。
#
# 由于 x0 已经是 P、Q 的最大公约数，
# 所以除去共同的 x0 后，a、b 不能再有公共因数。
#
# 因此：
#
#     gcd(a, b) = 1
#
# 也就是说，a、b 互质。
#
#
# 四、为什么 a、b 必须互质
#
# 假设：
#
#     gcd(a, b) = d > 1
#
# 那么：
#
#     a = d * a1
#     b = d * b1
#
# 因此：
#
#     P = x0 * d * a1
#     Q = x0 * d * b1
#
# 这说明 x0 * d 也是 P、Q 的公共因数。
#
# 因为 d > 1：
#
#     x0 * d > x0
#
# 这与 x0 是最大公约数矛盾。
#
# 所以必须有：
#
#     gcd(a, b) = 1
#
#
# 五、推导 a * b = y0 / x0
#
# 对任意正整数 P、Q，都有重要公式：
#
#     gcd(P, Q) * lcm(P, Q) = P * Q
#
# 代入题目条件：
#
#     x0 * y0 = P * Q
#
# 再代入：
#
#     P = x0 * a
#     Q = x0 * b
#
# 得到：
#
#     x0 * y0 = (x0 * a) * (x0 * b)
#
#     x0 * y0 = x0^2 * a * b
#
# 两边除以 x0：
#
#     y0 = x0 * a * b
#
# 所以：
#
#     a * b = y0 / x0
#
# 代码中的：
#
#     product = y0 // x0
#
# 就是 a * b 的值。
#
#
# 六、为什么只需要寻找互质因数对
#
# 现在原问题已经转化为：
#
#     找出所有满足以下条件的 a、b：
#
#     1. a * b = product；
#     2. gcd(a, b) = 1。
#
# 找到一组 a、b 后，可以还原：
#
#     P = x0 * a
#     Q = x0 * b
#
# 因为 a、b 互质，所以：
#
#     gcd(P, Q) = x0
#
# 又因为互质数的最小公倍数等于乘积：
#
#     lcm(a, b) = a * b
#
# 所以：
#
#     lcm(P, Q)
#     = x0 * lcm(a, b)
#     = x0 * a * b
#     = y0
#
# 因此每一组互质因数对都对应一组合法答案。
#
#
# 七、如何枚举因数对
#
# 设：
#
#     a * b = product
#
# 如果 a 是 product 的因数，那么：
#
#     b = product // a
#
# 因数总是成对出现：
#
#     1 和 product
#     2 和 product // 2
#     ...
#
# 因此只需要枚举：
#
#     1 <= a <= sqrt(product)
#
# 代码中的：
#
#     for a in range(1, math.isqrt(product) + 1):
#
# 就是在枚举较小的因数。
#
# 找到 a 后，通过：
#
#     b = product // a
#
# 得到与它配对的另一个因数。
#
#
# 八、为什么要判断 gcd(a, b)
#
# 并不是所有因数对都合法。
#
# 例如：
#
#     product = 20
#
# 因数对有：
#
#     (1, 20)
#     (2, 10)
#     (4, 5)
#
# 但是：
#
#     gcd(1, 20) = 1
#     gcd(2, 10) = 2
#     gcd(4, 5) = 1
#
# 所以只有：
#
#     (1, 20)
#     (4, 5)
#
# 合法。
#
# 代码中的：
#
#     if math.gcd(a, b) != 1:
#         continue
#
# 就是在排除不互质的因数对。
#
#
# 九、为什么答案要加 2
#
# 题目统计的是有序数对。
#
# 如果找到：
#
#     (a, b)
#
# 那么还要统计：
#
#     (b, a)
#
# 对应到 P、Q 就是：
#
#     (x0 * a, x0 * b)
#     (x0 * b, x0 * a)
#
# 所以一般情况下：
#
#     ans += 2
#
# 例如：
#
#     x0 = 3
#     y0 = 60
#     product = 20
#
# 合法因数对：
#
#     (1, 20)
#     (4, 5)
#
# 对应答案：
#
#     (3, 60)
#     (60, 3)
#     (12, 15)
#     (15, 12)
#
# 总数为 4。
#
#
# 十、为什么要特殊处理 a == b
#
# 如果：
#
#     a == b
#
# 那么交换后仍然是同一组：
#
#     (a, b) = (b, a)
#
# 不能重复计算，所以：
#
#     ans += 1
#
# 代码中的：
#
#     if a == b:
#         ans += 1
#     else:
#         ans += 2
#
# 就是在处理这个问题。
#
# 由于还要求 gcd(a, b) = 1，
# a == b 时实际上只能有：
#
#     a = b = 1
#
# 也就是：
#
#     product = 1
#     x0 = y0
#
# 此时唯一答案是：
#
#     P = Q = x0
#
#
# 十一、示例推导
#
# 输入：
#
#     x0 = 3
#     y0 = 60
#
# 首先：
#
#     60 % 3 == 0
#
# 所以：
#
#     product = 60 // 3 = 20
#
# 枚举因数：
#
#     a = 1, b = 20
#     gcd(1, 20) = 1
#
#     a = 2, b = 10
#     gcd(2, 10) = 2，不合法
#
#     a = 4, b = 5
#     gcd(4, 5) = 1
#
# 因此答案为：
#
#     2 + 2 = 4
#
#
# 十二、算法流程
#
#     1. 读入 x0、y0；
#     2. 判断 y0 是否能被 x0 整除；
#     3. 计算 product = y0 / x0；
#     4. 枚举 product 的因数 a；
#     5. 令 b = product / a；
#     6. 判断 gcd(a, b) 是否等于 1；
#     7. 根据 a、b 是否相等增加答案；
#     8. 输出答案。
#
#
# 十三、复杂度
#
# 只需要枚举到：
#
#     sqrt(product)
#
# 因此枚举次数为：
#
#     O(sqrt(product))
#
# 每次计算 gcd 的复杂度约为：
#
#     O(log(product))
#
# 总时间复杂度可以写成：
#
#     O(sqrt(product) * log(product))
#
# 其中：
#
#     product = y0 / x0
#
# 额外空间复杂度为：
#
#     O(1)
#
#
# 十四、这道题考查的数学知识
#
#     1. 最大公约数；
#     2. 最小公倍数；
#     3. gcd(a,b) * lcm(a,b) = a*b；
#     4. 互质数的性质；
#     5. 因数成对出现；
#     6. 平方根枚举因数；
#     7. 有序数对的计数。
