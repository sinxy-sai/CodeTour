import sys
# 排序+贪心模板题
# 贪心算法是一种每一步都选择当前看起来最优的方案，希望通过一连串局部最优选择得到全局最优解的算法。
def main():
    input = sys.stdin.readline
    n = int(input())
    data = list(map(int, input().split()))
    people = [(data[i],i+1) for i in range(n)]

    # 先按接水时间排序，再按序号排序
    # 贪心策略：接水时间短的人排在前面，长的人排在后面,这样平均等待时间最小。
    people.sort(key=lambda x: (x[0],x[1]))

    order = [person[1] for person in people]
    sys.stdout.write(" ".join(map(str, order)) + "\n")
    elapsed_time = 0
    total_wait = 0
    # 前缀和
    for time,_ in people:
        total_wait += elapsed_time
        elapsed_time += time

    sys.stdout.write(f'{total_wait/n:.2f}' + "\n")


if __name__ == '__main__':
    main()


# ============================================================
# 排序 + 贪心：算法理论、思路与实现细节
# ============================================================
#
# 一、题目要求
#
# n 个人排队接水，第 i 个人接水需要 data[i] 时间。
# 水龙头同一时间只能服务一个人。
#
# 一个人的等待时间不包括自己的接水时间，
# 只包括排在他前面的人所占用的时间。
#
# 目标是让所有人的平均等待时间最小。
#
# 由于人数 n 固定，
# 最小化平均等待时间等价于最小化总等待时间：
#
#     平均等待时间 = 总等待时间 / n
#
# 所以程序只需要最小化 total_wait。
#
#
# 二、等待时间与前缀和
#
# 假设排队顺序为：
#
#     p1, p2, p3, ..., pn
#
# 他们的接水时间分别为：
#
#     t1, t2, t3, ..., tn
#
# 则每个人的等待时间为：
#
#     第 1 个人：0
#     第 2 个人：t1
#     第 3 个人：t1 + t2
#     第 4 个人：t1 + t2 + t3
#     ...
#
# 因此总等待时间为：
#
#     0
#     + t1
#     + (t1 + t2)
#     + ...
#     + (t1 + t2 + ... + t[n-1])
#
# 程序中的：
#
#     elapsed_time
#
# 表示当前人之前所有人的接水时间之和，
# 也就是当前人的等待时间。
#
# 每次处理一个人时：
#
#     total_wait += elapsed_time
#     elapsed_time += time
#
# 先把当前等待时间加入总和，
# 再把当前人的接水时间加入前缀和，
# 供后面的人等待。
#
#
# 三、贪心策略
#
# 接水时间短的人排在前面，
# 接水时间长的人排在后面。
#
# 代码通过：
#
#     people.sort(key=lambda x: (x[0], x[1]))
#
# 实现：
#
#     第一关键字：接水时间升序；
#     第二关键字：编号升序。
#
# 第二关键字对应题目要求：
# 如果接水时间相同，编号小的人排在前面。
#
#
# 四、为什么短任务应该优先
#
# 假设相邻两个人的接水时间为 a、b，
# 且 a <= b。
#
# 先安排 a，再安排 b：
#
#     a, b
#
# 这两个人对总等待时间的贡献是：
#
#     0 + a = a
#
# 如果交换顺序，先安排 b，再安排 a：
#
#     b, a
#
# 对总等待时间的贡献是：
#
#     0 + b = b
#
# 因为：
#
#     a <= b
#
# 所以：
#
#     a <= b
#
# 让接水时间较短的人先接水，
# 不会增加总等待时间。
#
#
# 五、交换论证
#
# 假设某个排队方案中出现了逆序：
#
#     a, b
#
# 其中：
#
#     a > b
#
# 也就是说，接水时间较长的人 a 排在了较短的人 b 前面。
#
# 设这两个人之前已经经过了时间 T。
#
# 原顺序的等待时间为：
#
#     a 等待 T
#     b 等待 T + a
#
# 两人的等待时间总和为：
#
#     T + (T + a) = 2T + a
#
# 交换后：
#
#     b, a
#
# 两人的等待时间为：
#
#     b 等待 T
#     a 等待 T + b
#
# 两人的等待时间总和为：
#
#     T + (T + b) = 2T + b
#
# 因为 a > b，所以：
#
#     2T + b < 2T + a
#
# 交换后总等待时间变小。
#
# 因此，一个最优方案中不应该存在接水时间较长的人排在较短的人前面的情况。
# 不断消除这样的逆序，最终得到接水时间升序排列。
#
# 这证明了排序后的方案一定是最优方案。
#
#
# 六、为什么相同接水时间按编号排序
#
# 如果两个人的接水时间相同，例如：
#
#     a = b
#
# 无论谁先接水，这两个人对总等待时间的贡献都相同。
#
# 因此交换他们不会影响最优值。
#
# 题目进一步规定：
#
#     接水时间相同时，编号小的人排在前面。
#
# 所以使用编号作为第二排序关键字：
#
#     key=lambda x: (x[0], x[1])
#
#
# 七、前缀和计算过程
#
# 例如排序后的接水时间为：
#
#     1, 2, 5
#
# 等待时间为：
#
#     第 1 个人：0
#     第 2 个人：1
#     第 3 个人：1 + 2 = 3
#
# 总等待时间为：
#
#     0 + 1 + 3 = 4
#
# 程序执行过程：
#
#     elapsed_time = 0
#     total_wait = 0
#
#     处理 1：
#         total_wait = 0
#         elapsed_time = 1
#
#     处理 2：
#         total_wait = 1
#         elapsed_time = 3
#
#     处理 5：
#         total_wait = 4
#         elapsed_time = 8
#
# 最终：
#
#     total_wait = 4
#
#
# 八、为什么输出 `total_wait / n`
#
# 题目要求平均等待时间：
#
#     average = total_wait / n
#
# Python 中：
#
#     total_wait / n
#
# 会得到浮点数。
#
# 格式化代码：
#
#     f'{total_wait / n:.2f}'
#
# 表示保留两位小数。
#
# 例如：
#
#     291.9
#
# 会输出：
#
#     291.90
#
#
# 九、算法流程
#
#     1. 读入 n 个人的接水时间；
#     2. 将每个人保存为 (接水时间, 编号)；
#     3. 按接水时间升序、编号升序排序；
#     4. 按排序后的顺序输出编号；
#     5. 使用 elapsed_time 维护前缀和；
#     6. 累加每个人的等待时间；
#     7. 输出总等待时间除以 n 的结果。
#
#
# 十、正确性直觉
#
# 一个接水时间较长的人如果排在较短的人前面，
# 就会让较短的人等待较长时间。
#
# 将这两个人交换后，
# 较短的接水时间会影响后面的人更少，
# 因此总等待时间不会增加，逆序时还会减少。
#
# 所有逆序都消除后，
# 队列必然按照接水时间从小到大排列。
#
# 因此排序后的队列具有最小总等待时间，
# 从而具有最小平均等待时间。
#
#
# 十一、复杂度分析
#
# 构造 people 需要 O(n) 时间和 O(n) 空间。
#
# 排序需要：
#
#     O(n log n)
#
# 扫描计算等待时间需要：
#
#     O(n)
#
# 所以总时间复杂度为：
#
#     O(n log n)
#
# 额外空间复杂度为：
#
#     O(n)
