# Floyd 算法 全源最短路

import sys

def main():
    input = sys.stdin.buffer.readline
    n,m = map(int,input().split())

    INF = int(1e9)
    dist = [[INF]*(n+1) for _ in range(n+1)]

    for i in range(1,n+1):
        dist[i][i] = 0

    for _ in range(m):
        u,v,w = map(int,input().split())

        # 无向图且有重边, 只保留较小的边权
        if dist[u][v] > w:
            dist[u][v] = w
            dist[v][u] = w

    # Floyd 算法
    # k 为中间点,必须放在最外面
    for k in range(1,n+1):
        for i in range(1,n+1):
            for j in range(1,n+1):
                # new_dist = dist[i][k] + dist[k][j]

                # if new_dist < dist[i][j]:
                #     dist[i][j] = new_dist
                dist[i][j] = min(dist[i][k] + dist[k][j],dist[i][j])

    out = []
    for i in range(1,n+1):
        out.append(' '.join(map(str,dist[i][1:])))

    sys.stdout.write('\n'.join(out))

if __name__ == '__main__':
    main()


# 思路说明：
#
# 一、这题属于什么图论问题
#
# 本题给出一个带正权的无向连通图，
# 要求求出所有点对之间的最短路径。
#
# “所有点对”表示：
#
#     任意起点 i
#     任意终点 j
#     都要知道 i 到 j 的最短距离
#
# 这种问题叫：
#
#     全源最短路
#
# Floyd 算法就是解决全源最短路的经典算法。
#
# 它适合节点数较少的图。
# 本题 n <= 100，正好适合 Floyd。
#
#
# 二、如何建图
#
# graph 也可以用邻接矩阵表示。
# 本程序使用：
#
#     dist[i][j]
#
# 表示当前已知的 i 到 j 的最短距离。
#
# 初始化时：
#
#     dist[i][i] = 0
#
# 因为一个点到自己的距离是 0。
#
# 其他点对一开始设为无穷大：
#
#     INF = int(1e9)
#
# 表示目前还没有找到从 i 到 j 的路径。
#
# 读入一条无向边 u -- v，边权为 w 时：
#
#     dist[u][v] = w
#     dist[v][u] = w
#
# 因为图是无向图，
# 从 u 到 v 和从 v 到 u 都可以直接走。
#
#
# 三、重边怎么处理
#
# 题目允许存在重边。
#
# 例如：
#
#     1 2 5
#     1 2 3
#
# 表示 1 和 2 之间有两条边，
# 权值分别是 5 和 3。
#
# 直接边的最短距离应该保留较小的 3：
#
#     dist[1][2] = min(dist[1][2], 3)
#
# 所以程序写成：
#
#     if dist[u][v] > w:
#         dist[u][v] = w
#         dist[v][u] = w
#
# 不能无条件覆盖，
# 否则后读入的大权值边可能覆盖前面的小权值边。
#
#
# 四、Floyd 的状态定义
#
# Floyd 的关键是逐步增加“允许作为中间点的节点”。
#
# 定义：
#
#     dist[i][j]
#
# 在第 k 轮开始前，
# 可以理解为：
#
#     只允许使用 1 到 k-1 号节点作为中间点时，
#     i 到 j 的最短距离
#
# 注意：
# 起点 i 和终点 j 不算中间点。
#
# Floyd 每一轮尝试让 k 成为新的中间点。
#
#
# 五、状态转移
#
# 从 i 到 j 的最短路径，
# 关于节点 k 只有两种可能：
#
#     1. 不经过 k
#     2. 经过 k
#
# 不经过 k：
#
#     dist[i][j]
#
# 经过 k：
#
#     dist[i][k] + dist[k][j]
#
# 因此转移为：
#
#     dist[i][j] = min(
#         dist[i][j],
#         dist[i][k] + dist[k][j]
#     )
#
# 代码中的：
#
#     dist[i][j] = min(
#         dist[i][k] + dist[k][j],
#         dist[i][j]
#     )
#
# 就是在比较这两种方案。
#
#
# 六、为什么 k 必须放最外层
#
# Floyd 的 k 是动态规划的阶段变量。
#
# 第 k 轮表示：
#
#     在原来允许 1 到 k-1 号点作为中间点的基础上，
#     现在额外允许 k 号点作为中间点。
#
# 转移公式依赖上一阶段的结果：
#
#     dp[k][i][j] =
#         min(
#             dp[k-1][i][j],
#             dp[k-1][i][k] + dp[k-1][k][j]
#         )
#
# 所以必须先完成第 k-1 轮，
# 才能进行第 k 轮。
#
# 因此循环顺序必须是：
#
#     for k:
#         for i:
#             for j:
#
# 如果把 k 放在里面，
# 就可能在 dist[i][k] 或 dist[k][j] 还没有按照当前阶段计算完成时，
# 提前使用它们，破坏动态规划的阶段含义。
#
# 例如链：
#
#     1 -- 2 -- 3 -- 4
#
# 先允许 2 作为中间点，
# 才能算出：
#
#     dist[1][3] = 2
#
# 再允许 3 作为中间点，
# 才能算出：
#
#     dist[1][4] = dist[1][3] + dist[3][4] = 3
#
# k 放最外层时，这个顺序能够被保证。
#
#
# 七、Floyd 和其他最短路算法的区别
#
# Floyd 求的是所有点对最短路：
#
#     时间复杂度 O(n^3)
#
# Dijkstra 通常求一个起点到其他点的最短路。
#
# 如果要得到所有点对，
# 可以从每个点分别跑一次 Dijkstra，
# 但实现和适用场景不同。
#
# 本题 n <= 100，
# O(n^3) 可以接受，
# 所以 Floyd 更简单直接。
#
#
# 八、为什么 INF 可以这样设置
#
# 本题边权最大为 1000，
# 路径最多经过 n-1 条边，
# 最大可能最短路不超过：
#
#     99 * 1000
#
# 所以 1e9 远大于所有合法答案，
# 可以作为无穷大使用。
#
# 如果题目数据范围更大，
# 通常可以使用：
#
#     INF = 10**18
#
# 避免无穷大参与加法后溢出或变得不安全。
#
#
# 九、复杂度分析
#
# 初始化 dist 矩阵：
#
#     O(n^2)
#
# 读入 m 条边：
#
#     O(m)
#
# Floyd 三重循环：
#
#     O(n^3)
#
# 所以总时间复杂度是：
#
#     O(n^3 + m)
#
# 空间上保存一个 n * n 的距离矩阵：
#
#     O(n^2)
#
# 本题 n <= 100，
# 邻接矩阵的空间开销是可以接受的。
