import sys


def minimum_time(tasks):
    # 计算总时间
    # 初始化最佳时间等于总时间
    total_time = sum(tasks)
    best = total_time

    def dfs(index,left_time):
        '''
        index: 当前处理的数字的下标
        left_time: 之前左脑已经处理的时间
        right_time: 之前右脑已经处理的时间
        '''
        nonlocal best
        # 1.终止条件
        if index == len(tasks):
            right_time = total_time - left_time
            best = min(best,max(left_time,right_time))
            return

        # 2.枚举选择和处理当前状态，但是当前状态处理后是要通过参数传递的
        
        # 交给左脑
        dfs(index+1,left_time + tasks[index])
        
        # 交给右脑
        dfs(index+1,left_time)

    dfs(0,0)
    return best
    

def main():
    input = sys.stdin.readline
    s1,s2,s3,s4 = map(int,input().split())

    ans = 0
    for _ in range(4):
        tasks = list(map(int,input().split()))
        ans += minimum_time(tasks)
    
    sys.stdout.write(str(ans))

if __name__ == '__main__':
    main()


# ============================================================
# P2392 考前临时抱佛脚：理论、算法思路与细节
# ============================================================
#
# 一、题目本质
#
# 每一科的题目可以分别交给左脑和右脑。
# 同一科的两道题可以同时计算，所以这一科真正需要的时间是：
#
#     max(左脑总时间, 右脑总时间)
#
# 目标是把这一科的题目分成两组，使两组总时间尽可能接近。
#
# 四科必须一科一科完成，不能同时复习，因此四科的最短时间直接相加。
#
#
# 二、为什么可以只记录 left_time
#
# 当前科目的总时间 total_time 是固定的。
#
# 如果已经知道左脑分到的时间为 left_time，
# 那么右脑分到的时间一定是：
#
#     right_time = total_time - left_time
#
# 所以不需要额外记录 right_time。
#
# dfs 的状态可以写成：
#
#     dfs(index, left_time)
#
# 含义是：
#
#     已经处理完下标 0 到 index - 1 的题目；
#     这些题目中分给左脑的总时间为 left_time；
#     接下来处理第 index 道题。
#
#
# 三、二叉决策 DFS
#
# 每道题只有两种分配方式：
#
#     1. 交给左脑；
#     2. 交给右脑。
#
# 因此每个 DFS 状态都会产生两个下一状态。
#
# 交给左脑：
#
#     dfs(index + 1, left_time + tasks[index])
#
# 交给右脑：
#
#     dfs(index + 1, left_time)
#
# 这类每一步只有“选”或“不选”、“做”或“不做”的搜索，
# 称为二叉决策 DFS。
#
# 这里：
#
#     选择当前题目给左脑
#     可以看成“选”
#
#     选择当前题目给右脑
#     可以看成“不选”
#
#
# 四、递归树示例
#
# 假设某科有两道题，耗时为：
#
#     [5, 3]
#
# 初始状态：
#
#     dfs(0, 0)
#
# 表示：
#
#     还没有处理题目；
#     左脑当前耗时为 0。
#
# 第一题有两种选择：
#
#     dfs(1, 5)    # 5 分给左脑
#     dfs(1, 0)    # 5 分给右脑
#
# 从 dfs(1, 5) 继续处理第二题：
#
#     dfs(2, 8)    # 3 也分给左脑
#     dfs(2, 5)    # 3 分给右脑
#
# 从 dfs(1, 0) 继续处理第二题：
#
#     dfs(2, 3)    # 3 分给左脑
#     dfs(2, 0)    # 3 也分给右脑
#
# 一共得到 2^2 = 4 种分配方案。
#
#
# 五、递归终止条件
#
#     if index == len(tasks):
#
# 表示所有题目都已经分配完成。
#
# 此时计算右脑时间：
#
#     right_time = total_time - left_time
#
# 当前方案的完成时间是：
#
#     max(left_time, right_time)
#
# 再用它更新当前科目的最优答案：
#
#     best = min(best, max(left_time, right_time))
#
#
# 六、为什么目标是让两边尽可能接近
#
# 左右脑是同时工作的，所以完成时间由耗时较长的一边决定。
#
# 例如：
#
#     左脑 10 分钟，右脑 2 分钟
#
# 完成时间是：
#
#     max(10, 2) = 10
#
# 如果分配为：
#
#     左脑 6 分钟，右脑 6 分钟
#
# 完成时间是：
#
#     max(6, 6) = 6
#
# 因此最优策略通常是让左右脑的总时间尽量接近。
#
#
# 七、为什么四科的答案可以相加
#
# 题目要求必须一科一科复习。
#
# 假设四科分别需要：
#
#     t1, t2, t3, t4
#
# 因为四科不能同时进行，所以总时间为：
#
#     t1 + t2 + t3 + t4
#
# 代码中：
#
#     ans += minimum_time(tasks)
#
# 就是在分别求出每科的最短时间后累加。
#
#
# 八、这种写法和组合、排列搜索的区别
#
# P2392 中每一步只有两个固定选择，
# 所以直接写两个递归调用：
#
#     dfs(...)
#     dfs(...)
#
# P1157 组合题中，当前可能选择多个数字，
# 所以使用 for 循环：
#
#     for value in range(...):
#         path.append(value)
#         dfs(...)
#         path.pop()
#
# P1706 全排列题中，当前也有多个未使用数字，
# 所以使用 for 循环和 used 数组。
#
# 它们本质上都是：
#
#     当前状态
#         -> 枚举选择
#         -> 得到下一状态
#         -> 递归搜索
#
# 区别只在于每一步的候选数量和状态保存方式不同。
#
#
# 九、为什么这里不需要 path 和 pop
#
# P1157、P1706 需要输出具体的组合或排列，
# 所以必须保存当前路径 path。
#
# P2392 不需要输出具体分配方案，只需要知道左脑总时间。
# 因此状态只需要两个整数：
#
#     index
#     left_time
#
# 每次递归调用时直接传入新的数值：
#
#     left_time + tasks[index]
#
# 整数状态没有被原地修改，所以递归返回后不需要 pop 或撤销。
#
#
# 十、复杂度
#
# 如果一科有 s 道题，每道题有两种分配方式，
# 所以一共有：
#
#     2^s
#
# 种分配方案。
#
# 每个方案到达叶子时只进行 O(1) 的计算，
# 所以一科的时间复杂度为：
#
#     O(2^s)
#
# 题目中 s <= 20，最多约一百万种方案。
#
# 递归深度最多为 s，因此递归栈空间复杂度为：
#
#     O(s)
#
# 四科分别搜索，整体复杂度为：
#
#     O(2^s1 + 2^s2 + 2^s3 + 2^s4)
#
#
# 十一、这道题的搜索范式
#
#     def dfs(index, state):
#         if 到达所有选择:
#             计算当前方案
#             更新答案
#             return
#
#         dfs(index + 1, 选择方案一后的状态)
#         dfs(index + 1, 选择方案二后的状态)
#
# 这是“选/不选”型 DFS 的基本模板，
# 也可以用于子集枚举、分组、背包搜索等问题。
