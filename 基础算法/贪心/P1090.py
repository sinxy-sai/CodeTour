import sys
import heapq
# 哈夫曼式贪心 堆

def main():
    input = sys.stdin.buffer.readline
    n = int(input())
    data = list(map(int, input().split()))
    heapq.heapify(data)
    total_cost = 0

    while len(data) > 1:
        x1 = heapq.heappop(data)
        x2 = heapq.heappop(data)
        merged_cost = x1 + x2
        total_cost += merged_cost
        heapq.heappush(data,merged_cost)

    sys.stdout.buffer.write(str(total_cost).encode())

if __name__ == '__main__':
    main()


# ============================================================
# 贪心 + 最小堆：算法理论、思路与实现细节
# ============================================================
#
# 一、题目要求
#
# 有 n 堆果子，每堆都有一个重量。
# 每次可以选择两堆果子合并，
# 合并消耗的体力等于这两堆果子的重量之和。
#
# 最终所有果子会合并成一堆，
# 需要让所有次合并消耗的体力总和最小。
#
# 如果某次合并的两堆重量为 x 和 y，
# 那么这次代价为：
#
#     x + y
#
#
# 二、贪心策略
#
# 每次选择当前重量最小的两堆果子进行合并。
#
# 设当前最小的两堆为 x1、x2：
#
#     x1 <= x2
#
# 合并后新堆重量为：
#
#     merged_cost = x1 + x2
#
# 并且本次要付出：
#
#     x1 + x2
#
# 把新堆放回集合后，继续重复这个过程。
#
# 代码：
#
#     x1 = heapq.heappop(data)
#     x2 = heapq.heappop(data)
#     merged_cost = x1 + x2
#     total_cost += merged_cost
#     heapq.heappush(data, merged_cost)
#
#
# 三、为什么小堆应该优先合并
#
# 一个果子堆可能会参与多次合并。
# 每参与一次合并，它的重量就会被计入一次代价。
#
# 如果一个重量很大的堆过早参与合并，
# 它可能在后续过程中被重复计算多次，
# 从而增加总消耗。
#
# 较小的堆适合尽早合并，
# 让它们形成的新堆在后续合并中尽量少地增加代价。
#
# 因此每一步选择当前最小的两堆，
# 可以让当前代价和后续可能产生的代价都尽量小。
#
#
# 四、交换论证
#
# 可以把整个合并过程看成一棵二叉树：
#
#     叶子节点：最初的 n 堆果子；
#     内部节点：两堆合并后得到的新堆；
#     内部节点权值：左右子树权值之和。
#
# 总体力消耗就是所有内部节点权值之和。
#
# 等价地，每一堆初始果子的重量会被计算若干次，
# 计算次数等于它在合并树中的深度。
#
# 因此：
#
#     总代价 = sum(每堆重量 × 它被重复计算的次数)
#
# 为了让总代价最小，
# 较小的重量应该承担更深的合并层数，
# 较大的重量应该尽量靠近最终根节点。
#
# 在一棵最优合并树中，
# 权值最小的两堆可以放在最深的一对兄弟叶子位置。
# 将它们先合并不会增加最优代价。
#
# 合并后把 x1、x2 看成一个新堆，
# 原问题就转化成规模更小的同类问题。
# 对剩余问题继续使用相同策略，
# 就得到每次合并最小的两堆的算法。
#
# 这就是哈夫曼算法的核心贪心思想。
#
#
# 五、样例过程
#
# 初始果堆：
#
#     1, 2, 9
#
# 第一次取最小的两堆：
#
#     1 + 2 = 3
#
# 本次代价为 3，
# 放回新堆后变成：
#
#     3, 9
#
# 第二次合并：
#
#     3 + 9 = 12
#
# 本次代价为 12。
#
# 总代价：
#
#     3 + 12 = 15
#
#
# 六、为什么使用最小堆
#
# 贪心策略要求反复完成三种操作：
#
#     1. 取出当前最小的元素；
#     2. 再取出当前最小的元素；
#     3. 将合并后的新元素放回集合。
#
# 如果使用普通列表，
# 每次寻找最小值可能需要 O(n) 时间。
#
# 最小堆可以高效支持这些操作：
#
#     heapq.heapify(data)
#
# 将列表建立为最小堆。
#
#     heapq.heappop(data)
#
# 取出并删除堆顶最小值。
#
#     heapq.heappush(data, value)
#
# 将新值加入最小堆，并恢复堆结构。
#
# Python 的 `heapq` 默认实现最小堆，
# 所以堆顶 `data[0]` 始终是当前最小元素。
#
#
# 七、循环条件
#
# 代码使用：
#
#     while len(data) > 1:
#
# 只要还有至少两堆果子，就可以继续合并。
#
# 每次合并会：
#
#     删除两堆；
#     加回一堆。
#
# 所以堆的数量每次减少 1。
#
# 初始有 n 堆，最终剩 1 堆，
# 一共会进行：
#
#     n - 1
#
# 次合并。
#
# 当只剩一堆时，已经不能继续合并，循环结束。
#
#
# 八、总代价的累计
#
# `merged_cost` 有两个作用：
#
#     1. 它是当前这次合并消耗的体力；
#     2. 它是合并后新堆的重量。
#
# 因此代码需要同时完成：
#
#     total_cost += merged_cost
#     heapq.heappush(data, merged_cost)
#
# 不能只把新堆放回而不累计，
# 也不能累计后不把新堆放回。
#
#
# 九、边界情况
#
# 如果 n = 1，
# 一开始就只有一堆果子，不需要进行合并。
#
#     total_cost = 0
#
# 程序中的：
#
#     while len(data) > 1:
#
# 会直接跳过循环，输出 0。
#
#
# 十、算法流程
#
#     1. 读入所有果堆重量；
#     2. 建立最小堆；
#     3. 取出当前最小的两堆；
#     4. 计算合并代价；
#     5. 将合并代价加入 total_cost；
#     6. 将新堆放回最小堆；
#     7. 重复直到只剩一堆；
#     8. 输出 total_cost。
#
#
# 十一、正确性直觉
#
# 每个初始果堆的重量会根据合并顺序被重复计算。
# 重量越大的果堆越应该少被重复计算，
# 重量越小的果堆可以承担更多层的重复计算。
#
# 每次合并当前最小的两堆，
# 正好让较小重量更早进入合并树的深层，
# 让较大重量尽量靠近最终合并。
#
# 通过交换论证可以把任意最优方案调整为这种形式，
# 因此该贪心策略得到的总代价最小。
#
#
# 十二、与哈夫曼编码的关系
#
# 哈夫曼编码构造哈夫曼树时，
# 每次也选择权值最小的两个节点合并，
# 并把新节点放回优先队列。
#
# 两道题的核心过程完全相同：
#
#     取最小的两个权值；
#     合并；
#     累加合并权值；
#     将新权值放回最小堆。
#
# P1090 求的是所有合并权值之和，
# 哈夫曼编码通常进一步根据合并树生成每个字符的编码。
#
#
# 十三、复杂度分析
#
# 建立最小堆：
#
#     O(n)
#
# 一共进行 n - 1 次合并。
# 每次包含两次弹出和一次插入，
# 每次堆操作的复杂度为 O(log n)。
#
# 因此总时间复杂度为：
#
#     O(n log n)
#
# 最小堆需要保存当前所有果堆，
# 空间复杂度为：
#
#     O(n)
