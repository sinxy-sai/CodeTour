# 单源最短路径(弱化版)
import sys
import heapq

def main():
    input = sys.stdin.buffer.readline
    n,m,s = map(int,input().split())

    graph = [[] for _ in range(n+1)]
    
    for _ in range(m):
        u,v,w = map(int,input().split())
        graph[u].append((v,w))

    INF = 2**31-1   
    dist = [INF]*(n+1)
    dist[s] = 0

    heap = [(0,s)]
    while heap:
        current_dist,u = heapq.heappop(heap)

        if current_dist != dist[u]:
            continue

        for v,w in graph[u]:
            new_dist = current_dist + w

            if new_dist < dist[v]:
                dist[v] = new_dist
                heapq.heappush(heap,(new_dist,v))

    sys.stdout.write(' '.join(map(str,dist[1:])))

if __name__ == '__main__':
    main()


# 思路说明：
#
# 一、这题属于什么图论问题
#
# 本题给出一个有向带权图，
# 以及一个起点 s。
#
# 要求：
#
#     求 s 到其他所有节点的最短路径
#
# 这类问题叫：
#
#     单源最短路
#
# 本题边权满足 w >= 0，
# 因此可以使用 Dijkstra 算法。
#
#
# 二、为什么使用邻接表
#
# 图中每条边是：
#
#     u -> v，边权为 w
#
# 程序用：
#
#     graph[u].append((v, w))
#
# 保存从 u 出发的所有边。
#
# 例如：
#
#     graph[1] = [(2, 2), (3, 5)]
#
# 表示：
#
#     1 -> 2，权重 2
#     1 -> 3，权重 5
#
# 这是有向图，
# 所以只添加：
#
#     graph[u].append((v, w))
#
# 不需要添加反向边。
#
# 如果是无向图，才需要同时添加：
#
#     graph[u].append((v, w))
#     graph[v].append((u, w))
#
#
# 三、dist 数组表示什么
#
# 本程序中的：
#
#     dist[v]
#
# 表示：
#
#     从起点 s 到节点 v 的当前最短距离
#
# 它是一维数组，
# 因为本题只求一个起点到其他节点的距离。
#
# 这和 Floyd 的 dist[i][j] 不同。
#
# Floyd：
#
#     dist[i][j] 表示 i 到 j 的距离
#     求所有点对最短路
#
# Dijkstra：
#
#     dist[v] 表示 s 到 v 的距离
#     求一个起点到所有点的最短路
#
#
# 四、初始化
#
# 代码：
#
#     INF = 2**31 - 1
#     dist = [INF] * (n + 1)
#     dist[s] = 0
#
# 起点到自己的距离是 0。
#
# 其他节点一开始还不知道能否到达，
# 所以先设置成无穷大 INF。
#
# P3371 要求无法到达的节点输出 2^31 - 1，
# 所以这里直接使用：
#
#     INF = 2**31 - 1
#
# 如果某个节点最终仍然是 INF，
# 就说明从 s 无法到达它。
#
#
# 五、什么是松弛
#
# 假设当前已经知道：
#
#     s 到 u 的最短距离是 dist[u]
#
# 又有一条边：
#
#     u -> v，权重 w
#
# 那么经过 u 到 v 的路径长度就是：
#
#     dist[u] + w
#
# 如果这个距离比当前的 dist[v] 更小，
# 就更新：
#
#     new_dist = dist[u] + w
#
#     if new_dist < dist[v]:
#         dist[v] = new_dist
#
# 这个过程叫“松弛”。
#
# 松弛的含义是：
#
#     尝试用一条新路径改进当前最短距离
#
#
# 六、为什么要使用小根堆
#
# Dijkstra 每次需要选择：
#
#     当前距离起点最近的、还没有处理的节点
#
# 如果每次都扫描所有节点寻找最小 dist，
# 会比较慢。
#
# 所以使用小根堆：
#
#     heap = [(0, s)]
#
# 堆中保存：
#
#     (当前距离, 节点编号)
#
# Python 的 heapq 是小根堆，
# 元组会优先按照第一个元素排序。
#
# 所以：
#
#     (3, 5)
#
# 的优先级高于：
#
#     (10, 2)
#
# 因为当前距离 3 更小。
#
# 取出堆顶：
#
#     current_dist, u = heapq.heappop(heap)
#
# 就能优先处理当前距离最小的节点。
#
# 这是 Dijkstra 高效运行的关键。
#
#
# 七、为什么当前距离最小的节点可以优先确定
#
# 因为所有边权非负。
#
# 假设当前取出的节点 u 的距离是最小的。
# 如果之后还存在一条更短的路径到 u，
# 那条路径必须经过某个还没有处理的节点。
#
# 但还没有处理的节点当前距离不会小于 dist[u]，
# 再加上非负边权后，
# 通过它到达 u 的路径不可能更短。
#
# 因此：
#
#     当前距离最小的节点可以安全处理
#
# 如果边权可以为负，
# 这个结论就不成立，
# Dijkstra 也不能直接使用。
#
#
# 八、为什么要跳过旧状态
#
# 代码：
#
#     current_dist, u = heapq.heappop(heap)
#
#     if current_dist != dist[u]:
#         continue
#
# 一个节点可能多次进入堆。
#
# 例如先找到：
#
#     s 到 u 的距离是 10
#
# 就加入：
#
#     (10, u)
#
# 后来又找到更短的路径：
#
#     s 到 u 的距离是 5
#
# 再加入：
#
#     (5, u)
#
# Python 的 heapq 没有直接修改堆中旧元素优先级的操作，
# 所以旧的 (10, u) 还会留在堆里。
#
# 当 (5, u) 被取出后：
#
#     dist[u] = 5
#
# 之后取出旧状态 (10, u) 时：
#
#     current_dist = 10
#     dist[u] = 5
#
# 两者不相等，说明这是过期状态，
# 直接 continue 跳过即可。
#
# 这种做法叫“懒删除”。
#
#
# 九、Dijkstra 的完整流程
#
#     1. 建立有向图邻接表
#     2. dist[s] = 0，其余设为 INF
#     3. 把 (0, s) 放入小根堆
#     4. 取出当前距离最小的状态
#     5. 如果是旧状态，跳过
#     6. 遍历当前节点的所有出边
#     7. 对每条边进行松弛
#     8. 如果得到更短距离，就更新 dist 并入堆
#     9. 堆为空时结束
#
#
# 十、重边如何处理
#
# 两个点之间可能有多条边。
#
# 例如：
#
#     1 -> 2，权重 10
#     1 -> 2，权重 3
#
# 程序会把两条边都存进 graph[1]。
# 松弛时权重 3 的边会得到更短的结果，
# 最终 dist[2] 会保留正确的较小值。
#
# 因此不需要在建图时专门去重。
#
#
# 十一、复杂度分析
#
# 邻接表建图：
#
#     O(n + m)
#
# 使用二叉小根堆的 Dijkstra：
#
#     每次入堆和出堆是 O(log n)
#
# 每条边最多参与有限次松弛，
# 总时间复杂度是：
#
#     O((n + m) log n)
#
# 空间复杂度：
#
#     graph 保存 n 个节点和 m 条边
#     dist 保存 n 个距离
#     heap 最坏保存 O(m) 个状态
#
# 所以空间复杂度可以写作：
#
#     O(n + m)
#
#
# 十二、为什么不推荐本题使用 SPFA
#
# SPFA 在很多随机数据上可能表现不错，
# 但最坏情况下可能非常慢。
#
# P3371 题面也提醒可能出现构造数据，
# 让 SPFA 无法稳定通过。
#
# 因此本题应该把：
#
#     Dijkstra + 小根堆
#
# 作为正式模板。
