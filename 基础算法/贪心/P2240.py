import sys
# 部分背包问题，使用“单位重量价值最高优先”的贪心策略。

def main():
    input = sys.stdin.buffer.readline
    N,T = map(int, input().split())
    bag = []
    for _ in range(N):
        m,v = map(int, input().split())
        ratio = v/m
        bag.append((ratio,m,v))

    # 按单位重量价值从高到低降序排序
    bag.sort(reverse=True)

    total = 0
    remain = T
    for ratio,m,v in bag:
        if remain == 0:
            break

        if m <= remain:
            total += v
            remain -= m
        else:
            total += ratio*remain
            remain = 0
    sys.stdout.write(f"{total:.2f}\n")

if __name__ == '__main__':
    main()


# ============================================================
# 部分背包：算法理论、思路与实现细节
# ============================================================
#
# 一、题目模型
#
# 有 N 堆金币，第 i 堆金币的重量为 m_i，价值为 v_i。
# 背包最多承重 T。
#
# 与 0/1 背包不同，本题中的金币可以任意分割。
# 因此每一堆金币可以全部装入，也可以只装入其中一部分。
#
# 每堆金币的单位重量价值为：
#
#     ratio_i = v_i / m_i
#
# 表示每装入 1 单位重量的金币，可以获得多少价值。
#
#
# 二、为什么可以使用贪心
#
# 因为金币可以分割，
# 装入一堆金币的任意一部分时，
# 这一部分的单位价值仍然保持不变。
#
# 所以背包中的每一单位容量，
# 都应该优先用于单位价值最高的金币。
#
# 贪心策略是：
#
#     按单位重量价值从高到低排序；
#     依次尽可能多地装入金币；
#     如果剩余容量不足以装入整堆，
#     就装入这堆金币的一部分。
#
# 代码中的：
#
#     ratio = v / m
#     bag.append((ratio, m, v))
#     bag.sort(reverse=True)
#
# 正是在计算并按照单位价值降序排列。
#
#
# 三、装入过程
#
# `remain` 表示背包剩余容量。
#
# 如果当前金币重量 m 不超过剩余容量：
#
#     if m <= remain:
#         total += v
#         remain -= m
#
# 说明整堆金币可以装入。
#
# 如果当前金币重量超过剩余容量：
#
#     total += ratio * remain
#
# 只能装入当前金币的一部分。
#
# 由于金币可以分割，
# 装入重量为 remain 的部分，
# 能获得：
#
#     remain * (v / m)
#
# 的价值。
#
# 装完这部分后，背包已经没有剩余空间，
# 所以可以结束循环。
#
#
# 四、交换论证
#
# 假设当前背包中有一单位容量，
# 但它装的是单位价值较低的金币 A，
# 同时还有一单位价值更高的金币 B 没有装入。
#
# 设：
#
#     ratio_A < ratio_B
#
# 将这一单位容量中的金币 A 换成金币 B 后，
# 价值变化为：
#
#     ratio_B - ratio_A > 0
#
# 因此交换后不会增加重量，
# 但会增加总价值。
#
# 所以最优方案中不可能出现：
#
#     低单位价值金币已经装入，
#     高单位价值金币却还没有充分装入。
#
# 不断进行这种交换，
# 就能把任意最优方案调整为按单位价值从高到低装入的形式。
#
# 因此该贪心策略一定能得到最大价值。
#
#
# 五、为什么最后一堆可以只取一部分
#
# 假设当前剩余容量为 R，
# 当前金币整堆重量为 m，且：
#
#     m > R
#
# 因为金币可以分割，
# 可以取当前金币的 R / m 部分。
#
# 取走的重量为 R，
# 获得的价值为：
#
#     v * (R / m)
#
# 也可以写成：
#
#     (v / m) * R
#
# 代码中的：
#
#     total += ratio * remain
#
# 正是这个公式。
#
#
# 六、样例分析
#
# 背包容量：
#
#     T = 50
#
# 金币信息：
#
#     重量 10，价值 60，单位价值 6
#     重量 20，价值 100，单位价值 5
#     重量 25，价值 100，单位价值 4
#     重量 15，价值 45，单位价值 3
#
# 按单位价值排序后仍为：
#
#     6、5、4、3
#
# 装入过程：
#
#     装入第一堆：
#         使用重量 10，获得价值 60
#         剩余容量 40
#
#     装入第二堆：
#         使用重量 20，获得价值 100
#         剩余容量 20
#
#     第三堆重量为 25，只装入 20：
#         获得价值 20 * 4 = 80
#
# 总价值：
#
#     60 + 100 + 80 = 240
#
#
# 七、与 0/1 背包的区别
#
# 部分背包：
#
#     物品可以分割；
#     按单位价值排序；
#     使用贪心；
#     时间复杂度通常为 O(N log N)。
#
# 0/1 背包：
#
#     物品不能分割；
#     每件物品只能选或不选；
#     单位价值排序不能保证最优；
#     通常使用动态规划。
#
# 例如一个物品价值密度很高，
# 但它的重量可能太大，
# 直接选择它可能导致无法装入其他物品。
# 在不可分割的情况下，
# 不能简单地只看单位价值。
#
#
# 八、为什么相同单位价值的顺序不影响答案
#
# 如果两堆金币的单位价值相同，
# 那么先装哪一堆都不会影响最终价值。
#
# 设两堆金币单位价值都是 r，
# 总共装入重量为 w 的金币，
# 获得的价值始终为：
#
#     r * w
#
# 因此相同 ratio 的金币可以按任意顺序处理。
#
#
# 九、浮点数细节
#
# 代码使用：
#
#     ratio = v / m
#
# 得到浮点数单位价值。
#
# 题目要求输出两位小数，
# 因此最后使用：
#
#     f"{total:.2f}"
#
# 进行格式化。
#
# 在本题数据范围下，
# 使用浮点数计算足以满足输出精度要求。
#
#
# 十、算法流程
#
#     1. 读入每堆金币的重量和价值；
#     2. 计算每堆金币的单位重量价值；
#     3. 按单位价值从高到低排序；
#     4. 从前往后尽可能装入整堆金币；
#     5. 如果剩余容量不足，装入当前金币的一部分；
#     6. 背包装满或所有金币处理完毕后停止；
#     7. 输出总价值，保留两位小数。
#
#
# 十一、正确性直觉
#
# 背包容量是有限的，
# 每一单位容量都应该尽量放入能带来更高价值的金币。
#
# 如果某个方案把容量给了低单位价值金币，
# 却没有充分利用高单位价值金币，
# 就可以交换一部分金币并增加总价值。
#
# 所以最优方案一定具有这样的结构：
#
#     单位价值高的金币全部或尽量多地装入；
#     单位价值低的金币只在前面的金币装完后再考虑。
#
# 这正是按单位价值降序装入的贪心策略。
#
#
# 十二、复杂度分析
#
# 计算单位价值需要：
#
#     O(N)
#
# 排序需要：
#
#     O(N log N)
#
# 排序后扫描所有金币需要：
#
#     O(N)
#
# 因此总时间复杂度为：
#
#     O(N log N)
#
# `bag` 保存所有金币信息，
# 空间复杂度为：
#
#     O(N)
