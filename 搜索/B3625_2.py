# DFS 版：理解递归搜索
# BFS 版：理解队列搜索
# BFS：适合求最短路
# DFS：适合判断是否存在路径
import sys

sys.setrecursionlimit(10**6)

def main():
    input = sys.stdin.readline
    n, m = map(int, input().split())
    data = [input().strip() for _ in range(n)]
    visited = [[False]*m for _ in range(n)]

    directions = [(0,1),(0,-1),(1,0),(-1,0)]

    def dfs(x,y):
        # 1. 递归终止条件
        if x == n-1 and y == m-1:
            return True

        # 2.标记当前状态
        visited[x][y] = True

        # 3.枚举下一步选择
        for dx,dy in directions:
            nx = x + dx
            ny = y + dy

            # 4.做选择(处理冲突)
            if not (0<=nx<n and 0<=ny<m):
                continue
            if data[nx][ny] == '#':
                continue
            if visited[nx][ny]:
                continue

            # 5.递归
            if dfs(nx,ny):
                return True

            # (6.撤销选择)

        return False

    if dfs(0,0):
        sys.stdout.write('Yes')
    else:
        sys.stdout.write('No')


if __name__ == '__main__':
    main()


# ==================== DFS 理论、算法思路与细节 ====================
#
# 一、DFS 是什么
#
# DFS 是 Depth-First Search 的缩写，中文是“深度优先搜索”。
#
# 它的基本思想是：
#
#     从当前状态出发，选择一条路继续深入；
#     如果这条路走不通，就返回上一层；
#     再尝试其他选择。
#
# 对本题来说：
#
#     每个空地可以看成一个状态；
#     上、下、左、右四个方向就是下一步的选择。
#
#
# 二、本题的搜索目标
#
# 机器猫从：
#
#     (0, 0)
#
# 出发，判断能否到达：
#
#     (n - 1, m - 1)
#
# 输入中的坐标从 1 开始，
# 程序中使用从 0 开始的下标，
# 所以：
#
#     输入的 (1, 1)     -> 程序中的 (0, 0)
#     输入的 (n, m)     -> 程序中的 (n - 1, m - 1)
#
#
# 三、递归函数 dfs(x, y) 的含义
#
# 本程序中：
#
#     dfs(x, y)
#
# 表示：
#
#     从位置 (x, y) 出发，
#     能否走到终点。
#
# 它返回一个布尔值：
#
#     True  ：可以到达终点
#     False ：无法到达终点
#
# 设计递归函数时，首先要明确：
#
#     函数参数表示什么；
#     函数返回什么。
#
# 这里参数是当前位置，
# 返回值是“能否到达终点”。
#
#
# 四、为什么先写终止条件
#
# 递归函数必须知道什么时候停止继续调用自己。
#
# 代码：
#
#     if x == n - 1 and y == m - 1:
#         return True
#
# 表示：
#
#     如果当前位置已经是终点，
#     说明找到了一条可行路径，
#     直接返回 True。
#
# 递归函数通常优先写终止条件，
# 因为它相当于递归的出口。
#
# 如果没有终止条件，
# 函数就会不断调用自己，最终导致无限递归。
#
#
# 五、visited 数组的作用
#
#     visited[x][y]
#
# 表示位置 (x, y) 是否已经搜索过。
#
# 进入一个位置后：
#
#     visited[x][y] = True
#
# 这样可以避免重复搜索。
#
# 迷宫中可能存在环，例如：
#
#     A -> B -> C -> A
#
# 如果不记录 visited，
# DFS 可能在这些位置之间无限循环。
#
# 本题只是判断是否存在路径，
# 所以某个位置搜索过一次后，
# 不需要再次从它出发搜索。
#
#
# 六、为什么先标记当前位置
#
# 代码中：
#
#     visited[x][y] = True
#
# 写在枚举方向之前。
#
# 原因是：
#
#     当前节点已经进入搜索过程，
#     后续路径不能再把它当成新节点重复进入。
#
# 如果把标记放到递归返回之后，
# 相邻位置可能会在当前递归过程中再次走回当前位置，
# 从而产生循环。
#
#
# 七、枚举四个方向
#
#     directions = [
#         (0, 1),
#         (0, -1),
#         (1, 0),
#         (-1, 0)
#     ]
#
# 每个二元组表示：
#
#     (行坐标变化量, 列坐标变化量)
#
# 例如：
#
#     (0, 1)   向右
#     (0, -1)  向左
#     (1, 0)   向下
#     (-1, 0)  向上
#
# 当前坐标为 (x, y) 时，
# 下一位置为：
#
#     nx = x + dx
#     ny = y + dy
#
#
# 八、为什么要进行三种判断
#
# 第一种：判断是否越界
#
#     if not (0 <= nx < n and 0 <= ny < m):
#         continue
#
# 下一位置必须在迷宫范围内。
#
#
# 第二种：判断是不是墙
#
#     if data[nx][ny] == '#':
#         continue
#
# 墙不能进入。
#
#
# 第三种：判断是否访问过
#
#     if visited[nx][ny]:
#         continue
#
# 已经搜索过的位置不需要重复进入。
#
# 只有满足以下条件时，才递归进入下一格：
#
#     没有越界
#     不是墙
#     没有访问过
#
#
# 九、递归调用与回传答案
#
# 代码：
#
#     if dfs(nx, ny):
#         return True
#
# 含义是：
#
#     如果从下一位置出发能够到达终点，
#     那么从当前位置也一定能够到达终点，
#     直接把 True 返回给上一层。
#
# 例如：
#
#     dfs(A)
#       -> dfs(B)
#            -> dfs(C)
#                 -> 找到终点
#
# 最底层返回 True，
# 然后每一层都继续返回 True：
#
#     C 返回 True
#     B 返回 True
#     A 返回 True
#
# 这叫做递归结果的逐层回传。
#
#
# 十、为什么所有方向都失败后返回 False
#
# 如果当前位置不是终点，
# 并且四个方向都满足以下情况之一：
#
#     越界
#     是墙
#     已经访问过
#     递归搜索失败
#
# 那么从当前位置就没有可行路径。
#
# 所以最后执行：
#
#     return False
#
#
# 十一、DFS 的完整执行框架
#
# 本题的 DFS 可以概括为：
#
#     dfs(当前位置):
#         如果到达终点:
#             返回 True
#
#         标记当前位置
#
#         枚举所有可能方向:
#             如果方向不合法:
#                 跳过
#
#             如果从下一位置能到达终点:
#                 返回 True
#
#         所有方向都失败:
#             返回 False
#
#
# 十二、这里的递归体现在哪里
#
# 代码：
#
#     dfs(nx, ny)
#
# 表示：
#
#     当前问题“从 (x, y) 能否到达终点”，
#     被拆成了更小的问题：
#     “从相邻位置 (nx, ny) 能否到达终点”。
#
# 每次递归调用都会进入更深的一层迷宫位置。
#
# 当遇到终点或没有可走方向时，
# 递归停止并返回。
#
#
# 十三、这里的回溯体现在哪里
#
# 当某个方向搜索失败时：
#
#     dfs(nx, ny) 返回 False
#
# 程序会回到当前函数，
# 继续尝试 directions 中的下一个方向。
#
# 过程就是：
#
#     选择一个方向
#     ↓
#     递归深入
#     ↓
#     发现走不通
#     ↓
#     返回上一层
#     ↓
#     尝试下一个方向
#
# 这就是回溯。
#
# 不过本题的回溯不需要撤销 visited，
# 因为 visited 表示“这个位置已经完整搜索过或正在搜索”，
# 重复搜索它没有意义。
#
# 在八皇后、选数等问题中，
# 回溯通常还需要：
#
#     做选择
#     递归
#     撤销选择
#
# 而本题只需要记录已经访问过的迷宫位置。
#
#
# 十四、递归、搜索、回溯三者的关系
#
# 递归是一种编程形式：
#
#     函数调用自己。
#
# DFS 是一种搜索策略：
#
#     优先沿一条路径深入。
#
# 回溯是一种搜索过程：
#
#     做出选择，深入尝试，失败后返回并换选择。
#
# 本题同时体现了：
#
#     递归：dfs 调用 dfs
#     DFS：先沿一个方向深入
#     回溯：失败后返回上一层尝试其他方向
#
#
# 十五、为什么本题 DFS 可以解决
#
# 本题只要求：
#
#     是否存在一条从起点到终点的路径。
#
# DFS 会搜索所有从起点可达的位置。
#
# 如果终点可达，
# DFS 一定会搜索到终点并返回 True。
#
# 如果终点不可达，
# 所有可达位置都会被搜索完，
# 最终返回 False。
#
# 因此 DFS 能正确判断路径是否存在。
#
# 但是，如果题目要求最短步数，
# DFS 就不是最合适的算法，
# 应该使用 BFS。
#
#
# 十六、复杂度
#
# 每个位置最多访问一次，
# 每个位置最多检查四个方向。
#
# 因此时间复杂度为：
#
#     O(n * m)
#
# visited 数组需要：
#
#     O(n * m)
#
# 递归调用栈最深可能达到：
#
#     O(n * m)
#
# 所以空间复杂度为：
#
#     O(n * m)
#
#
# 十七、DFS 通用递归范式
#
#     def dfs(state):
#         # 1. 递归终止条件
#         if state 满足目标:
#             return 结果
#
#         # 2. 标记当前状态
#         mark(state)
#
#         # 3. 枚举下一步选择
#         for choice in choices:
#             if choice 不合法:
#                 continue
#
#             # 4. 递归进入下一层
#             result = dfs(next_state)
#
#             # 5. 如果找到答案，向上返回
#             if result:
#                 return result
#
#         # 6. 所有选择都失败
#         return 失败结果
#
#
# 十八、带撤销操作的回溯范式
#
#     def dfs(state):
#         if state 满足结束条件:
#             记录答案
#             return
#
#         for choice in choices:
#             if choice 不合法:
#                 continue
#
#             做选择
#             dfs(next_state)
#             撤销选择
#
# 本题中的“选择”是走向某个相邻空地；
# “递归”是继续搜索；
# “失败后回到上一层并尝试其他方向”
# 就是回溯的体现。
