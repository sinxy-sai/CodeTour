import sys
# 二分答案 最大可行值

def main():
    input = sys.stdin.buffer.readline
    n,k = map(int,input().split())

    data = []
    for _ in range(n):
        data.append(int(input()))

    left = 0
    right = max(data) + 1

    def check(h):
        total = 0
        for L in data:
            total += L // h
            if total >= k:
                return True
        return False
        

    while right - left > 1:
        mid = (left + right) // 2
        if check(mid):
            left = mid
        else:
            right = mid

    sys.stdout.buffer.write(str(left).encode())

if __name__ == '__main__':
    main()


# ============================================================
# 二分答案：算法理论、思路与实现细节
# ============================================================
#
# 一、题目要求
#
# 有 n 根木头，需要切出至少 k 段长度相同的小木段。
# 要求小木段的长度尽可能大。
#
# 设每一段小木段的长度为 length。
# 对于长度为 L 的原木，可以切出的完整小木段数量为：
#
#     L // length
#
# 因为只计算完整的小木段，剩余不足 length 的部分不能使用。
#
#
# 二、可行性判断
#
# 固定一个候选长度 length 后，所有木头能够切出的总段数为：
#
#     pieces(length) =
#         data[0] // length
#         + data[1] // length
#         + ...
#         + data[n - 1] // length
#
# 如果：
#
#     pieces(length) >= k
#
# 说明长度为 length 时可以切出至少 k 段，
# 因此 length 是一个可行答案。
#
# 代码中的 check 函数正是在判断这个条件：
#
#     def check(h):
#         total = 0
#         for L in data:
#             total += L // h
#             if total >= k:
#                 return True
#         return False
#
# 当 total 已经达到 k 时，可以提前返回 True，
# 因为后面的木头不会让“至少 k 段”这个结论变成 False。
#
#
# 三、为什么可以使用二分答案
#
# 本题要求的是最大的可行长度，
# 候选答案范围为：
#
#     1 <= length <= max(data)
#
# 直接枚举每一种长度，需要 O(max(data)) 次判断，
# 可能比较慢。
#
# 观察 length 的变化：
#
#     length 越大，每根木头能切出的段数越少或不变；
#     length 越小，每根木头能切出的段数越多或不变。
#
# 因此 pieces(length) 是关于 length 的单调不增函数。
#
# 可行性具有如下形式：
#
#     较短的长度：可行
#     较长的长度：可行
#     超过某个分界点后：不可行
#
# 题目要求的就是最后一个可行长度，
# 所以可以对答案 length 进行二分。
#
#
# 四、二分边界的设计
#
# 代码使用：
#
#     left = 0
#     right = max(data) + 1
#
# 这里的两个边界分别表示：
#
#     left：当前已知的可行边界；
#     right：一定不可行的边界。
#
# right 为什么一定不可行？
#
# 当 length = max(data) + 1 时，
# 它比所有木头都长，每根木头都切不出完整的小段，
# 所以总段数为 0。
#
# 由于 k >= 1，因此 right 一定不可行。
#
# left = 0 是一个虚拟边界。
# 实际切割长度不能为 0，但它用于表示：
#
#     如果连长度为 1 的小段都切不出来，
#     最终答案可以是 0。
#
# 注意：程序不会调用 check(0)。
# 因为初始 right >= 2，
# 且循环中 mid 始终大于 0。
#
#
# 五、循环不变量
#
# 二分过程中始终维护：
#
#     答案不会大于 right；
#     所有已经确认可行的答案都不大于 left；
#     right 本身一定不可行。
#
# 更直观地说，答案位于 left 和 right 之间，
# 并且最终希望把它们缩小到相邻位置：
#
#     right = left + 1
#
# 这时 left 就是最大的可行长度。
#
#
# 六、为什么可行时使用 left = mid
#
# 代码：
#
#     if check(mid):
#         left = mid
#     else:
#         right = mid
#
# 如果 mid 可行，mid 本身可能就是最大答案，
# 不能把它排除，所以保留 mid：
#
#     left = mid
#
# 如果 mid 不可行，那么 mid 以及比 mid 更大的长度都不可能切出
# 至少 k 段，因此：
#
#     right = mid
#
# 由于 right 表示不可行边界，mid 也可以作为新的 right。
#
#
# 七、为什么循环条件是 right - left > 1
#
# 当：
#
#     right - left == 1
#
# 例如：
#
#     left = 114   # 可行
#     right = 115  # 不可行
#
# 两个边界已经相邻，114 必然是最后一个可行长度，
# 不需要继续搜索。
#
# 如果写成：
#
#     while right > left:
#
# 那么在 left 和 right 相邻时，
# 可能出现：
#
#     mid = (left + right) // 2 = left
#
# 如果 mid 可行，再执行 left = mid，
# left 不会改变，从而可能死循环。
#
# 因此这种边界写法要使用：
#
#     while right - left > 1:
#
#
# 八、为什么不能把 left 初始化为 1
#
# 如果长度为 1 也无法切出 k 段，
# 正确答案应该是 0。
#
# 例如：
#
#     n = 1
#     k = 2
#     data = [1]
#
# 长度为 1 的木头只能切出 1 段，
# 无法得到 2 段，所以答案为 0。
#
# 如果写成：
#
#     left = 1
#
# 程序会把 1 当作默认答案，可能错误输出 1。
#
# 因此必须使用：
#
#     left = 0
#
# 来正确表示“没有任何正整数长度可行”的情况。
#
#
# 九、样例分析
#
# 木头长度为：
#
#     232, 124, 456
#
# 需要切出：
#
#     k = 7
#
# 尝试 length = 114：
#
#     232 // 114 = 2
#     124 // 114 = 1
#     456 // 114 = 4
#
# 总段数：
#
#     2 + 1 + 4 = 7
#
# 所以 114 可行。
#
# 尝试 length = 115：
#
#     232 // 115 = 2
#     124 // 115 = 1
#     456 // 115 = 3
#
# 总段数：
#
#     2 + 1 + 3 = 6
#
# 小于 7，所以 115 不可行。
#
# 因此最大可行长度为 114。
#
#
# 十、与 P1873 的区别
#
# P1873 是按照高度 H 切树：
#
#     一棵树贡献 max(0, tree_height - H) 米木材
#
# P2440 是把原木切成长度相等的小段：
#
#     一根木头贡献 L // length 段
#
# 两题都使用二分答案，是因为它们都有单调性：
#
#     P1873：锯片高度越高，得到的木材越少；
#     P2440：小段长度越长，切出的段数越少。
#
# 但 check 函数的计算方式不同。
#
#
# 十一、算法流程
#
#     1. 读入 n、k 和 n 根木头的长度；
#     2. 将 left 设为 0；
#     3. 将 right 设为 max(data) + 1；
#     4. 计算中间长度 mid；
#     5. 统计每根木头能切出的完整段数；
#     6. 如果总段数不少于 k，说明 mid 可行，增大 left；
#     7. 否则 mid 不可行，减小 right；
#     8. 当 right - left == 1 时停止；
#     9. 输出 left。
#
#
# 十二、正确性直觉
#
# check(length) 计算了固定长度 length 下的总段数，
# 因而能够正确判断 length 是否满足题目要求。
#
# 由于长度越长，能够切出的段数不会增加，
# 所有可行长度一定集中在较小的一侧，
# 所有不可行长度集中在较大的一侧。
#
# 二分始终保留答案所在的范围，
# 并且每次排除一半不可能的长度。
# 最终 left 与 right 相邻，
# left 就是最大的可行长度。
#
#
# 十三、复杂度分析
#
# 设最长木头的长度为 L_max。
#
# 二分的次数为：
#
#     O(log L_max)
#
# 每次 check 都遍历 n 根木头，
# 所以总时间复杂度为：
#
#     O(n log L_max)
#
# 保存所有木头长度需要：
#
#     O(n)
#
# 二分过程只使用常数个额外变量，
# 因此额外空间复杂度为：
#
#     O(1)
