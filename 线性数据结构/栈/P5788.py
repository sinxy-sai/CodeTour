# 单调栈 找每个位置右边第一个比它大的数的下标。
# 栈里是单调递减的，到栈顶前。
import sys

def main():
    n = int(sys.stdin.buffer.readline())

    data = list(map(int,sys.stdin.buffer.readline().split()))

    out = [0]*n
    stack = []

    for i,x in enumerate(data):
        # 维护最大值栈，栈顶到栈底是单调递减的
        while stack and data[stack[-1]] < x:
            idx = stack.pop()
            out[idx] = i+1

        stack.append(i)

    sys.stdout.write(' '.join(map(str,out)))

if __name__ == '__main__':
    main()


# 思路说明：
#
# 一、题目要做什么
#
# 对每个位置 i，要求找到它右边第一个比 data[i] 大的数的位置。
#
# 例如：
#
#     data = [1, 4, 2, 3, 5]
#
# 对第 1 个数 1 来说，右边第一个比它大的是 4，
# 4 的位置是 2，所以答案是 2。
#
# 对第 3 个数 2 来说，右边第一个比它大的是 3，
# 3 的位置是 4，所以答案是 4。
#
# 如果右边没有比它大的数，答案就是 0。
#
#
# 二、为什么不能暴力
#
# 最直接的想法是：
#
#     for i in range(n):
#         从 i + 1 一直往右找第一个比 data[i] 大的数
#
# 这种做法最坏是 O(n^2)。
#
# 如果序列是：
#
#     5 4 3 2 1
#
# 每个数右边都没有更大的数，
# 每个位置都要一路扫到结尾。
#
# 这题 n 最大是 3 * 10^6，
# O(n^2) 一定过不了。
#
#
# 三、单调栈的核心想法
#
# 栈里保存的是：
#
#     还没有找到“右边第一个更大元素”的位置下标
#
# 从左到右扫描数组。
# 当前扫描到的位置是 i，当前值是 x = data[i]。
#
# 如果栈顶位置 stack[-1] 对应的值比 x 小：
#
#     data[stack[-1]] < x
#
# 说明当前这个 x 就是栈顶位置右边第一个更大的数。
#
# 为什么是“第一个”？
#
# 因为我们是从左到右扫描的。
# 栈顶位置在之前已经入栈，
# 从它入栈之后到当前 i 之前，
# 如果中间出现过更大的数，它早就被弹出并记录答案了。
# 现在第一次遇到能让它弹出的 x，
# 那么 x 的下标 i + 1 就是它的答案。
#
# 所以可以：
#
#     idx = stack.pop()
#     out[idx] = i + 1
#
# 注意：
# 本程序里 i 是 Python 的 0-based 下标，
# 题目要求输出的是 1-based 下标，
# 所以答案要写 i + 1。
#
#
# 四、为什么叫“单调栈”
#
# 栈里保存的是下标。
# 这些下标对应的值，从栈底到栈顶保持单调不增。
#
# 也就是说，如果栈里是：
#
#     [p1, p2, p3]
#
# 那么大致满足：
#
#     data[p1] >= data[p2] >= data[p3]
#
# 因为只要当前 x 比栈顶元素大，
# 栈顶就可以确定答案并被弹出。
# 弹到栈顶不再小于 x 为止，才把当前 i 入栈。
#
# 所以这个栈维护的是一个“等待被右边更大元素解决”的下降序列。
#
#
# 五、用样例走一遍
#
# 输入：
#
#     1 4 2 3 5
#
# i = 0, x = 1
# 栈空，0 入栈。
#
#     stack = [0]
#
# i = 1, x = 4
# data[0] = 1 < 4，
# 所以 0 号位置的答案是 2。
# 弹出 0，再把 1 入栈。
#
#     out[0] = 2
#     stack = [1]
#
# i = 2, x = 2
# data[1] = 4 不小于 2，
# 2 号位置入栈。
#
#     stack = [1, 2]
#
# i = 3, x = 3
# data[2] = 2 < 3，
# 所以 2 号位置的答案是 4。
# 然后 data[1] = 4 不小于 3，
# 3 号位置入栈。
#
#     out[2] = 4
#     stack = [1, 3]
#
# i = 4, x = 5
# data[3] = 3 < 5，
# 所以 3 号位置的答案是 5。
# data[1] = 4 < 5，
# 所以 1 号位置的答案也是 5。
# 最后 4 号位置入栈。
#
#     out[3] = 5
#     out[1] = 5
#     stack = [4]
#
# 扫描结束后，栈里剩下的位置说明右边没有更大的数，
# 它们的答案保持初始值 0。
#
#
# 六、程序细节
#
#     data = list(map(int, sys.stdin.buffer.readline().split()))
#
# 读入整个数列。
#
#     out = [0] * n
#
# 答案数组先全设为 0。
# 如果某个位置一直没有被更大的数弹出，
# 它的答案自然就是 0。
#
#     stack = []
#
# 栈里存下标，不直接存值。
# 因为最后要给对应位置 out[idx] 填答案，
# 所以必须知道原位置 idx。
#
#     while stack and data[stack[-1]] < x:
#
# 只要当前值 x 大于栈顶位置的值，
# 就说明栈顶位置找到了答案。
#
#     stack.append(i)
#
# 当前 i 还没找到右边更大的元素，
# 扫描到它时只是用它解决前面的人，
# 它自己的答案要等未来更大的数来解决，
# 所以最后把 i 入栈。
#
#
# 七、时间复杂度
#
# 每个位置最多入栈一次：
#
#     stack.append(i)
#
# 每个位置最多出栈一次：
#
#     stack.pop()
#
# 所以虽然代码里有 while，
# 但所有 while 弹出的总次数不会超过 n。
#
# 总时间复杂度是：
#
#     O(n)
#
#
# 八、空间复杂度
#
# 本程序使用了：
#
#     data   存原数组，长度 n
#     out    存答案，长度 n
#     stack  最坏情况下存 n 个下标
#
# 所以空间复杂度是：
#
#     O(n)
#
# 但是要注意：
# Python 的普通 list 里存的是 Python int 对象引用，
# 内存开销比 C++ 的 int 数组大很多。
#
# 因此这个写法算法复杂度是正确的，
# 但在 n = 3 * 10^6 的极限数据下，
# 可能因为 data、out、stack 三个大 list 导致部分测试点 MLE。
#
# 如果要进一步省内存，可以用 array 模块，
# 或者不保存完整 data，把栈改成同时保存“下标和值”。
