#  欧拉路径 Hierholzer算法
import sys

# 欧拉路径是：
# 经过图中每条边恰好一次的路径。
# 如果最后回到起点，则称为欧拉回路。
def main():
    data = map(int,sys.stdin.buffer.read().split())
    it = iter(data)
    n = next(it)
    m = next(it)
    graph = [[] for _ in range(n+1)]

    in_degree = [0] * (n+1)
    out_degree = [0] * (n+1)

    for _ in range(m):
        u = next(it)
        v = next(it)
        graph[u].append(v)
        in_degree[v] += 1
        out_degree[u] += 1

    # 判断度数条件并确定起点
    start = -1
    open_path = False

    for vertex in range(1,n+1):
        diff = out_degree[vertex] - in_degree[vertex]

        if diff == 1:
            # 欧拉路径起点
            if open_path or start != -1:
                sys.stdout.write("No")
                return

            start = vertex
            open_path = True

        elif diff == -1:
            continue

        elif diff != 0:
            sys.stdout.write("No")
            return

    if open_path:
        # 必须有一个终点
        end_count = 0
        for vertex in range(1,n+1):
            if out_degree[vertex] - in_degree[vertex] == -1:
                end_count += 1

        if end_count != 1:
            sys.stdout.write("No")
            return
    else:
        # 欧拉回路 所有顶点的入度和出度必须相等
        # 起点选择有出边的最小编号顶点
        for vertex in range(1,n+1):
            if out_degree[vertex] > 0:
                start = vertex
                break

    if start == -1:
        sys.stdout.write('1')
        return
    
    # 降序排列 pop时得到最小的边
    for vertex in range(1,n+1):
        graph[vertex].sort(reverse=True)
        
    # Hierholzer算法
    stack = [start]
    path = []
    while stack:
        u = stack[-1]
        if graph[u]:
            # 取当前最小的出边
            v = graph[u].pop()
            stack.append(v)
        else:
            # 当前点没有未使用的边，加入答案
            path.append(stack.pop())
    # 答案逆序输出
    path.reverse()
    if len(path) != m+1:
        sys.stdout.write("No")
        return
    
    sys.stdout.write(' '.join(map(str,path)))

if __name__ == '__main__':
    main()


# ============================================================
# 欧拉路径：算法理论、思路与实现细节
# ============================================================
#
# 一、什么是欧拉路径
#
# 欧拉路径是经过图中每条边恰好一次的路径。
#
# 注意：
#
#     欧拉路径限制的是“边”不能重复；
#     顶点可以重复经过。
#
# 如果欧拉路径的起点和终点相同，
# 就称为欧拉回路。
#
# 例如：
#
#     1 -> 2 -> 3 -> 1
#
# 每条边都只经过一次，
# 并且最后回到 1，
# 所以这是一条欧拉回路。
#
#
# 二、有向图中的入度和出度
#
# 对有向图中的顶点 v：
#
#     入度：进入 v 的边数；
#     出度：从 v 出发的边数。
#
# 代码使用：
#
#     in_degree[v]
#     out_degree[v]
#
# 分别记录入度和出度。
#
#
# 三、为什么欧拉路径要满足度数条件
#
# 假设正在经过一个中间顶点 v。
#
# 每次进入 v 后，
# 除非 v 是终点，
# 否则还必须从 v 离开。
#
# 因此对普通中间顶点：
#
#     入度 = 出度
#
# 如果是欧拉路径的起点，
# 一开始可以直接离开而不需要先进入，
# 所以：
#
#     出度 = 入度 + 1
#
# 如果是欧拉路径的终点，
# 最后需要进入但不再离开，
# 所以：
#
#     入度 = 出度 + 1
#
#
# 四、有向图存在欧拉路径的度数条件
#
# 普通欧拉路径：
#
#     恰好一个顶点满足：
#         出度 = 入度 + 1
#
#     恰好一个顶点满足：
#         入度 = 出度 + 1
#
#     其他顶点满足：
#         入度 = 出度
#
# 欧拉回路：
#
#     所有顶点都满足：
#         入度 = 出度
#
# 代码中使用：
#
#     diff = out_degree[vertex] - in_degree[vertex]
#
# 对合法图来说，diff 只能是：
#
#     1：欧拉路径起点；
#     -1：欧拉路径终点；
#     0：中间点或欧拉回路中的点。
#
# 如果出现其他差值，
# 说明不可能存在欧拉路径。
#
#
# 五、为什么要确定起点
#
# 如果存在普通欧拉路径，
# 起点必须是满足：
#
#     出度 - 入度 = 1
#
# 的顶点。
#
# 如果是欧拉回路，
# 所有顶点入度等于出度，
# 任意有出边的顶点都可以作为起点。
#
# 但题目要求字典序最小，
# 所以欧拉回路应选择编号最小的有出边顶点。
#
# 代码：
#
#     for vertex in range(1, n + 1):
#         if out_degree[vertex] > 0:
#             start = vertex
#             break
#
# 因为顶点是从小到大枚举，
# 第一个找到的就是最小起点。
#
#
# 六、什么是 Hierholzer 算法
#
# Hierholzer 算法用于在线性时间内构造欧拉路径或欧拉回路。
#
# 基本过程：
#
#     1. 从起点出发；
#     2. 沿着还没有使用过的边继续走；
#     3. 如果当前顶点没有未使用的出边，
#        就把当前顶点加入答案；
#     4. 回退到上一个顶点；
#     5. 继续处理剩余的边；
#     6. 最后反转答案。
#
# 这里的“回退”不是重新使用边，
# 而是回到搜索栈中的上一个顶点，
# 继续寻找它的其他未使用出边。
#
#
# 七、为什么使用栈
#
# 递归版 Hierholzer 可以写成：
#
#     dfs(u):
#         while u 还有未使用的边:
#             v = 取出一条边 u -> v
#             dfs(v)
#         answer.append(u)
#
# 但是 m 最大为 2 * 10^5，
# 深度递归可能导致递归层数过深。
#
# 因此代码使用显式栈：
#
#     stack = [start]
#
# 栈顶：
#
#     stack[-1]
#
# 表示当前正在处理的顶点。
#
# 继续沿边走：
#
#     stack.append(v)
#
# 当前点没有边可走时回退：
#
#     path.append(stack.pop())
#
# 这与递归函数返回时执行：
#
#     answer.append(u)
#
# 是等价的。
#
#
# 八、为什么顶点是在“无边可走”时加入答案
#
# 假设当前路径为：
#
#     1 -> 2 -> 3
#
# 如果 3 没有未使用的边，
# 3 必须最后出现在这段路径中，
# 所以先把 3 放入答案。
#
# 然后回退到 2：
#
#     2 -> 3
#
# 再把 2 放入答案。
#
# 最初得到的顺序是：
#
#     3, 2, 1
#
# 所以最后需要反转：
#
#     1, 2, 3
#
# 代码：
#
#     path.reverse()
#
# 就是完成这个逆序恢复。
#
#
# 九、为什么要先降序排序
#
# 题目要求输出字典序最小的欧拉路径。
#
# 我们希望每次选择当前顶点最小编号的出边。
#
# 但是 Python 的：
#
#     list.pop()
#
# 默认删除最后一个元素。
#
# 因此把邻接表降序排列：
#
#     graph[vertex].sort(reverse=True)
#
# 例如：
#
#     graph[u] = [5, 3, 2]
#
# 执行：
#
#     graph[u].pop()
#
# 依次得到：
#
#     2、3、5
#
# 也就是每次取最小编号的出边。
#
# 这样可以在线性构造过程中保证字典序最小。
#
#
# 十、为什么不能简单地贪心走最小边
#
# 不能只写成：
#
#     每次走当前最小的边
#
# 然后走到不能走为止。
#
# 因为当前最小的边可能会把某些必须经过的边提前封死，
# 导致还剩边没有办法继续连接。
#
# Hierholzer 算法的关键是：
#
#     先沿未使用边深入；
#     无法继续时再加入答案；
#     回退后继续拼接剩余路径。
#
# 这种“后序加入答案”的方式，
# 既能使用所有边，
# 又能结合邻接表顺序得到字典序最小结果。
#
#
# 十一、为什么最后要检查 `len(path) == m + 1`
#
# 一条经过 m 条边的路径，
# 必须包含 m + 1 个顶点。
#
# 因此合法答案应该满足：
#
#     len(path) = m + 1
#
# 如果长度不足，
# 说明还有边没有被访问到。
#
# 题目保证把有向边看成无向边后图连通，
# 所以主要只需要检查度数条件。
# 但长度检查仍然可以作为最终正确性验证。
#
#
# 十二、题目为什么说 m 不是图的边数
#
# 输入中每一行给出一条信息：
#
#     u v w
#
# 当 w >= 0 时，
# 它表示两条有向边：
#
#     u -> v
#     v -> u
#
# 但 P7771 的输入格式本身直接给出一条有向边 u -> v，
# 所以代码每次只添加：
#
#     graph[u].append(v)
#
# 这里的 m 就是输入中有向边的条数。
#
# 如果是其他题目规定非负边权自动生成反向边，
# 才需要额外添加 graph[v]。
#
#
# 十三、算法流程
#
#     1. 读入 n、m；
#     2. 建立邻接表；
#     3. 统计每个顶点的入度和出度；
#     4. 根据度数条件判断是否可能存在欧拉路径；
#     5. 确定起点；
#     6. 将每个邻接表降序排列；
#     7. 使用栈执行 Hierholzer 算法；
#     8. 反转得到的顶点序列；
#     9. 检查序列长度是否为 m + 1；
#    10. 输出答案。
#
#
# 十四、复杂度分析
#
# 统计入度和出度需要：
#
#     O(m)
#
# 对所有邻接表排序的总复杂度为：
#
#     O(sum(deg(v) * log(deg(v))))
#
# 最坏可以写成：
#
#     O(m log m)
#
# Hierholzer 算法中每条边只会被取出一次，
# 每个顶点也会进出栈若干次，
# 所以遍历复杂度为：
#
#     O(n + m)
#
# 总时间复杂度为：
#
#     O(n + m log m)
#
# 邻接表、度数数组、栈和答案需要：
#
#     O(n + m)
#
# 的空间复杂度。
