import sys
# 经典的区间调度问题，按照结束时间排序的贪心策略

def main():
    input = sys.stdin.buffer.readline
    n = int(input())
    data = []
    for _ in range(n):
        begin,end = map(int,input().split())
        data.append((begin,end))

    # 按比赛结束时间升序排列
    data.sort(key=lambda x:x[1])

    cnt = 0
    last_end = -1
    for begin,end in data:
        # 上一场结束可以参加下一场
        if begin >= last_end:
            cnt += 1
            last_end = end

    sys.stdout.buffer.write(f'{cnt}'.encode())
    

if __name__ == '__main__':
    main()


# ============================================================
# 区间调度：算法理论、思路与实现细节
# ============================================================
#
# 一、题目模型
#
# 每场比赛可以看作一个时间区间：
#
#     [begin, end)
#
# 参加一场比赛必须从开始时间一直参加到结束时间，
# 因此两场比赛不能有时间重叠。
#
# 如果上一场比赛在 last_end 结束，
# 下一场比赛在 begin 开始，
# 那么只有：
#
#     begin >= last_end
#
# 时，下一场比赛才可以参加。
#
# begin == last_end 也可以参加，
# 因为上一场比赛已经结束，下一场比赛恰好开始。
#
#
# 二、题目要求的优化目标
#
# 题目要求参加的比赛数量最多。
#
# 这不是按照比赛总时长最大，
# 也不是按照比赛开始时间最早，
# 而是要在互不冲突的前提下选择最多的区间。
#
# 这是经典的区间调度问题。
#
#
# 三、贪心策略
#
# 将所有比赛按照结束时间从小到大排序：
#
#     data.sort(key=lambda x: x[1])
#
# 然后从前往后扫描：
#
#     如果当前比赛的开始时间 begin >= last_end，
#     就参加当前比赛。
#
# 也就是：
#
#     每次选择当前能够参加的、结束时间最早的比赛。
#
# 选择一场结束更早的比赛，
# 可以给后面的比赛留下更多时间，
# 从而为后续选择创造更多机会。
#
#
# 四、为什么不能只按开始时间排序
#
# 例如有以下比赛：
#
#     [1, 100]
#     [2, 3]
#     [3, 4]
#
# 如果按开始时间排序，
# 可能先选择 [1, 100]，
# 之后无法参加其他比赛，只能参加 1 场。
#
# 如果优先选择结束时间最早的比赛：
#
#     [2, 3]
#     [3, 4]
#
# 就可以参加 2 场。
#
# 所以“开始得早”不代表“更优”，
# 真正重要的是尽早结束当前比赛。
#
#
# 五、交换论证
#
# 假设当前时刻为 current，
# 在所有可以参加的比赛中，
# 贪心选择了结束时间最早的比赛 G。
#
# 设另一个最优方案选择的第一场比赛是 O。
#
# 因为 G 是结束时间最早的可选比赛，所以：
#
#     end(G) <= end(O)
#
# 如果把最优方案中的 O 替换成 G：
#
#     1. G 可以参加，因为它和 current 不冲突；
#     2. G 结束得不晚于 O；
#     3. 原来安排在 O 之后的所有比赛，
#        仍然不会因为 G 而产生冲突。
#
# 因此替换后至少可以参加和原方案一样多的比赛。
#
# 这说明存在一个最优方案，
# 它的第一场比赛就是贪心选择的 G。
#
# 选择 G 后，对剩余时间段重复使用相同策略，
# 最终得到的方案一定是最优的。
#
#
# 六、代码中的状态变量
#
#     cnt
#
# 表示已经选择的比赛数量。
#
#     last_end
#
# 表示上一场被选择的比赛的结束时间。
#
# 初始设置：
#
#     last_end = -1
#
# 因为题目保证 begin >= 0，
# 所以第一场比赛可以正常判断。
#
# 扫描每场比赛时：
#
#     if begin >= last_end:
#         cnt += 1
#         last_end = end
#
# 如果当前比赛能够参加：
#
#     1. 选择它；
#     2. 计数加一；
#     3. 更新最后结束时间。
#
# 如果 begin < last_end，
# 说明当前比赛和上一场比赛冲突，跳过它。
#
#
# 七、样例分析
#
# 比赛为：
#
#     [0, 2]
#     [2, 4]
#     [1, 3]
#
# 按结束时间排序：
#
#     [0, 2]
#     [1, 3]
#     [2, 4]
#
# 扫描过程：
#
#     选择 [0, 2]，last_end = 2
#     [1, 3] 的 begin = 1 < 2，冲突，跳过
#     选择 [2, 4]，last_end = 4
#
# 最终选择：
#
#     [0, 2]、[2, 4]
#
# 共 2 场。
#
#
# 八、算法流程
#
#     1. 读入所有比赛的开始时间和结束时间；
#     2. 按结束时间升序排序；
#     3. 初始化上一场结束时间 last_end；
#     4. 从前到后扫描比赛；
#     5. 如果当前比赛不冲突，就选择它；
#     6. 更新 cnt 和 last_end；
#     7. 输出最多能参加的比赛数量。
#
#
# 九、正确性直觉
#
# 当前能参加的比赛中，
# 结束时间越早，就越早释放时间，
# 后面能够安排的比赛就越多。
#
# 贪心选择结束时间最早的比赛后，
# 不会减少任何最优方案能够安排的后续比赛数量。
#
# 因此每一步都选择结束时间最早的可行比赛，
# 最终得到的比赛数量最多。
#
#
# 十、与 P1223 的区别
#
# P1223 是：
#
#     按接水时间排序，
#     让短任务优先，减少等待时间。
#
# P1803 是：
#
#     按比赛结束时间排序，
#     让当前比赛尽早结束，增加后续选择空间。
#
# 两者都属于排序贪心，
# 但贪心关键字不同：
#
#     P1223：接水时间；
#     P1803：结束时间。
#
#
# 十一、复杂度分析
#
