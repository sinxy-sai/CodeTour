# 组合
# 回溯搜索
import sys
# 不考虑顺序
# 每个数字最多选择一次
# 选择结果按递增顺序排列

def main():
    n,r = map(int,sys.stdin.readline().split())

    path = []
    out = []

    def dfs(start):
        # 1.终止条件
        if len(path) == r:
            out.append(''.join(f'{x:3d}' for x in path))
            return

        # 2.处理当前状态
        remain = r - len(path)

        # 3.枚举下一步选择
        for value in range(start,n + 1):
            # 4.选择
            if n - value < remain - 1:
                break
            path.append(value)
            # 5.递归
            dfs(value + 1)
            # 6.撤销选择
            path.pop()


    dfs(1)
    sys.stdout.write('\n'.join(out))



if __name__ == '__main__':
    main()


# ============================================================
# P1157 组合的输出：理论、算法思路与细节
# ============================================================
#
# 一、组合与排列的区别
#
# 组合是不考虑顺序的选择。
#
# 例如从 1、2、3 中选择 2 个数字：
#
#     1 2
#     1 3
#     2 3
#
# 其中 2 1 和 1 2 表示同一种组合，所以不能重复输出。
#
# 为了避免重复，本程序规定：
#
#     后面选择的数字必须比前面选择的数字大。
#
# 因此每个组合天然保持递增顺序。
#
#
# 二、DFS 状态
#
# dfs(start) 表示：
#
#     当前 path 中已经选择了一部分数字，
#     接下来只能从 start 到 n 中继续选择。
#
# 例如：
#
#     path = [1, 3]
#     dfs(4)
#
# 表示已经选择了 1 和 3，后面只能选择 4、5、6……
#
# 由于后续只能从更大的数字中选择，
# 所以不会出现 [3, 1]、[2, 1] 这种重复或无序方案。
#
#
# 三、path 的作用
#
# path 保存当前递归路径，也就是当前正在构造的组合。
#
# 例如搜索过程中：
#
#     path = []
#     path = [1]
#     path = [1, 3]
#     path = [1, 3, 5]
#
# 当 path 的长度达到 r 时，说明已经选出了一个完整组合，
# 将它保存到输出数组中。
#
#
# 四、递归终止条件
#
#     if len(path) == r:
#
# 表示当前已经选择了 r 个数字。
#
# 此时：
#
#     1. 当前组合已经完整；
#     2. 按题目要求格式化输出；
#     3. return 返回上一层。
#
# 这里的 return 很重要，因为一个组合完成后，
# 不能继续向下选择，否则组合中的数字数量会超过 r。
#
#
# 五、选择与回溯
#
# 代码中的核心结构是：
#
#     path.append(value)
#     dfs(value + 1)
#     path.pop()
#
# 三步分别表示：
#
#     1. 选择 value；
#     2. 继续搜索后面的数字；
#     3. 撤销 value，回到选择 value 之前的状态。
#
# 例如当前 path 为 [1]，尝试选择 3：
#
#     [1]
#       -> append(3)
#     [1, 3]
#       -> 继续搜索
#     搜索结束后
#       -> pop()
#     [1]
#
# pop() 之后才能尝试同一层的下一个选择，例如 4。
#
#
# 六、为什么递归调用是 dfs(value + 1)
#
# 如果当前选择了 value，那么后面不能再次选择 value，
# 也不能选择比 value 小的数字。
#
# 所以下一层从 value + 1 开始：
#
#     dfs(value + 1)
#
# 这同时完成了两件事：
#
#     1. 防止同一个数字重复使用；
#     2. 保证组合中的数字递增。
#
#
# 七、剩余数量剪枝
#
#     remain = r - len(path)
#
# 表示当前还需要选择多少个数字。
#
# 如果当前尝试选择 value，
# 那么后面还需要选择 remain - 1 个数字。
#
# 当前可用数字是 value + 1 到 n，
# 一共有：
#
#     n - value
#
# 个数字。
#
# 如果：
#
#     n - value < remain - 1
#
# 说明即使把后面所有数字都用上，也不够凑出 r 个数字，
# 当前 value 不可能作为选择。
#
# 因为 value 越来越大，后面可用数字只会越来越少，
# 所以可以直接 break。
#
#
# 八、为什么要按照从小到大的顺序搜索
#
# 外层循环是：
#
#     for value in range(start, n + 1):
#
# 因为从小到大尝试，所以生成的组合天然按字典序排列。
#
# 例如 n = 5、r = 3 时，搜索顺序是：
#
#     1 2 3
#     1 2 4
#     1 2 5
#     1 3 4
#     1 3 5
#     1 4 5
#     2 3 4
#     2 3 5
#     2 4 5
#     3 4 5
#
#
# 九、复杂度
#
# 一共需要输出：
#
#     C(n, r)
#
# 个组合。
#
# 因为每个组合包含 r 个数字，
# 时间复杂度至少为：
#
#     O(C(n, r) * r)
#
# 这也是输出本身所需要的复杂度。
#
# 递归深度最多为 r，path 占用 O(r) 空间。
# 如果把所有结果保存到 out 中，还需要额外的输出空间。
#
# 递归辅助空间：
#
#     O(r)
#
#
# 十、这道题的搜索范式
#
#     def dfs(状态):
#         if 到达终止条件:
#             处理答案
#             return
#
#         for 当前层的每种选择:
#             做选择
#             dfs(下一状态)
#             撤销选择
#
# P1157 的特殊之处是使用 start 控制选择范围，
# 从而避免组合重复。
