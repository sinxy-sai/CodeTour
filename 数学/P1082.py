# 同余方程
import sys

# 扩展欧几里得算法
def extend_gcd(a,b):
    '''
    返回三元组(g,x,y)，满足 a*x + b*y = g,
    其中g = gcd(a,b)
    
    '''
    if b == 0:
        return a,1,0

    g,x1,y1 = extend_gcd(b,a % b)
    x = y1
    y = x1 - (a // b)*y1

    return g,x,y

def gcd(a,b):
    while b != 0:
        a,b = b,a % b
    return a


def main():
    a,b = map(int,sys.stdin.buffer.readline().split())

    g,x,y = extend_gcd(a,b)
    '''
    扩展欧几里得算法的性质
    可以求 gcd(a,b) 和 整数x,y 使得 ax + by = gcd(a,b)

    a *x + b *y = gcd(a,b)
    题目保证同余方程一定有解,所以gcd(a,b) = 1

    a * x + b * y = 1

    1 - a *x 能被b整除得到y

    所以 ax = 1 (mod b)

    '''


    ans = x % b
    sys.stdout.buffer.write(str(ans).encode())

if __name__ == '__main__':
    main()


# ============================================================
# P1082 同余方程：数学理论、算法思路与细节
# ============================================================
#
# 一、题目要求
#
# 求同余方程：
#
#     a * x ≡ 1 (mod b)
#
# 的最小正整数解。
#
# 这实际上是在求：
#
#     a 在模 b 意义下的乘法逆元。
#
#
# 二、同余的含义
#
#     a * x ≡ 1 (mod b)
#
# 表示：
#
#     a * x 除以 b 的余数是 1。
#
# 根据同余的定义，也可以写成：
#
#     b | (a * x - 1)
#
# 也就是：
#
#     a * x - 1
#
# 能够被 b 整除。
#
#
# 三、欧几里得算法
#
# 欧几里得算法用于求两个数的最大公约数。
#
# 核心性质：
#
#     gcd(a, b) = gcd(b, a % b)
#
# 例如求 gcd(30, 18)：
#
#     30 = 18 * 1 + 12
#     18 = 12 * 1 + 6
#     12 = 6 * 2 + 0
#
# 最后一个非零余数是 6，所以：
#
#     gcd(30, 18) = 6
#
# 代码中的 gcd 函数就是循环版本的欧几里得算法。
#
#
# 四、贝祖等式
#
# 对任意整数 a、b，都存在整数 x、y，使得：
#
#     a * x + b * y = gcd(a, b)
#
# 这个等式叫做贝祖等式。
#
# 扩展欧几里得算法的作用，就是同时求出：
#
#     gcd(a, b)
#     x
#     y
#
# 使得：
#
#     a * x + b * y = gcd(a, b)
#
#
# 五、为什么扩展欧几里得可以求逆元
#
# 题目保证同余方程有解。
#
# 方程：
#
#     a * x ≡ 1 (mod b)
#
# 有解的条件是：
#
#     gcd(a, b) = 1
#
# 此时贝祖等式变成：
#
#     a * x + b * y = 1
#
# 移项：
#
#     a * x - 1 = -b * y
#
# 右边是 b 的倍数，因此：
#
#     a * x ≡ 1 (mod b)
#
# 所以扩展欧几里得得到的 x，
# 就是题目所要求的逆元。
#
#
# 六、扩展欧几里得的递推
#
# 函数：
#
#     extend_gcd(a, b)
#
# 返回：
#
#     (g, x, y)
#
# 满足：
#
#     a * x + b * y = g
#
# 其中：
#
#     g = gcd(a, b)
#
# 当 b == 0 时：
#
#     gcd(a, 0) = a
#
# 并且：
#
#     a * 1 + 0 * 0 = a
#
# 所以递归边界是：
#
#     return a, 1, 0
#
#
# 七、递归回溯时如何更新 x、y
#
# 递归调用：
#
#     extend_gcd(b, a % b)
#
# 得到：
#
#     b * x1 + (a % b) * y1 = g
#
# 根据带余除法：
#
#     a % b = a - (a // b) * b
#
# 代入：
#
#     b * x1
#     + [a - (a // b) * b] * y1
#     = g
#
# 展开：
#
#     a * y1
#     + b * [x1 - (a // b) * y1]
#     = g
#
# 所以当前层的系数为：
#
#     x = y1
#     y = x1 - (a // b) * y1
#
# 这就是代码中的：
#
#     x = y1
#     y = x1 - (a // b) * y1
#
#
# 八、样例推导
#
# 求：
#
#     3 * x ≡ 1 (mod 10)
#
# 欧几里得过程：
#
#     10 = 3 * 3 + 1
#     3 = 1 * 3 + 0
#
# 所以：
#
#     gcd(3, 10) = 1
#
# 回代：
#
#     1 = 10 - 3 * 3
#
# 整理：
#
#     3 * (-3) + 10 * 1 = 1
#
# 因此扩展欧几里得得到：
#
#     x = -3
#     y = 1
#
# 两边模 10：
#
#     3 * (-3) ≡ 1 (mod 10)
#
# 因为：
#
#     -3 ≡ 7 (mod 10)
#
# 所以最小正整数解是：
#
#     x = 7
#
#
# 九、为什么代码使用 x % b
#
# 扩展欧几里得得到的 x 可能是负数。
#
# 例如：
#
#     x = -3
#     b = 10
#
# Python 中：
#
#     -3 % 10 = 7
#
# 所以：
#
#     ans = x % b
#
# 可以把 x 转换成 0 到 b - 1 之间的等价解。
#
# 因为 b >= 2，且题目保证 gcd(a,b) = 1，
# 逆元不可能等于 0，
# 因此 `x % b` 正好是最小正整数解。
#
#
# 十、同余方程解的周期性
#
# 如果 x0 是：
#
#     a * x ≡ 1 (mod b)
#
# 的一个解，那么：
#
#     x0 + k * b
#
# 也是解，其中 k 是任意整数。
#
# 例如：
#
#     3 * x ≡ 1 (mod 10)
#
# 一个解是 7，那么：
#
#     7、17、27、37、...
#
# 都是解。
#
# 题目要求最小正整数解，
# 所以把扩展欧几里得得到的 x 取模 b 即可。
#
#
# 十一、为什么不能直接进行普通除法
#
# 在普通等式中：
#
#     a * x = 1
#
# 可以写成：
#
#     x = 1 / a
#
# 但在模运算中不能直接使用普通除法。
#
# 模意义下的“除以 a”，
# 实际上是乘以 a 的乘法逆元：
#
#     除以 a
#     等价于乘以 inv(a)
#
# 而本题正是在求这个逆元。
#
#
# 十二、算法流程
#
#     1. 读入 a、b；
#     2. 使用扩展欧几里得求出：
#        a * x + b * y = gcd(a,b)；
#     3. 题目保证 gcd(a,b) = 1；
#     4. 得到：
#        a * x ≡ 1 (mod b)；
#     5. 输出 x % b。
#
#
# 十三、复杂度
#
# 欧几里得算法每次都会把问题规模缩小为：
#
#     (b, a % b)
#
# 复杂度为：
#
#     O(log(min(a,b)))
#

#
# 十四、带余除法公式与 `%`
#
# 对任意整数 a 和正整数 b，都可以写成：
#
#     a = (a // b) * b + (a % b)
#
# 其中：
#
#     a // b：a 除以 b 的商；
#     a % b ：a 除以 b 的余数。
#
# 因此：
#
#     a % b = a - (a // b) * b
#
# 例如：
#
#     17 // 5 = 3
#     17 % 5  = 2
#
# 因为：
#
#     17 = 3 * 5 + 2
#
# 这个公式不是 Python 特有的技巧，而是整数除法的基本关系。
#
# 被除数 = 商 × 除数 + 余数
#
#
# 十五、带余除法为什么出现在欧几里得算法中
#
# 欧几里得算法使用下面的性质：
#
#     gcd(a, b) = gcd(b, a % b)
#
# 设：
#
#     a = q * b + r
#
# 其中：
#
#     q = a // b
#     r = a % b
#
# 也就是：
#
#     r = a - q * b
#
# 一个数 d 如果同时整除 a 和 b，
# 那么它也一定整除：
#
#     a - q * b = r
#
# 反过来，一个数如果同时整除 b 和 r，
# 那么它也一定整除：
#
#     q * b + r = a
#
# 所以 a、b 与 b、r 拥有完全相同的公约数，
# 最大公约数也就相同：
#
#     gcd(a, b) = gcd(b, r)
#                = gcd(b, a % b)
#
# 这就是欧几里得算法不断执行：
#
#     a, b = b, a % b
#
# 的数学依据。
#
#
# 十六、带余除法为什么出现在扩展欧几里得回代中
#
# 扩展欧几里得需要把：
#
#     gcd(a, b)
#
# 写成 a 和 b 的线性组合。
#
# 例如：
#
#     a = q * b + r
#
# 根据带余除法公式：
#
#     r = a - q * b
#
# 如果递归已经求出了：
#
#     gcd(b, r) = b * x1 + r * y1
#
# 把 r = a - q * b 代入：
#
#     gcd(a, b)
#       = b * x1 + (a - q * b) * y1
#       = a * y1 + b * (x1 - q * y1)
#
# 因此当前层的系数是：
#
#     x = y1
#     y = x1 - q * y1
#
# 代码中的 `a // b` 就是这里的 q，
# 代码中的 `a % b` 就是这里的 r。
#
#
# 十七、`%` 在本题最后的作用
#
# 扩展欧几里得求出的系数 x 可能是负数，
# 但同余方程的解可以相差任意个 b：
#
#     x、x + b、x + 2b、...
#
# 使用：
#
#     x % b
#
# 就可以把它转换到 0 到 b - 1 的范围内。
#
# 例如：
#
#     -3 % 10 = 7
#
# 而：
#
#     3 * (-3) = -9 ≡ 1 (mod 10)
#     3 * 7   = 21  ≡ 1 (mod 10)
#
# 所以 `x % b` 得到的是同一个同余类中最小的非负代表。
# 本题保证解存在且 b >= 2，因此这个结果不会是 0，
# 也就是最小正整数解。
# 扩展欧几里得只是在欧几里得算法的基础上额外维护系数，
# 所以时间复杂度仍然是：
#
#     O(log(min(a,b)))
#
# 递归深度也是：
#
#     O(log(min(a,b)))
#
