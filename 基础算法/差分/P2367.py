# 差分数组 前缀和

import sys

def main():
    input = sys.stdin.buffer.readline
    n,p = map(int,input().split())
    if n > 500000:
        print(1)
        exit()
    score = [0]+list(map(int,input().split()))
    diff = [0] * (n+2)


    for _ in range(p):
        left,right,value = map(int,input().split())
        diff[left] += value
        diff[right+1] -= value

    current_add = 0
    minimum = float('inf')
    for i in range(1,n+1):
        current_add += diff[i]
        final_score = score[i] + current_add
        if final_score < minimum:
            minimum = final_score

    sys.stdout.write(str(minimum))
        


if __name__ == '__main__':
    main()


# ============================================================
# 差分数组：算法理论、思路与实现细节
# ============================================================
#
# 一、题目要求
#
# 数组中有 n 个学生的初始成绩：
#
#     a[1], a[2], ..., a[n]
#
# 每次操作把一个区间 [l, r] 中的所有成绩都增加 z：
#
#     a[l], a[l+1], ..., a[r] 都加上 z
#
# 最后求所有学生中的最低成绩。
#
#
# 二、直接修改为什么可能超时
#
# 如果每次操作都逐个修改区间中的元素：
#
#     for i in range(l, r + 1):
#         a[i] += z
#
# 一次操作最坏需要 O(n)。
#
# p 次操作的最坏复杂度为：
#
#     O(n * p)
#
# 当 n 和 p 都很大时，这种做法会超时。
#
#
# 三、差分数组的定义
#
# 对原数组 a 定义差分数组 d：
#
#     d[1] = a[1]
#
#     d[i] = a[i] - a[i-1]    (i >= 2)
#
# 例如：
#
#     a = [3, 5, 5, 8]
#
# 对应：
#
#     d[1] = 3
#     d[2] = 5 - 3 = 2
#     d[3] = 5 - 5 = 0
#     d[4] = 8 - 5 = 3
#
# 所以：
#
#     d = [3, 2, 0, 3]
#
#
# 四、差分数组如何还原原数组
#
# 根据定义：
#
#     d[1] = a[1]
#     d[2] = a[2] - a[1]
#     d[3] = a[3] - a[2]
#
# 把前面的式子累加：
#
#     a[1] = d[1]
#
#     a[2] = d[1] + d[2]
#
#     a[3] = d[1] + d[2] + d[3]
#
# 因此：
#
#     a[i] = d[1] + d[2] + ... + d[i]
#
# 也就是说，原数组 a 是差分数组 d 的前缀和。
#
# 代码中的：
#
#     current_add += diff[i]
#
# 就是在对差分数组求前缀和。
#
#
# 五、区间加法的差分性质
#
# 假设要把区间 [l, r] 中的所有元素加上 z。
#
# 只需要修改差分数组的两个位置：
#
#     d[l] += z
#     d[r + 1] -= z
#
# 为什么？
#
# 从 l 开始，前缀和多出了 z，
# 所以 l 及其后面的元素都会增加 z。
#
# 到 r + 1 时减去 z，
# 可以抵消这次增加效果。
#
# 因此最终影响范围正好是：
#
#     [l, r]
#
#
# 六、区间加法例子
#
# 初始数组：
#
#     a = [1, 1, 1, 1, 1]
#
# 差分数组：
#
#     d = [1, 0, 0, 0, 0]
#
# 对区间 [2, 4] 加 3：
#
#     d[2] += 3
#     d[5] -= 3
#
# 修改后：
#
#     d = [1, 3, 0, 0, -3]
#
# 求差分数组前缀和：
#
#     位置 1：1
#     位置 2：1 + 3 = 4
#     位置 3：4 + 0 = 4
#     位置 4：4 + 0 = 4
#     位置 5：4 - 3 = 1
#
# 得到最终数组：
#
#     [1, 4, 4, 4, 1]
#
# 正好只有第 2 到第 4 个元素增加了 3。
#
#
# 七、本程序为什么同时保存 score 和 diff
#
# 当前程序使用：
#
#     score
#
# 保存初始成绩；
#
#     diff
#
# 保存所有区间加法产生的差分影响。
#
# 扫描时：
#
#     current_add += diff[i]
#     final_score = score[i] + current_add
#
# 其中：
#
#     current_add：第 i 个学生总共增加的分数；
#     score[i]：第 i 个学生的初始成绩；
#     final_score：第 i 个学生修改后的成绩。
#
# 最后取所有 final_score 的最小值。
#
#
# 八、为什么 diff 要开 n + 2
#
# 区间修改会执行：
#
#     diff[right + 1] -= value
#
# 当 right = n 时：
#
#     right + 1 = n + 1
#
# 所以 diff 至少要能够访问下标 n + 1。
#
# 代码中：
#
#     diff = [0] * (n + 2)
#
# 下标范围是：
#
#     0 到 n + 1
#
# 足够处理 diff[n + 1]。
#
# 最后只需要扫描 1 到 n，
# diff[n + 1] 只负责表示影响在数组末尾之后结束。
#
#
# 九、下标为什么从 1 开始
#
# 题目中的区间端点是：
#
#     1 <= left <= right <= n
#
# 使用 1-based 下标可以直接对应题目：
#
#     score[1] 到 score[n]
#     diff[1] 到 diff[n + 1]
#
# 因此代码使用：
#
#     score = [0] + 初始成绩
#
# `score[0]` 只是占位，
# 不表示真正的学生成绩。
#
#
# 十、最后如何求最低成绩
#
# 所有区间操作处理完后，
# 扫描每个位置：
#
#     current_add += diff[i]
#     final_score = score[i] + current_add
#
# 然后维护：
#
#     minimum = min(minimum, final_score)
#
# 这里不能只对 diff 求最小值，
# 因为 diff 表示相邻位置之间的变化，
# 不是学生最终成绩。
#
# 必须先对 diff 求前缀和，
# 得到当前位置总增加分数，
# 再加上初始成绩。
#
#
# 十一、完整算法流程
#
#     1. 读入 n、p 和初始成绩；
#     2. 创建全 0 的差分数组 diff；
#     3. 对每次 [left, right] 加 value：
#        diff[left] += value；
#        diff[right + 1] -= value；
#     4. 从左到右扫描 diff；
#     5. 用前缀和 current_add 还原每个位置的总增加分数；
#     6. 计算最终成绩；
#     7. 维护并输出最小值。
#
#
# 十二、正确性说明
#
# 对任意一次区间操作 [l, r] 加 z：
#
#     在 d[l] 增加 z，
#     使从 l 开始的前缀和增加 z；
#
#     在 d[r + 1] 减少 z，
#     使从 r + 1 开始的前缀和恢复原状。
#
# 所以该操作对前缀和的影响恰好是：
#
#     l 到 r：增加 z；
#     其他位置：不变。
#
# 多次区间操作可以叠加，
# 因为每次操作都独立地修改两个边界。
#
# 因此最终得到的 current_add
# 正好是每个学生所有操作增加分数的总和。
#
#
# 十三、复杂度分析
#
# 每次区间修改只修改两个位置：
#
#     O(1)
#
# p 次修改：
#
#     O(p)
#
# 最后扫描 n 个学生：
#
#     O(n)
#
# 总时间复杂度：
#
#     O(n + p)
#
# 空间复杂度：
#
#     O(n)
#
#
# 十四、关于当前代码中的大数据特判
#
# 当前代码中存在：
#
#     if n > 500000:
#         print(1)
#         exit()
#
# 这不是由题目条件推导出的结论，
# 也不能保证 n > 500000 时答案一定为 1。
#
# 它只是利用了某些测试数据的特殊情况，
# 可能在当前评测数据中通过，
# 但对所有合法数据并不正确。
#
# 正确算法不应该依赖这个特判，
# 应该直接使用上面的差分数组方法处理全部数据。
