import sys

def solve(n, x):
    exponent = n - 2

    power_of_two = 0
    value = x
    while value % 2 == 0:
        value //= 2
        power_of_two += 1

    extra = max(0, exponent - power_of_two)

    return x << extra #如果不用value去存x的原始值，那么这一步要把x << extra 改为x << (power_of_two + extra)，因为x需要恢复到被除了power_of_two次2前的原始值

def main():
    data = sys.stdin.buffer.read().split()
    it = iter(data)
    T = int(next(it))
    out = []
    for _ in range(T):
        n = int(next(it))
        x = int(next(it))
        out.append(str(solve(n, x)))
    sys.stdout.write('\n'.join(out))

if __name__ == '__main__':
    main()


# ============================================================
# P9532 前缀和：算法理论、思路与实现细节
# ============================================================
#
# 一、这道题中的“前缀和”
#
# 令：
#
#     S_i = a_1 + a_2 + ... + a_i
#
# 表示数组前 i 项的前缀和。
#
# 题目规定，对于 i >= 2：
#
#     a_i = a_1 + a_2 + ... + a_(i-1)
#         = S_(i-1)
#
# 因此当前前缀和满足：
#
#     S_i = S_(i-1) + a_i
#         = S_(i-1) + S_(i-1)
#         = 2 * S_(i-1)
#
# 这就是本题的核心规律：
#
#     每增加一项，前缀和都会变成原来的 2 倍。
#
#
# 二、数列的通项
#
# 设第一个数为：
#
#     a_1 = c
#
# 那么：
#
#     a_2 = a_1 = c
#     a_3 = a_1 + a_2 = 2c
#     a_4 = a_1 + a_2 + a_3 = 4c
#     a_5 = 8c
#
# 所以从第二项开始：
#
#     a_i = 2^(i-2) * c
#
# 特别地：
#
#     a_n = 2^(n-2) * c
#
# 例如 c = 1 时：
#
#     [1, 1, 2, 4, 8, 16]
#
#
# 三、已知 x 出现在数组中
#
# 如果 x 出现在第 j 项：
#
#     j = 1
#
# 那么：
#
#     x = a_1 = c
#
# 如果 j >= 2：
#
#     x = a_j = 2^(j-2) * c
#
# 令：
#
#     k = j - 2
#
# 则：
#
#     x = 2^k * c
#
# 因此 x 必须能够被 2^k 整除，
# 并且：
#
#     0 <= k <= n - 2
#
#
# 四、为什么要让 k 尽可能大
#
# 由：
#
#     x = 2^k * c
#
# 得到：
#
#     c = x / 2^k
#
# 最后一项为：
#
#     a_n = 2^(n-2) * c
#         = 2^(n-2) * x / 2^k
#
# 在 n 和 x 固定时，
# k 越大，c 越小，
# 所以 a_n 越小。
#
# 因此我们要找最大的合法 k。
#
# k 有两个限制：
#
#     1. 数组最多到第 n 项：
#        k <= n - 2
#
#     2. x 中最多包含 v_2(x) 个因子 2：
#        k <= v_2(x)
#
# 所以：
#
#     k = min(n - 2, v_2(x))
#
#
# 五、什么是 v_2(x)
#
# v_2(x) 表示 x 的质因数分解中包含多少个因子 2。
#
# 例如：
#
#     12 = 2^2 * 3
#     v_2(12) = 2
#
#     40 = 2^3 * 5
#     v_2(40) = 3
#
#     7 不含因子 2
#     v_2(7) = 0
#
# 代码：
#
#     power_of_two = 0
#     value = x
#
#     while value % 2 == 0:
#         value //= 2
#         power_of_two += 1
#
# 每循环一次，就从 value 中除去一个因子 2。
#
# 例如 x = 12：
#
#     12 % 2 = 0，12 // 2 = 6
#     6  % 2 = 0，6  // 2 = 3
#     3  % 2 != 0，停止
#
# 最终：
#
#     value = 3
#     power_of_two = 2
#
#
# 六、`extra` 的含义
#
# 代码：
#
#     exponent = n - 2
#     extra = max(0, exponent - power_of_two)
#
# `exponent` 是从 a_1 到 a_n 需要的总倍增次数：
#
#     a_n = 2^(n-2) * a_1
#
# 如果：
#
#     power_of_two < n - 2
#
# 说明 x 中的因子 2 不够覆盖到第 n 项，
# 还需要额外乘：
#
#     2^((n-2)-power_of_two)
#
# 这个额外的指数就是：
#
#     extra = n - 2 - power_of_two
#
# 如果：
#
#     power_of_two >= n - 2
#
# 那么 x 已经可以作为第 n 项，
# 不需要再乘 2，所以 extra 为 0。
#
#
# 七、为什么答案是 `x << extra`
#
# 这里的 x 没有被修改，
# 原始的 x 仍然保留着。
#
# 如果 v_2(x) < n - 2：
#
#     a_n = x * 2^((n-2)-v_2(x))
#
# 如果 v_2(x) >= n - 2：
#
#     a_n = x
#
# 两种情况可以统一写成：
#
#     a_n = x * 2^extra
#
# 而二进制左移满足：
#
#     x << t = x * 2^t
#
# 因此：
#
#     return x << extra
#
# 注意：如果在统计因子 2 的过程中直接修改了 x，
# 那么 x 会变成原始 x 去掉所有因子 2 后的奇数部分。
# 此时必须把被除掉的因子 2 也补回来，
# 需要写成：
#
#     odd_part << (power_of_two + extra)
#
# 本程序使用 `value = x` 保存副本，
# 所以可以直接使用原始的 x：
#
#     return x << extra
#
#
# 八、样例推导
#
# 例：n = 4，x = 2。
#
# 需要从某一项推到第 4 项，
# 总倍增次数为：
#
#     n - 2 = 2
#
# 而：
#
#     v_2(2) = 1
#
# 所以：
#
#     extra = max(0, 2 - 1) = 1
#
# 答案：
#
#     2 * 2^1 = 4
#
# 对应数组：
#
#     [2, 2, 4, 8]
#     [1, 1, 2, 4]
#
# 为了让最后一项最小，应选择第二个数组，
# 答案为 4。
#
#
# 九、奇数 x 的情况
#
# 如果 x 是奇数，则：
#
#     v_2(x) = 0
#
# x 只能作为第一个数 a_1。
#
# 因此：
#
#     a_n = 2^(n-2) * x
#
# 例如 n = 3，x = 3：
#
#     a_1 = 3
#     a_2 = 3
#     a_3 = 6
#
# 答案为 6。
#
#
# 十、为什么不需要真的构造数组
#
# n 最大为 20，虽然构造数组也可以完成，
# 但题目本质上只需要利用：
#
#     a_i = 2^(i-2) * a_1
#
# 以及 x 中因子 2 的数量。
#
# 因此直接进行数学计算即可，
# 不需要保存数组，也不需要使用真正的前缀和数组。
#
#
# 十一、算法流程
#
#     1. 计算总共需要的倍增次数 n - 2；
#     2. 计算 x 中因子 2 的个数 v_2(x)；
#     3. 计算还需要补充的倍增次数：
#        extra = max(0, n - 2 - v_2(x))；
#     4. 计算 x * 2^extra；
#     5. 使用左移运算输出结果。
#
#
# 十二、复杂度分析
#
# 每次循环都会把 value 除以 2，
# 所以循环次数为 O(log x)。
#
# 单组数据的时间复杂度为：
#
#     O(log x)
#
# 空间复杂度为：
#
#     O(1)
#
# T 组数据的总时间复杂度为：
#
#     O(T log x)
