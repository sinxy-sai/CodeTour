# 快速幂
# 二进制快速幂
import sys

def fast_power(base,exp,mod):
    res = 1
    base %= mod

    while exp > 0:

        # 如果指数最低位为1，需要用这次的base乘以之前计算的res
        if exp & 1:
            res = res * base % mod

        base = base * base % mod

        # 指数右移一位
        exp >>= 1

    return res



def main():
    a,b,p = map(int,sys.stdin.buffer.readline().split())

    ans = fast_power(a,b,p)

    sys.stdout.buffer.write(f"{a}^{b} mod {p}={ans}".encode())

if __name__ == '__main__':
    main()


# ============================================================
# P1226 快速幂：数学理论、算法思路与细节
# ============================================================
#
# 一、题目要求
#
# 计算：
#
#     a^b mod p
#
# 其中：
#
#     a 是底数；
#     b 是指数；
#     p 是模数。
#
# 如果直接进行 b 次乘法，时间复杂度为 O(b)。
# 当 b 很大时，这种方法会很慢。
#
# 快速幂可以把复杂度降低到 O(log b)。
#
#
# 二、快速幂的数学基础
#
# 对于任意整数 a：
#
#     a^0 = 1
#
# 如果指数是偶数：
#
#     a^b = (a^(b/2))^2
#
# 如果指数是奇数：
#
#     a^b = a * a^(b-1)
#
# 而 b - 1 是偶数，所以还可以继续平方。
#
# 例如：
#
#     a^10 = (a^5)^2
#     a^5 = a * (a^2)^2
#
# 通过不断把指数除以 2，
# 就可以快速计算幂。
#
#
# 三、二进制分解
#
# 快速幂也可以理解为把指数写成二进制。
#
# 例如：
#
#     10 = 1010₂
#        = 8 + 2
#
# 所以：
#
#     a^10 = a^8 * a^2
#
# 程序会依次计算：
#
#     base = a^1
#     base = a^2
#     base = a^4
#     base = a^8
#     ...
#
# 每次把 base 平方：
#
#     base = base * base % mod
#
# 如果指数当前二进制位为 1，
# 就把当前 base 乘入答案。
#
#
# 四、res 和 base 的含义
#
#     res
#
# 保存已经处理过的二进制位对应的幂的乘积。
#
#     base
#
# 表示当前正在处理的幂：
#
#     a^1、a^2、a^4、a^8、...
#
# 初始时：
#
#     res = 1
#     base = a % mod
#
# 因为任何数乘以 1 都不会改变结果。
#
#
# 五、exp & 1 的含义
#
#     exp & 1
#
# 是按位与运算，用来检查 exp 的最低二进制位。
#
# 二进制数字 1 是：
#
#     0001
#
# 如果 exp 是奇数，最低位一定是 1：
#
#     5 = 0101
#     1 = 0001
#     ----------
#         0001
#
# 所以：
#
#     5 & 1 = 1
#
# 在 if 中表示 True。
#
# 如果 exp 是偶数，最低位一定是 0：
#
#     6 = 0110
#     1 = 0001
#     ----------
#         0000
#
# 所以：
#
#     6 & 1 = 0
#
# 在 if 中表示 False。
#
# 因此：
#
#     if exp & 1:
#
# 等价于判断：
#
#     exp 是否为奇数
#
# 在快速幂中，它表示：
#
#     当前指数的最低二进制位是否为 1。
#
#
# 六、为什么要执行 exp >>= 1
#
#     exp >>= 1
#
# 表示把 exp 的二进制整体向右移动一位，
# 相当于整数除以 2：
#
#     exp >>= 1
#     等价于 exp = exp // 2
#
# 例如：
#
#     10 = 1010₂
#     10 >> 1 = 0101₂ = 5
#
# 每右移一次，就处理完当前最低位，
# 然后继续处理下一位。
#
#
# 七、为什么每次都要平方 base
#
# 当前 base 依次表示：
#
#     a^1、a^2、a^4、a^8、...
#
# 因此每轮需要：
#
#     base = base * base
#
# 例如：
#
#     a^1 * a^1 = a^2
#     a^2 * a^2 = a^4
#     a^4 * a^4 = a^8
#
# 代码中的：
#
#     base = base * base % mod
#
# 就是在计算下一个二进制位对应的幂。
#
#
# 八、为什么乘法过程中可以直接取模
#
# 使用了同余运算性质：
#
#     (x * y) mod p
#     =
#     ((x mod p) * (y mod p)) mod p
#
# 因此可以每次乘法后立即取模：
#
#     res = res * base % mod
#     base = base * base % mod
#
# 这样可以避免中间结果变得非常大。
#
# 例如：
#
#     (12 * 15) mod 7
#     =
#     ((12 mod 7) * (15 mod 7)) mod 7
#     =
#     (5 * 1) mod 7
#     =
#     5
#
#
# 九、算法流程
#
#     1. 初始化 res = 1；
#     2. 令 base = a % p；
#     3. 判断 exp 的最低位：
#        - 如果是 1，将 base 乘入 res；
#        - 如果是 0，不进行乘法；
#     4. 将 base 平方；
#     5. 将 exp 右移一位；
#     6. 重复直到 exp 变为 0。
#
#
# 十、样例计算
#
# 计算：
#
#     2^10 mod 9
#
#     10 = 1010₂
#
# 初始：
#
#     res = 1
#     base = 2
#     exp = 10
#
# 第 1 轮：
#
#     exp 的最低位为 0，不乘 res；
#     base = 2^2 = 4；
#     exp = 5。
#
# 第 2 轮：
#
#     exp 的最低位为 1；
#     res = 1 * 4 mod 9 = 4；
#     base = 4^2 mod 9 = 7；
#     exp = 2。
#
# 第 3 轮：
#
#     exp 的最低位为 0；
#     base = 7^2 mod 9 = 4；
#     exp = 1。
#
# 第 4 轮：
#
#     exp 的最低位为 1；
#     res = 4 * 4 mod 9 = 7；
#     exp = 0。
#
# 最终：
#
#     2^10 mod 9 = 7
#
#
# 十一、边界情况
#
# 如果 b = 0：
#
#     a^0 = 1
#
# 程序一开始令：
#
#     res = 1
#
# 此时循环不会执行，直接返回 1。
#
# 如果 a = 0 且 b > 0：
#
#     0^b = 0
#
# 程序也能正确计算。
#
#
# 十二、复杂度
#
# 每轮都会将 exp 除以 2，
# 所以循环次数约为：
#
#     log2(b)
#
# 时间复杂度：
#
#     O(log b)
#
# 只使用 res、base、exp 等少量变量，
# 空间复杂度：
#
#     O(1)
#
#
