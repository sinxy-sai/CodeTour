import sys
from functools import cmp_to_key

def compare(a:str,b:str)->int:
    if a+b>b+a:
        return -1
    if a+b<b+a:
        return 1
    else:
        return 0


def main():
    input = sys.stdin.buffer.readline
    n = int(input())
    data = input().decode().split()

    data.sort(key=cmp_to_key(compare))

    sys.stdout.buffer.write(''.join(data).encode())

if __name__ == '__main__':
    main()


# ============================================================
# 排序 + 贪心：算法理论、思路与实现细节
# ============================================================
#
# 一、题目要求
#
# 给出 n 个正整数，
# 将它们重新排列后首尾连接，
# 使得到的整数最大。
#
# 例如：
#
#     13、312、343
#
# 可以排列为：
#
#     343、312、13
#
# 连接后得到：
#
#     34331213
#
#
# 二、为什么要把数字当成字符串
#
# 本题比较的是数字连接后的结果，
# 不是数字本身的大小。
#
# 例如：
#
#     a = "9"
#     b = "91"
#
# 如果按照数值大小排序：
#
#     91 > 9
#
# 但连接后：
#
#     "9" + "91" = "991"
#     "91" + "9" = "919"
#
# 因为：
#
#     991 > 919
#
# 所以应该让 9 排在 91 前面。
#
# 因此程序读取数字后保留为字符串，
# 不能直接转换成 int。
#
#
# 三、相邻两个数字的比较规则
#
# 假设相邻有两个字符串 a 和 b。
#
# 它们只有两种排列方式：
#
#     a + b
#     b + a
#
# 如果：
#
#     a + b > b + a
#
# 就应该让 a 排在 b 前面。
#
# 如果：
#
#     a + b < b + a
#
# 就应该让 b 排在 a 前面。
#
# 程序中的比较器：
#
#     def compare(a, b):
#         if a + b > b + a:
#             return -1
#         if a + b < b + a:
#             return 1
#         return 0
#
# `cmp_to_key` 的比较器约定是：
#
#     返回负数：a 排在 b 前面；
#     返回正数：a 排在 b 后面；
#     返回 0：两者顺序无所谓。
#
# 所以当 a + b 更大时返回 -1，
# 表示 a 应该排在 b 前面。
#
#
# 四、贪心策略
#
# 对任意两个待排列的数字 a、b，
# 优先选择能让拼接结果更大的顺序：
#
#     如果 a + b > b + a，就让 a 在前；
#     否则让 b 在前。
#
# 对所有数字按照这个比较规则排序，
# 最后连接起来即可得到最大整数。
#
#
# 五、交换论证
#
# 假设一个排列中有相邻的两个数字 a、b，
# 并且它们当前的顺序不满足贪心规则：
#
#     a + b < b + a
#
# 那么交换它们后，局部连接结果会变大。
#
# 设它们前面的部分连接成字符串 X，
# 后面的部分连接成字符串 Y。
#
# 原排列为：
#
#     X + a + b + Y
#
# 交换后为：
#
#     X + b + a + Y
#
# 因为：
#
#     a + b < b + a
#
# 且两种结果前面的 X 和后面的 Y 完全相同，
# 所以交换后得到的整体数字更大。
#
# 因此最大排列中不可能存在这种逆序相邻对。
#
# 不断交换所有不满足规则的相邻数字，
# 最终得到的排列必然满足：
#
#     对每一对相邻数字 a、b，都有 a + b >= b + a
#
# 这就是排序比较器生成的顺序。
#
#
# 六、样例分析
#
# 对数字：
#
#     13、312、343
#
# 比较 13 和 312：
#
#     13 + 312 = 13312
#     312 + 13 = 31213
#
# 所以：
#
#     312 应排在 13 前面。
#
# 比较 343 和 312：
#
#     343312 > 312343
#
# 所以：
#
#     343 应排在 312 前面。
#
# 最终顺序：
#
#     343、312、13
#
# 连接结果：
#
#     34331213
#
#
# 七、为什么不能按照数值大小排序
#
# 数值大小只比较数字本身，
# 但本题的目标是比较拼接结果。
#
# 例如：
#
#     3、30、34
#
# 按照数值从大到小排列：
#
#     34、30、3
#
# 结果为：
#
#     34303
#
# 但按照拼接比较：
#
#     "3" + "30" = "330"
#     "30" + "3" = "303"
#
# 所以 3 应排在 30 前面。
#
# 最优排列是：
#
#     34、3、30
#
# 结果为：
#
#     34330
#
#
# 八、为什么比较字符串与比较连接后的数字等价
#
# 所有输入数字都是正整数，
# 直接连接后得到的数字没有前导零问题。
#
# 对长度相同的十进制字符串，
# 字典序大的字符串对应的数值更大。
#
# 对长度不同的字符串，
# 本题直接比较：
#
#     a + b
#     b + a
#
# 这两个字符串长度相同，
# 因此字符串比较可以准确表示连接后整数的大小关系。
#
# 例如：
#
#     "13" + "312" = "13312"
#     "312" + "13" = "31213"
#
# 直接比较这两个字符串即可，
# 不需要把它们转换成可能很大的整数。
#
#
# 九、`cmp_to_key` 的作用
#
# Python 的 `list.sort` 默认支持 key 函数，
# 例如：
#
#     data.sort(key=lambda x: x[1])
#
# 但本题的规则不是给每个元素计算一个独立的关键字，
# 而是需要同时比较两个元素：
#
#     a + b 和 b + a
#
# 因此需要使用比较器。
#
#     cmp_to_key(compare)
#
# 会把传统的二元比较函数转换成 `sort` 可以使用的 key。
#
# 调用：
#
#     data.sort(key=cmp_to_key(compare))
#
# 表示按照 compare 函数定义的顺序排序。
#
#
# 十、比较器返回值为什么是 -1 和 1
#
# 当：
#
#     a + b > b + a
#
# a 应该排在 b 前面。
#
# `cmp_to_key` 规定前者优先时返回负数，
# 所以写：
#
#     return -1
#
# 当：
#
#     a + b < b + a
#
# b 应该排在 a 前面，
# 所以 a 应该排在后面，写：
#
#     return 1
#
# 如果把这两个返回值写反，
# 排序方向就会反过来，最终得到的可能是最小拼接结果。
#
#
# 十一、算法流程
#
#     1. 将所有输入数字读取为字符串；
#     2. 定义两个字符串的拼接比较规则；
#     3. 按照比较规则排序；
#     4. 将排序后的字符串直接连接；
#     5. 输出连接结果。
#
#
# 十二、正确性直觉
#
# 最终结果中，任意相邻的两个数字 a、b，
# 它们的相对顺序只会影响：
#
#     a + b
#     或 b + a
#
# 如果当前顺序不是较大的那一种，
# 交换它们就能使整体结果变大。
#
# 因此最大结果不可能包含违反比较规则的相邻顺序。
# 按照该规则排序后，
# 所有数字的相对顺序都满足局部最优条件，
# 得到的连接结果就是全局最大值。
#
#
# 十三、复杂度分析
#
# 排序需要 O(n log n) 次元素比较。
#
# 每次比较需要拼接并比较字符串。
# 如果单个数字的最大长度为 L，
# 单次比较复杂度可以看作 O(L)。
#
# 因此总时间复杂度为：
#
#     O(n log n * L)
#
# 连接所有字符串需要：
#
#     O(n * L)
#
# 额外空间复杂度主要来自排序和字符串列表：
#
#     O(n * L)
