# 负环
import sys
from collections import deque


def has_negative_cycle(n,graph):
    INF = 10**19

    # 只从顶点1出发
    # dist[i]表示顶点i到1的最短距离  初始化为无穷大
    # depth[i]表示顶点i到1的最短路径经过的边数  初始化为0
    # in_queue[i]表示顶点i是否在队列中  初始化为False

    dist = [INF] * (n+1)  
    depth = [0] * (n+1)
    in_queue = [False] * (n+1)

    queue = deque([1])
    dist[1] = 0
    in_queue[1] = True

    while queue:
        u = queue.popleft()
        in_queue[u] = False

        for v,weight in graph[u]:
            new_dist = dist[u] + weight
            if new_dist >= dist[v]:
                continue

            dist[v] = new_dist

            # 当前路径经过的边数 + 1
            depth[v] = depth[u] + 1

            # n 个点的路径如果包含 n 条边，必然经过某个点至少两次，存在环
            if depth[v] >= n:
                return True

            if not in_queue[v]:
                queue.append(v)
                in_queue[v] = True

    return False






def main():
    data = list(map(int,sys.stdin.buffer.read().split()))
    it = iter(data)
    T = next(it)

    out = []
    for _ in range(T):
        n,m = next(it),next(it)

        graph = [[] for _ in range(n+1)]

        for _ in range(m):
            u = next(it)
            v = next(it)
            w = next(it)
            graph[u].append((v,w))

            # 题目规定：非负边权需要建立双向边
            if w >= 0:
                graph[v].append((u,w))

        if has_negative_cycle(n,graph):
            out.append('YES')
        else:
            out.append('NO')

    sys.stdout.buffer.write('\n'.join(out).encode())

    
if __name__ == '__main__':
    main()


# ============================================================
# 负环：算法理论、思路与实现细节
# ============================================================
#
# 一、什么是有向图
#
# 有向图由：
#
#     顶点
#     有向边
#
# 组成。
#
# 一条有向边：
#
#     u -> v
#
# 表示可以从顶点 u 走到顶点 v。
#
# 如果边上带有一个数 w，
# 就称 w 为这条边的边权。
#
#
# 二、什么是环
#
# 如果从某个顶点出发，
# 沿着有向边走了一圈又回到这个顶点，
# 那么这条路径就形成了一个环。
#
# 例如：
#
#     1 -> 2
#     2 -> 3
#     3 -> 1
#
# 形成环：
#
#     1 -> 2 -> 3 -> 1
#
# 环的权值和是环上所有边权之和。
#
#
# 三、什么是负环
#
# 如果一个环的边权和小于 0，
# 就称它为负环。
#
# 例如：
#
#     1 -> 2，权值 2
#     2 -> 3，权值 -5
#     3 -> 1，权值 1
#
# 环的权值和：
#
#     2 + (-5) + 1 = -2
#
# 所以这是一个负环。
#
# 如果从顶点 1 可以到达这个负环，
# 那么沿着负环不断绕圈，
# 路径总权值可以无限减小：
#
#     0
#     -2
#     -4
#     -6
#     ...
#
# 因此不存在有限的最短路答案。
#
#
# 四、本题的特殊要求
#
# 题目不是询问整个图中是否存在负环，
# 而是询问：
#
#     从顶点 1 出发能到达的区域内，
#     是否存在负环。
#
# 因此：
#
#     1. 只能从顶点 1 开始搜索；
#     2. 不可从其他未到达的顶点开始松弛；
#     3. 与顶点 1 不连通的负环不影响答案。
#
# 代码中：
#
#     dist = [INF] * (n + 1)
#     dist[1] = 0
#
# 表示只有顶点 1 的初始距离是已知的。
#
# 其他顶点保持为无穷大，
# 只有通过图上的边从顶点 1 到达它们后，
# 才会被更新。
#
#
# 五、什么是最短路中的松弛
#
# 设当前已经知道：
#
#     dist[u]
#
# 表示从起点 1 到 u 的当前最短距离。
#
# 如果存在一条边：
#
#     u -> v，权值为 w
#
# 那么经过 u 再走到 v 的距离是：
#
#     dist[u] + w
#
# 如果它比当前的 dist[v] 更小，
# 就应该更新：
#
#     dist[v] = dist[u] + w
#
# 这一步称为松弛。
#
# 代码：
#
#     new_dist = dist[u] + weight
#
#     if new_dist < dist[v]:
#         dist[v] = new_dist
#
# 就是在执行松弛。
#
#
# 六、SPFA 是什么
#
# SPFA 的全称是：
#
#     Shortest Path Faster Algorithm
#
# 中文通常称为最短路快速算法。
#
# 它本质上是 Bellman-Ford 算法的队列优化。
#
# Bellman-Ford 会反复扫描所有边，
# 而 SPFA 只处理那些“距离刚刚发生变化”的顶点。
#
# 如果顶点 u 的距离变小，
# 那么只有从 u 出发的边可能继续产生新的松弛，
# 所以把 u 放入队列。
#
#
# 七、SPFA 的基本流程
#
#     1. 设置起点 1 的距离为 0；
#     2. 其他顶点距离设为无穷大；
#     3. 把顶点 1 放入队列；
#     4. 从队列取出顶点 u；
#     5. 遍历 u 的所有出边；
#     6. 如果某个邻接点 v 可以被松弛，
#        就更新 dist[v]；
#     7. 如果 v 当前不在队列中，
#        就把 v 加入队列；
#     8. 队列为空时结束；
#     9. 如果某个点的路径深度达到 n，
#        判定存在负环。
#
# 代码中的：
#
#     queue = deque([1])
#
# 创建队列并放入起点。
#
#     u = queue.popleft()
#
# 取出当前需要处理的顶点。
#
#     for v, weight in graph[u]:
#
# 遍历顶点 u 的所有出边。
#
#
# 八、为什么要使用 `in_queue`
#
# 一个顶点的距离可能在短时间内被多次更新。
#
# 如果每次更新都无条件入队，
# 队列中可能同时出现很多个相同的顶点。
#
# 但同一个顶点只要已经在队列中，
# 后续重复入队没有必要。
#
# 因此使用：
#
#     in_queue[v]
#
# 记录顶点 v 是否已经在队列中。
#
# 入队前判断：
#
#     if not in_queue[v]:
#         queue.append(v)
#         in_queue[v] = True
#
# 出队后恢复：
#
#     in_queue[u] = False
#
#
# 九、为什么普通 BFS 不能解决这道题
#
# BFS 适用于无权图，
# 或者所有边权都相同的图。
#
# 本题存在：
#
#     负权边
#     不同的边权
#
# 一个顶点可能先被较差的路径到达，
# 后面又被更短的路径更新。
#
# 因此一个顶点可能需要多次处理，
# 这与普通 BFS“一个顶点只访问一次”不同。
#
# SPFA 使用了队列，
# 但它不是 BFS：
#
#     BFS：按照层次扩展；
#     SPFA：按照距离更新情况反复松弛。
#
#
# 十、为什么 Dijkstra 不能直接使用
#
# Dijkstra 要求边权非负。
#
# 它依赖这样的性质：
#
#     当前选出的最小距离以后不会再变小。
#
# 如果存在负权边，这个性质可能失效。
#
# 例如：
#
#     1 -> 2，权值 5
#     1 -> 3，权值 2
#     3 -> 2，权值 -4
#
# 直接到达 2 的距离是 5，
# 但经过 3 到达 2 的距离是：
#
#     2 + (-4) = -2
#
# 所以 Dijkstra 不适合含负权边的图。
#
# SPFA 和 Bellman-Ford 可以处理负权边。
#
#
# 十一、为什么可以通过路径长度判断负环
#
# 图中有 n 个顶点。
#
# 一条不重复顶点的简单路径最多经过：
#
#     n - 1 条边
#
# 如果一条路径经过了至少 n 条边，
# 那么路径中至少有一个顶点出现了两次。
#
# 根据抽屉原理，
# 这条路径中一定包含一个环。
#
# 代码中的：
#
#     depth[v] = depth[u] + 1
#
# 表示当前松弛路径经过的边数。
#
# 当：
#
#     depth[v] >= n
#
# 就说明当前路径已经包含至少 n 条边，
# 因此存在重复顶点。
#
#
# 十二、为什么这个环一定是负环
#
# 假设重复部分形成的环权值和为 W。
#
# 绕环之前，到达某个顶点 x 的距离为：
#
#     dist[x]
#
# 绕环之后再次到达 x 的距离为：
#
#     dist[x] + W
#
# 只有当新距离严格更小时，
# SPFA 才会进行松弛：
#
#     dist[x] + W < dist[x]
#
# 两边同时减去 dist[x]：
#
#     W < 0
#
# 所以这个环的权值和必须小于 0，
# 也就是负环。
#
# 如果 W > 0，距离会变大，不能松弛；
# 如果 W = 0，距离不变，也不能松弛。
#
#
# 十三、`depth` 为什么初始化为 0
#
# 顶点 1 是起点，
# 从起点到自身还没有经过任何边：
#
#     depth[1] = 0
#
# 经过一条边到达新顶点：
#
#     depth[v] = depth[u] + 1
#
# n 个顶点的简单路径最多有 n-1 条边，
# 因此达到 n 条边时才说明出现重复顶点：
#
#     if depth[v] >= n:
#         return True
#
# 如果初始化为 1，
# 就可能把一条只有 n-1 条边的简单路径误判为负环。
#
#
# 十四、题目中的建边规则
#
# 输入一条：
#
#     u v w
#
# 如果 w >= 0，
# 题目表示存在两条边：
#
#     u -> v，权值 w
#     v -> u，权值 w
#
# 所以代码：
#
#     graph[u].append((v, w))
#
#     if w >= 0:
#         graph[v].append((u, w))
#
# 如果 w < 0，
# 只添加：
#
#     u -> v
#
# 不能额外添加反向负边。
#
#
# 十五、为什么图要开 n + 1 个位置
#
# 题目顶点编号是：
#
#     1, 2, ..., n
#
# Python 列表下标从 0 开始，
# 因此通常开：
#
#     graph = [[] for _ in range(n + 1)]
#
# 下标 0 空着不用，
# 直接使用 graph[1] 到 graph[n]。
#
# 如果错误地开成 n 个位置，
# 访问 graph[n] 时会发生下标越界。
#
#
# 十六、负环的一个例子
#
# 考虑：
#
#     1 -> 2，权值 2
#     2 -> 3，权值 1
#     3 -> 1，权值 -4
#
# 环的权值和：
#
#     2 + 1 - 4 = -1
#
# 从 1 出发：
#
#     dist[1] = 0
#     dist[2] = 2
#     dist[3] = 3
#     dist[1] = 3 - 4 = -1
#
# 回到 1 后距离从 0 变成 -1，
# 说明绕一圈后距离变小。
#
# 继续绕环：
#
#     dist[1] = -2
#     dist[1] = -3
#     dist[1] = -4
#     ...
#
# 因此最终会触发 depth >= n。
#
#
# 十七、不可达负环为什么不影响答案
#
# 假设顶点 4、5、6 之间存在负环，
# 但从顶点 1 无法到达顶点 4。
#
# 因为：
#
#     dist[4] = dist[5] = dist[6] = INF
#
# 且没有从已到达顶点指向它们的路径，
# 它们不会进入队列，
# 也不会参与松弛。
#
# 所以程序只判断从顶点 1 可达区域中的负环。
#
#
# 十八、算法复杂度
#
# SPFA 在很多实际数据上比直接 Bellman-Ford 快，
# 因为它不会反复扫描完全没有变化的顶点。
#
# 但 SPFA 没有始终很快的理论保证，
# 最坏时间复杂度可以达到：
#
#     O(nm)
#
# 邻接表保存所有顶点和边，
# 空间复杂度为：
#
#     O(n + m)
#
# 本题使用 SPFA 的主要原因是：
#
#     1. 图中允许负权边；
#     2. 需要判断负环；
#     3. 只关心从顶点 1 可达的部分；
#     4. 队列松弛能够同时完成最短距离更新和负环检测。
