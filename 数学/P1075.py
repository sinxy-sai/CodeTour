# 质因数分解
import sys
import math
def main():
    n = int(sys.stdin.buffer.readline())

    # 整数平方根 isqrt
    for i in range(2,math.isqrt(n)+1):
        if n % i==0:
            sys.stdout.buffer.write(str(n//i).encode())
            return

if __name__ == '__main__':
    main()


# ============================================================
# 因数、质数与合数
# ============================================================
#
# 一、因数
#
# 如果正整数 a 能够整除正整数 n，
# 那么 a 就是 n 的因数。
#
# 也可以理解为：
#
#     a * b = n
#
# 那么 a 和 b 都是 n 的因数。
#
# 例如：
#
#     12 = 1 * 12
#     12 = 2 * 6
#     12 = 3 * 4
#
# 所以 12 的正因数是：
#
#     1、2、3、4、6、12
#
#
# 二、因数的个数
#
# 对于大于 1 的正整数 n，
# 至少有两个正因数：
#
#     1 和 n
#
# 特殊情况：
#
#     1 的正因数只有 1 个，就是 1。
#
#
# 三、质数
#
# 质数是大于 1，并且恰好有两个正因数的整数。
#
# 这两个因数一定是：
#
#     1 和它本身
#
# 例如：
#
#     2 的因数：1、2
#     3 的因数：1、3
#     5 的因数：1、5
#     7 的因数：1、7
#
# 因此 2、3、5、7 都是质数。
#
#
# 四、合数
#
# 大于 1 且正因数超过两个的整数叫做合数。
#
# 例如：
#
#     12 的因数：1、2、3、4、6、12
#
# 12 的因数超过两个，所以 12 是合数。
#
#
# 五、三者的区别
#
#     1：
#         只有一个正因数，不是质数，也不是合数。
#
#     质数：
#         恰好有两个正因数。
#
#     合数：
#         有超过两个正因数。
#
#
# 六、本题中的质因数
#
# P1075 保证 n 是两个不同质数的乘积。
#
# 例如：
#
#     21 = 3 * 7
#
# 3 和 7 都是质数，同时也是 21 的因数，
# 所以它们叫做 21 的质因数。
#
# 程序从 2 开始枚举 n 的因数，
# 找到的第一个因数就是较小的质因数；
# 用 n 除以它，就得到较大的质因数。

# ============================================================
# P1075 质因数分解：数学理论、算法思路与细节
# ============================================================
#
# 一、质数与因数
#
# 质数是大于 1 的整数，并且只有 1 和它本身两个因数。
#
# 因数描述的是两个数之间的关系。
# 如果：
#
#     a * b = n
#
# 那么 a 和 b 都是 n 的因数。
#
# 如果一个因数本身还是质数，
# 就称它为 n 的质因数。
#
#
# 二、题目条件
#
# 题目保证：
#
#     n = p * q
#
# 其中 p、q 是两个不同的质数。
#
# 例如：
#
#     21 = 3 * 7
#
# 3 和 7 都是质数，
# 其中 3 是较小的质因数，7 是较大的质因数。
#
#
# 三、为什么枚举因数可以解决问题
#
# 从 2 开始枚举可能的因数：
#
#     2, 3, 4, ...
#
# 第一个能够整除 n 的数字，一定是较小的质因数。
#
# 设找到的第一个因数为 p，那么：
#
#     q = n // p
#
# 因此直接输出：
#
#     n // i
#
# 就是较大的质因数。
#
#
# 四、为什么只枚举到 sqrt(n)
#
# 如果 n = a * b，并且：
#
#     a <= b
#
# 那么一定有：
#
#     a <= sqrt(n)
#
# 证明：
#
# 如果 a > sqrt(n)，那么 b 也会大于 sqrt(n)，
# 于是：
#
#     a * b > sqrt(n) * sqrt(n) = n
#
# 这与 a * b = n 矛盾。
#
# 所以只要枚举到 sqrt(n)，
# 就一定能够找到较小的因数。
#
# 代码中的：
#
#     math.isqrt(n)
#
# 表示不超过 sqrt(n) 的最大整数。
#
# 它比 math.sqrt(n) 更适合整数问题，
# 因为不会产生浮点数精度误差。
#
#
# 五、为什么第一个因数就是较小质因数
#
# 枚举顺序是从小到大：
#
#     for i in range(2, math.isqrt(n) + 1):
#
# 第一个满足：
#
#     n % i == 0
#
# 的 i，就是 n 的最小非 1 因数。
#
# 题目保证 n 由两个质数相乘得到，
# 因此这个最小因数一定是较小的质数。
#
# 例如：
#
#     n = 35
#
# 枚举过程：
#
#     i = 2，35 % 2 != 0
#     i = 3，35 % 3 != 0
#     i = 4，35 % 4 != 0
#     i = 5，35 % 5 == 0
#
# 所以：
#
#     35 // 5 = 7
#
# 7 就是较大的质因数。
#
#
# 六、为什么不需要额外判断 i 是否为质数
#
# 一般的因数分解题中，找到的因数可能是合数。
#
# 但本题保证：
#
#     n = p * q
#
# 且 p、q 是两个不同的质数。
#
# 因此 n 的非平凡因数只有：
#
#     p 和 q
#
# 第一个找到的因数必然是 p，
# 不可能先找到一个合数因数。
#
#
# 七、`n % i == 0` 的含义
#
# `%` 是取模运算，表示求余数。
#
#     n % i
#
# 表示 n 除以 i 的余数。
#
# 如果：
#
#     n % i == 0
#
# 说明 n 能够被 i 整除，
# i 就是 n 的因数。
#
#
# 八、`n // i` 的含义
#
# `//` 是整除运算。
#
# 如果：
#
#     n = i * q
#
# 那么：
#
#     n // i = q
#
# 在本题中，i 是较小质因数，
# 所以 n // i 就是较大的质因数。
#
#
# 九、为什么找到后要 return
#
# 代码：
#
#     if n % i == 0:
#         sys.stdout.buffer.write(
#             str(n // i).encode()
#         )
#         return
#
# 找到第一个因数后，答案已经确定，
# 不需要继续枚举其他数字。
#
# `return` 会直接结束 main 函数。
#
#
# 十、算法流程
#
#     1. 读入 n；
#     2. 从 2 枚举到 sqrt(n)；
#     3. 找到第一个满足 n % i == 0 的 i；
#     4. 输出 n // i；
#     5. 结束程序。
#
#
# 十一、复杂度
#
# 最坏情况下，需要枚举到 sqrt(n)，
# 因此时间复杂度为：
#
#     O(sqrt(n))
#
# 程序只使用了少量变量，
# 空间复杂度为：
#
#     O(1)
#
