# 模意义下的乘法逆元
import sys
from array import array

def main():
    n,p = map(int,sys.stdin.buffer.readline().split())

    inverse = array('I',[0]) * (n+1)
    inverse[1] = 1

    for i in range(2,n+1):
        inverse[i] = (p - p // i) * inverse[p % i] % p

    out = bytearray()
    for i in range(1,n+1):
        out.extend(str(inverse[i]).encode()+b'\n')
    sys.stdout.buffer.write(out)


if __name__ == '__main__':
    main()


# ============================================================
# P3811 模意义下的乘法逆元
# 数学理论、数论基础、算法思路与细节
# ============================================================
#
# 一、什么是取模
#
# 对整数 a 除以正整数 m，得到：
#
#     a = q * m + r
#
# 其中：
#
#     q 是商；
#     r 是余数；
#     0 <= r < m。
#
# 记作：
#
#     a mod m = r
#
# 例如：
#
#     17 mod 5 = 2
#
# 因为：
#
#     17 = 3 * 5 + 2
#
#
# 二、什么是同余
#
# 如果两个整数 a、b 除以 m 的余数相同，
# 就称 a、b 模 m 同余，记作：
#
#     a ≡ b (mod m)
#
# 等价地：
#
#     m | (a - b)
#
# 也就是说，a 和 b 的差能够被 m 整除。
#
# 例如：
#
#     17 ≡ 2 (mod 5)
#
# 因为：
#
#     17 - 2 = 15
#
# 而 15 能被 5 整除。
#
# 同余不是普通的相等。
#
#     -2 != 11
#
# 但是：
#
#     -2 ≡ 11 (mod 13)
#
# 因为：
#
#     11 - (-2) = 13
#
#
# 三、模运算的加法和乘法性质
#
# 如果：
#
#     a ≡ b (mod m)
#     c ≡ d (mod m)
#
# 那么：
#
#     a + c ≡ b + d (mod m)
#
#     a * c ≡ b * d (mod m)
#
# 因此在计算很大的乘积时，
# 可以在每一步之后立即取模：
#
#     (a * b) mod m
#     =
#     ((a mod m) * (b mod m)) mod m
#
# 这可以避免中间结果无限增大。
#
#
# 四、什么是乘法逆元
#
# 在模 p 的意义下，如果存在整数 x，使得：
#
#     a * x ≡ 1 (mod p)
#
# 那么 x 就叫作 a 的乘法逆元，
# 记作：
#
#     inv(a)
#
# 例如，模 13 下 5 的逆元是 8：
#
#     5 * 8 = 40
#     40 mod 13 = 1
#
# 所以：
#
#     inv(5) = 8 (mod 13)
#
#
# 五、逆元存在的条件
#
# a 在模 m 下有乘法逆元，当且仅当：
#
#     gcd(a, m) = 1
#
# 也就是 a 和 m 必须互质。
#
# 例如，模 8 下 2 没有逆元。
#
# 因为：
#
#     gcd(2, 8) = 2
#
# 而且 2 乘以任何整数都是偶数，
# 不可能模 8 余 1。
#
# 如果 m 是质数 p，
# 那么 1 到 p - 1 中的每个数都和 p 互质，
# 因此都有乘法逆元。
#
# 本题保证：
#
#     p 是质数
#     n < p
#
# 所以：
#
#     1 <= i <= n < p
#
# 每个 i 都有模 p 的逆元。
#
#
# 六、什么是同余方程
#
# 同余方程的一般形式是：
#
#     a * x ≡ b (mod m)
#
# 它表示：
#
#     a * x - b
#
# 是 m 的倍数。
#
# 如果 a 有逆元，那么两边可以乘以 inv(a)：
#
#     x ≡ b * inv(a) (mod m)
#
# 特别地：
#
#     a * x ≡ 1 (mod m)
#
# 的解 x 就是 a 的乘法逆元。
#
# 注意：模运算中不能随意“除法”。
# 只有当被除数对应的数与模数互质，
# 才能使用它的乘法逆元来代替除法。
#
#
# 七、本题的递推公式
#
# 令：
#
#     q = p // i
#     r = p % i
#
# 根据带余除法：
#
#     p = q * i + r
#
# 在模 p 意义下，p 等于 0：
#
#     q * i + r ≡ 0 (mod p)
#
# 移项：
#
#     r ≡ -q * i (mod p)
#
# 因为 r < i < p，且 p 是质数，
# 所以 r 也有逆元。
#
# 两边乘以 inv(r)：
#
#     r * inv(r)
#     ≡
#     -q * i * inv(r) (mod p)
#
# 左边等于 1：
#
#     1 ≡ -q * i * inv(r) (mod p)
#
# 调整乘法顺序：
#
#     i * (-q * inv(r)) ≡ 1 (mod p)
#
# 因此：
#
#     inv(i) ≡ -q * inv(r) (mod p)
#
# 把 q、r 换回原来的表达式：
#
#     inv(i)
#     ≡
#     -(p // i) * inv(p % i)
#     (mod p)
#
#
# 八、为什么代码写成 p - p // i
#
# 代码中不能直接使用负数作为最终答案，
# 所以要把 -q 改写成模 p 下的正数。
#
#     -q ≡ p - q (mod p)
#
# 因为：
#
#     (p - q) - (-q) = p
#
# 两者相差一个 p，所以模 p 同余。
#
# 例如 p = 13、q = 2：
#
#     -2 ≡ 11 (mod 13)
#
# 因此：
#
#     inv[i]
#     =
#     (p - p // i) * inv[p % i] % p
#
# 这正是程序中的递推式。
#
#
# 九、为什么 inv[p % i] 一定已经求出
#
# 对于 i >= 2：
#
#     p % i < i
#
# 所以在计算 inv[i] 时，
# inv[p % i] 对应的下标一定比 i 小。
#
# 程序是按照 i 从小到大计算的：
#
#     inv[1]
#     inv[2]
#     inv[3]
#     ...
#
# 因此 inv[p % i] 已经提前计算完成。
#
# 另外，因为 p 是质数且 i < p，
# i 不可能整除 p，所以：
#
#     p % i != 0
#
# 不会出现访问 inv[0] 的情况。
#
#
# 十、样例计算
#
# 设：
#
#     p = 13
#
# 初始：
#
#     inv[1] = 1
#
# 计算 inv[2]：
#
#     13 // 2 = 6
#     13 % 2 = 1
#
#     inv[2]
#     = (13 - 6) * inv[1] % 13
#     = 7
#
# 验证：
#
#     2 * 7 = 14 ≡ 1 (mod 13)
#
# 计算 inv[5]：
#
#     13 // 5 = 2
#     13 % 5 = 3
#
#     inv[5]
#     = (13 - 2) * inv[3] % 13
#     = 11 * inv[3] % 13
#
# 如果 inv[3] = 9：
#
#     inv[5] = 11 * 9 % 13 = 8
#
# 验证：
#
#     5 * 8 = 40 ≡ 1 (mod 13)
#
#
# 十一、算法流程
#
#     1. 设置 inv[1] = 1；
#     2. 从 i = 2 枚举到 n；
#     3. 计算 p // i 和 p % i；
#     4. 使用已经求出的 inv[p % i]；
#     5. 根据递推公式计算 inv[i]；
#     6. 输出 inv[1] 到 inv[n]。
#
#
# 十二、为什么不用每次快速幂求逆元
#
# 因为 p 是质数，也可以利用费马小定理：
#
#     inv(a) ≡ a^(p - 2) (mod p)
#
# 然后对每个 a 使用快速幂。
#
# 但是这样需要计算 n 次快速幂，
# 时间复杂度约为：
#
#     O(n log p)
#
# 本题的递推公式每个逆元只计算一次，
# 因此总时间复杂度为：
#
#     O(n)
#
# 更适合 n 达到数百万的情况。
#
#
# 十三、代码中的内存优化
#
# inverse 使用：
#
#     array('I')
#
# 而不是 Python 普通列表。
#
# 'I' 表示无符号整数，
# 可以保存本题中的逆元结果，并且比 Python 整数对象列表节省内存。
#
# 输出使用 bytearray：
#
#     out.extend(...)
#     out.extend(b'\n')
#
# 最后一次性写出，减少大量输出调用。
#
#
# 十四、复杂度
#
# 每个 i 只进行常数次运算：
#
#     时间复杂度：O(n)
#
# inverse 数组和输出缓冲区占用线性空间：
#
#     空间复杂度：O(n)
