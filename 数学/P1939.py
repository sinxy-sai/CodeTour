# 矩阵加速(数列)
import sys


MOD = 10**9 + 7

def multiply(A, B):
    C = [[0]*3 for _ in range(3)]
    for i in range(3):
        for k in range(3):
            if A[i][k] == 0:
                continue
            for j in range(3):
                C[i][j] = (C[i][j] + A[i][k] * B[k][j]) % MOD

    return C
                
def matrix_power(A, exp):
    res = [[1,0,0],[0,1,0],[0,0,1]]

    while exp > 0:
        if exp & 1:
            res = multiply(res, A)
        A = multiply(A, A)
        exp >>= 1
    return res

def solve(n):
    if n <= 3:
        return 1
    # 状态
    # 
    # [a_i]
    # [a_(i-1)]
    # [a_(i-2)]
    # 
    # 状态转移
    # 
    # a_(i+1) = a_i + a_(i-2)
    # [a_(i+1),a_(i),a_(i-1)].T = [[1,0,1],[1,0,0],[0,1,0]] * [a_i,a_(i-1),a_(i-2)].T

    transition = [
        [1,0,1],
        [1,0,0],
        [0,1,0]
    ]

    power = matrix_power(transition, n-3)
    return sum(power[0]) % MOD

def main():
    T = int(sys.stdin.buffer.readline())
    out = []
    for _ in range(T):
        n = int(sys.stdin.buffer.readline())
        out.append(str(solve(n)))

    sys.stdout.buffer.write('\n'.join(out).encode())

if __name__ == '__main__':
    main()


# ============================================================
# 矩阵加速数列：数学理论、算法思路与实现细节
# ============================================================
#
# 一、题目中的递推数列
#
# 数列满足：
#
#     a1 = a2 = a3 = 1
#
# 当 n >= 4 时：
#
#     an = a(n-1) + a(n-3)
#
# 直接递推可以依次计算：
#
#     a4 = a3 + a1 = 1 + 1 = 2
#     a5 = a4 + a2 = 2 + 1 = 3
#     a6 = a5 + a3 = 3 + 1 = 4
#
# 但是 n 最大为 2 * 10^9，
# 不可能从 a1 一直递推到 an。
#
# 因此需要把递推过程表示成矩阵乘法，
# 再使用矩阵快速幂。
#
#
# 二、为什么要设计状态
#
# 递推式：
#
#     a(n+1) = an + a(n-2)
#
# 计算下一项 a(n+1) 时，
# 需要知道：
#
#     an
#     a(n-1)
#     a(n-2)
#
# 所以定义状态向量：
#
#     Vn =
#     [  an   ]
#     [ a(n-1)]
#     [ a(n-2)]
#
# 状态中必须保存这三个数，
# 因为只保存 an 和 a(n-1)
# 无法直接得到下一项所需的 a(n-2)。
#
#
# 三、推导状态转移矩阵
#
# 已知：
#
#     Vn =
#     [  an   ]
#     [ a(n-1)]
#     [ a(n-2)]
#
# 下一状态为：
#
#     V(n+1) =
#     [ a(n+1)]
#     [  an   ]
#     [a(n-1)]
#
# 根据递推关系：
#
#     a(n+1) = an + a(n-2)
#
# 第一行可以写成：
#
#     a(n+1) = 1 * an
#            + 0 * a(n-1)
#            + 1 * a(n-2)
#
# 后两行只是把状态整体向下移动：
#
#     an = 1 * an + 0 * a(n-1) + 0 * a(n-2)
#
#     a(n-1) = 0 * an + 1 * a(n-1) + 0 * a(n-2)
#
# 因此：
#
#     V(n+1) = M * Vn
#
# 其中转移矩阵 M 为：
#
#     M =
#     [1 0 1]
#     [1 0 0]
#     [0 1 0]
#
# 代码中的：
#
#     transition = [
#         [1, 0, 1],
#         [1, 0, 0],
#         [0, 1, 0]
#     ]
#
# 就是这个转移矩阵。
#
#
# 四、初始状态
#
# 因为 a1、a2、a3 都等于 1，
# 所以：
#
#     V3 =
#     [a3]
#     [a2]
#     [a1]
#     =
#     [1]
#     [1]
#     [1]
#
# 从 V3 转移到 Vn，
# 一共需要 n - 3 次转移：
#
#     Vn = M^(n-3) * V3
#
# 因此对于 n >= 3：
#
#     an = M^(n-3) * [1, 1, 1]^T 的第一项
#
# n <= 3 时，答案直接为 1，
# 所以代码先进行：
#
#     if n <= 3:
#         return 1
#
#
# 五、为什么使用矩阵快速幂
#
# 直接计算 M^(n-3) 需要做 n-3 次矩阵乘法，
# 复杂度是 O(n)。
#
# 但 n 最大为 2 * 10^9，
# 线性递推会超时。
#
# 矩阵乘法满足结合律：
#
#     (A * B) * C = A * (B * C)
#
# 所以可以使用快速幂：
#
#     M^0 = I
#
#     M^e = (M^(e/2))^2       e 为偶数
#
#     M^e = M^(e//2) * M^(e//2) * M
#           e 为奇数
#
# 通过不断将指数除以 2，
# 复杂度从 O(n) 降为 O(log n)。
#
#
# 六、矩阵快速幂中的 result、A 和 exp
#
# `res` 表示当前已经收集到的答案，
# 初始为单位矩阵 I：
#
#     res = I
#
# `A` 表示当前的幂：
#
#     M, M^2, M^4, M^8, ...
#
# 当 `exp` 的二进制最低位为 1 时，
# 当前的幂需要参与最终结果：
#
#     res = res * A
#
# 然后当前矩阵平方：
#
#     A = A * A
#
# 指数右移一位：
#
#     exp >>= 1
#
#
# 七、`exp & 1` 的数学含义
#
# 一个整数的二进制最低位：
#
#     0 表示偶数；
#     1 表示奇数。
#
# 因此：
#
#     exp & 1
#
# 就是在判断 exp 的最低二进制位。
#
# 例如：
#
#     13 = 1101(二进制)
#     13 & 1 = 1
#
# 所以 13 是奇数。
#
#     12 = 1100(二进制)
#     12 & 1 = 0
#
# 所以 12 是偶数。
#
#
# 八、为什么最终答案是 `sum(power[0])`
#
# 设：
#
#     P = M^(n-3)
#
# 那么：
#
#     Vn = P * V3
#
# 而：
#
#     V3 = [1, 1, 1]^T
#
# 设 P 的第一行为：
#
#     [p0, p1, p2]
#
# 那么 Vn 的第一项为：
#
#     an = p0 * 1 + p1 * 1 + p2 * 1
#       = p0 + p1 + p2
#
# `power[0]` 就是矩阵 P 的第一行：
#
#     power[0] = [p0, p1, p2]
#
# 所以：
#
#     sum(power[0])
#
# 就是：
#
#     an
#
# 代码中的：
#
#     return sum(power[0]) % MOD
#
# 正是在计算这个结果。
#
# 更一般地，如果初始状态不是 [1, 1, 1]^T，
# 就不能直接求第一行的和，
# 而应该计算：
#
#     sum(power[0][j] * initial[j])
#
#
# 九、矩阵乘法
#
# 对两个三阶矩阵 A、B：
#
#     C[i][j] = A[i][0] * B[0][j]
#             + A[i][1] * B[1][j]
#             + A[i][2] * B[2][j]
#
# 代码中的三层循环：
#
#     for i in range(3):
#         for k in range(3):
#             for j in range(3):
#                 C[i][j] += A[i][k] * B[k][j]
#
# 就是在实现矩阵乘法公式。
#
# 如果 A[i][k] 为 0，
# 那么这一项对所有 j 的贡献都是 0，
# 可以直接跳过：
#
#     if A[i][k] == 0:
#         continue
#
#
# 十、为什么可以在运算过程中取模
#
# 题目要求计算：
#
#     an mod MOD
#
# 模运算满足：
#
#     (x + y) mod MOD
#     = ((x mod MOD) + (y mod MOD)) mod MOD
#
#     (x * y) mod MOD
#     = ((x mod MOD) * (y mod MOD)) mod MOD
#
# 因此矩阵乘法中的每一次累加都可以及时取模：
#
#     C[i][j] = (
#         C[i][j] + A[i][k] * B[k][j]
#     ) % MOD
#
# 这样不会改变最终答案，
# 还能避免中间数过大。
#
#
# 十一、算法流程
#
#     1. 如果 n <= 3，直接输出 1；
#     2. 构造三阶转移矩阵 M；
#     3. 计算 M^(n-3)；
#     4. 取结果矩阵第一行；
#     5. 因为初始状态是 [1, 1, 1]^T，
#        所以将第一行三个元素相加；
#     6. 对 MOD 取模并输出。
#
#
# 十二、复杂度
#
# 本题使用的是固定大小的 3 * 3 矩阵。
#
# 一次矩阵乘法需要常数次运算，
# 矩阵快速幂需要 O(log n) 次矩阵乘法。
#
# 因此单次询问的复杂度为：
#
#     O(log n)
#
# T 次询问的总复杂度为：
#
#     O(T log n)
#
# 由于矩阵大小固定为 3，
# 额外空间复杂度为：
#
#     O(1)
